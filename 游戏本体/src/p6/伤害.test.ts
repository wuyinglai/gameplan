import { describe, expect, it } from 'vitest';
import { 攻击倍率表, 整体防护倍率, 结算外伤, 结算内伤, 结算穿甲 } from './伤害';
import type { 防护构成 } from './伤害';

const 纯无甲: 防护构成 = { 无甲: 1, 软甲: 0, 硬甲: 0 };
const 纯软甲: 防护构成 = { 无甲: 0, 软甲: 1, 硬甲: 0 };
const 纯硬甲: 防护构成 = { 无甲: 0, 软甲: 0, 硬甲: 1 };
const 混合示例: 防护构成 = { 无甲: 0.1, 软甲: 0.3, 硬甲: 0.6 }; // 🔴 示例构成（4A §3.3），非正式权重

describe('6B · 6.2 伤害与防御（判据 1~10）', () => {
  it('1 倍率表九格（✅ 4A §3.2 · 2026-10-10 修订值）', () => {
    expect(攻击倍率表.打击).toEqual({ 无甲: 0.9, 软甲: 1.0, 硬甲: 1.3 });
    expect(攻击倍率表.斩击).toEqual({ 无甲: 1.1, 软甲: 1.2, 硬甲: 0.9 });
    expect(攻击倍率表.刺击).toEqual({ 无甲: 1.1, 软甲: 0.9, 硬甲: 0.9 });
  });

  it('2 整体防护倍率 = 构成加权（✅ 4A §3.3：硬60/软30/无10 对斩击 → 1.01）', () => {
    // 0.6×0.9 + 0.3×1.2 + 0.1×1.1 = 0.54 + 0.36 + 0.11 = 1.01
    expect(整体防护倍率('斩击', 混合示例)).toBeCloseTo(1.01, 10);
  });

  it('3 三型对同一构成的倍率互不相同（打击克硬甲、斩击克软甲、刺击两头不吃）', () => {
    expect(整体防护倍率('打击', 纯硬甲)).toBeGreaterThan(整体防护倍率('斩击', 纯硬甲));
    expect(整体防护倍率('斩击', 纯软甲)).toBeGreaterThan(整体防护倍率('打击', 纯软甲));
    expect(整体防护倍率('刺击', 纯软甲)).toBeLessThan(整体防护倍率('斩击', 纯软甲));
    expect(整体防护倍率('刺击', 纯硬甲)).toBeLessThan(整体防护倍率('打击', 纯硬甲));
  });

  it('4 外伤结算顺序：护盾 → 屏障 → 护甲 → 承伤（✅ 4A §3.4）', () => {
    const r = 结算外伤({ 面板: 12, 招式倍数: 1, 角色加成: 0, 攻击类型: '斩击', 构成: 纯无甲, 护盾: 5, 屏障: 3, 护甲: 4 });
    // 12×1.1=13.2→13：盾5(余8)→屏3(余5)→甲4(余1)→承伤1
    expect(r.总伤害).toBe(13);
    expect(r.剩余护盾).toBe(0);
    expect(r.剩余屏障).toBe(0);
    expect(r.剩余护甲).toBe(0);
    expect(r.承伤扣减).toBe(1);
    expect(r.完全吸挡).toBe(false);
  });

  it('5 溢出跨层：斩击25（×1.1=27）vs 盾5/屏3/甲4 → 护甲归零、承伤扣15', () => {
    const r = 结算外伤({ 面板: 25, 招式倍数: 1, 角色加成: 0, 攻击类型: '斩击', 构成: 纯无甲, 护盾: 5, 屏障: 3, 护甲: 4 });
    // 27：盾5(余22)→屏3(余19)→甲4(余15)→承伤15
    expect(r.承伤扣减).toBe(15);
    expect(r.剩余护甲).toBe(0);
    expect(r.完全吸挡).toBe(false);
  });

  it('6 完全吸挡：被甲完全吸收（无溢出）→ 标记 true（✅ 4A §4.5 条目4 → 不施加流血/迟滞）', () => {
    const r = 结算外伤({ 面板: 12, 招式倍数: 1, 角色加成: 0, 攻击类型: '斩击', 构成: 纯无甲, 护盾: 0, 屏障: 0, 护甲: 20 });
    expect(r.承伤扣减).toBe(0);
    expect(r.剩余护甲).toBe(7); // 13 点伤害吃掉 20 甲中的 13
    expect(r.完全吸挡).toBe(true);
  });

  it('7 穿甲：无视护甲（甲不动）· 护盾/屏障仍挡（✅ 4A §3.4 穿甲结算）', () => {
    const r = 结算穿甲({ 面板: 28, 招式倍数: 1, 角色加成: 0, 护盾: 5, 屏障: 3, 护甲: 20 });
    // 28：盾5(余23)→屏3(余20)→直进承伤20
    expect(r.总伤害).toBe(28);
    expect(r.剩余护盾).toBe(0);
    expect(r.剩余屏障).toBe(0);
    expect(r.剩余护甲).toBe(20); // 🔴 穿甲不动护甲
    expect(r.承伤扣减).toBe(20);
  });

  it('8 内伤：无视一切防御直扣承伤（✅ 4A §3），负数/零不产生正扣', () => {
    expect(结算内伤(48, 3)).toBe(3);   // 流血单层 3
    expect(结算内伤(48, 15)).toBe(15);
    expect(结算内伤(5, 12)).toBe(5);   // 余量封顶
    expect(结算内伤(48, 0)).toBe(0);
  });

  it('9 🔴 倍率作用于整次伤害（不分段）：重甲目标吃打击 ×1.3 一直算到承伤', () => {
    // 面板 10 × 1.3 = 13 → 甲 8 挡 8，余 5 进承伤（若只打在甲上则承伤为 0）
    const r = 结算外伤({ 面板: 10, 招式倍数: 1, 角色加成: 0, 攻击类型: '打击', 构成: 纯硬甲, 护盾: 0, 屏障: 0, 护甲: 8 });
    expect(r.总伤害).toBe(13);
    expect(r.承伤扣减).toBe(5);
  });

  it('10 第4A类.12 示例复算：迎击 12 对纯无甲（按斩击 ×1.1 示例）→ 13.2 取整 13', () => {
    const r = 结算外伤({ 面板: 12, 招式倍数: 1, 角色加成: 0, 攻击类型: '斩击', 构成: 纯无甲, 护盾: 0, 屏障: 0, 护甲: 0 });
    expect(r.总伤害).toBe(13);
    expect(r.承伤扣减).toBe(13);
    // 对照：打击对无甲 ×0.9 → 10（"前半场武器"保险丝）
    const 打击版 = 结算外伤({ 面板: 12, 招式倍数: 1, 角色加成: 0, 攻击类型: '打击', 构成: 纯无甲, 护盾: 0, 屏障: 0, 护甲: 0 });
    expect(打击版.总伤害).toBe(10);
  });
});
