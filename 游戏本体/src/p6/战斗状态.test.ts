import { describe, expect, it } from 'vitest';
import type { 敌方单位, 角色快照, 战斗入参 } from './战斗接口';
import { 开始战斗, 进入下一回合, 判定结局, 单位归零 } from './战斗状态';

/** 三角色官方数值（✅ 4A §7：护路人 120 / 荒野射手 70 / 修补师 85） */
function 官方三人(体力 = [50, 50, 50]): 角色快照[] {
  return [
    { 名字: '护路人', 当前生命: 120, 生命上限: 120, 个人体力: 体力[0], 护甲: 0, 技能: [] },
    { 名字: '荒野射手', 当前生命: 70, 生命上限: 70, 个人体力: 体力[1], 护甲: 0, 技能: [] },
    { 名字: '修补师', 当前生命: 85, 生命上限: 85, 个人体力: 体力[2], 护甲: 0, 技能: [] },
  ];
}

function 敌人(名字 = '灰狼', 血 = 60): 敌方单位 {
  return { 名字, 生命上限: 血, 当前生命: 血, 护甲: 0, 护盾: 0, 初始状态: [], 迟滞层数: 0 };
}

function 入参(我方 = 官方三人(), 敌方 = [敌人()]): 战斗入参 {
  return { 我方, 敌方, 难度: '普通', 商队当前耐久: 100, 可用药包: 5, 可用零件: 5 };
}

describe('6B · 6.0 战斗数据与状态机（判据 1~8）', () => {
  it('1 三角色官方数值 + 体力池三行表（✅ 4A:88-92：3人 回复150 上限300 起手=上限）', () => {
    const 状态 = 开始战斗(入参());
    expect(状态.我方.map((u) => u.生命上限)).toEqual([120, 70, 85]);
    expect(状态.体力池).toEqual({ 当前: 300, 上限: 300, 每回合回复: 150 });
    expect(状态.回合).toBe(1);
    expect(状态.结局).toBeNull();
  });

  it('2 个体差异照加（40/60/50 → 回复=Σ=150 · 上限=300）—— 不是 50×3 死乘（✅ 4A:83）', () => {
    const 状态 = 开始战斗(入参(官方三人([40, 60, 50])));
    expect(状态.体力池.每回合回复).toBe(150);
    expect(状态.体力池.上限).toBe(300);
  });

  it('3 🔴 深拷贝：改内部状态不许影响入参原件（快照原则）', () => {
    const 原 = 入参();
    const 留底 = JSON.parse(JSON.stringify(原)) as 战斗入参;
    const 状态 = 开始战斗(原);
    状态.我方[0].当前生命 = 1;
    状态.我方[0].状态.push({ 名字: '流血', 层数: 9 });
    单位归零(状态, 状态.敌方[0]);
    进入下一回合(状态);
    expect(原).toEqual(留底);
  });

  it('4 敌方全部归零 → 胜利', () => {
    const 状态 = 开始战斗(入参());
    单位归零(状态, 状态.敌方[0]);
    expect(判定结局(状态)).toBe('胜利');
  });

  it('5 我方全部归零 → 失败', () => {
    const 状态 = 开始战斗(入参());
    for (const u of 状态.我方) 单位归零(状态, u);
    expect(判定结局(状态)).toBe('失败');
  });

  it('6 双方各有存活 → 战斗继续（null）', () => {
    const 状态 = 开始战斗(入参());
    单位归零(状态, 状态.我方[1]); // 只倒一个
    expect(判定结局(状态)).toBeNull();
  });

  it('7 单位归零 → 已退出 + 本场重伤次数 +1（✅ 4A:641/643）', () => {
    const 状态 = 开始战斗(入参());
    const 射手 = 状态.我方[1];
    单位归零(状态, 射手);
    expect(射手.已退出).toBe(true);
    expect(射手.本场重伤次数).toBe(1);
    单位归零(状态, 射手); // 同一人再归零（假设被拉起后再倒）→ 次数继续累计
    expect(射手.本场重伤次数).toBe(2);
  });

  it('8 进入下一回合 → 回合+1 · 体力回复封顶上限 · 敌我护盾都清零（✅ 4A:170/281）', () => {
    const 状态 = 开始战斗(入参());
    状态.体力池.当前 = 280;                       // 花掉一点
    状态.我方[0].护盾 = 12;
    状态.敌方[0].护盾 = 8;
    进入下一回合(状态);
    expect(状态.回合).toBe(2);
    expect(状态.体力池.当前).toBe(300);            // 280+150 封顶 300
    expect(状态.我方[0].护盾).toBe(0);
    expect(状态.敌方[0].护盾).toBe(0);
    // 攒不住超额：当前=200 → 200+150 也封顶 300（攒的价值=集火，不是变多 · 4A:98）
    状态.体力池.当前 = 200;
    进入下一回合(状态);
    expect(状态.体力池.当前).toBe(300);
  });
});
