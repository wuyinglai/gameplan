/** 撤退修正要用：敌方单位的迟滞层数（✅ 4A:527 敌方平均迟滞提高逃跑成功率） */
export interface 敌方单位 {
  名字: string;
  生命上限: number;
  当前生命: number;
  /** 护甲值（✅ 4A §4.5 只由防具提供；敌方同理 §5.0 对等原则） */
  护甲: number;
  /** 护盾值（✅ 4A §4.4 只由盾牌提供） */
  护盾: number;
  /** 开战时自带的初始状态（如无则空数组；🟡 状态枚举施工图 §6.3 定） */
  初始状态: string[];
  /** 迟滞层数（撤退成功率修正用；✅ 4A:527） */
  迟滞层数: number;
}

/** 我方一名角色的快照 —— 战斗只读它，不改原件（🔴 快照进、战果出） */
export interface 角色快照 {
  名字: string;
  当前生命: number;
  生命上限: number;
  /** ✅ 4A §2.2：每人基准 50、有个体差异 —— 全队池 = 各人相加，不是 50×人数 */
  个人体力: number;
  /** 🟡 护甲等装具数值来自 6A 装备系统（未建）—— 先带数值，来源由调用方保证 */
  护甲: number;
  /** 🟡 技能卡池先带名字；卡牌效果 6.1 起在战斗内部定义（4A §2.3 起手 3 张） */
  技能: string[];
}

/** ✅ 4A §8.1 三档（2026-09-20 统一口径） */
export type 战斗难度 = '普通' | '精英' | 'Boss';

/** 🔴 入口契约：战斗开始前，主流程交给战斗的东西 */
export interface 战斗入参 {
  我方: 角色快照[];
  敌方: 敌方单位[];
  难度: 战斗难度;
  /** ✅ 3A：商队当前总耐久（战斗会损耗；损耗量见 战斗结果.耐久损耗） */
  商队当前耐久: number;
  /** ✅ 4A §4.5 / §7.3：战斗内回血只靠药包；修补师技能耗零件 */
  可用药包: number;
  可用零件: number;
  /** ✅ 4A §9.1：Boss 战默认不能普通逃跑（剧情允许的 25%~35%）—— 标记位 */
  剧情允许Boss逃跑?: boolean;
}

