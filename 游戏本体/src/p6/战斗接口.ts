/** ✅ 4A §10（→ 6A §7.2）：四级 —— 重伤 → 加重 → 再加重 → 严重重伤 */
export type 重伤等级 = '无' | '重伤' | '加重' | '再加重' | '严重重伤';

/** 一名角色的战果（只报事实，怎么落账由主流程） */
export interface 角色战果 {
  名字: string;
  结束生命: number;
  /** 本场结束时该角色所处档位（✅ 4A:643-646 四级表） */
  重伤: 重伤等级;
  /** 🔴 第 4 次重伤 = 严重重伤 = 全部失去战斗力（✅ 4A:646 · 铁律 21） */
  失去战斗力: boolean;
}

/** ✅ 4A §9.1：撤退成功 / 战败 / 胜利 三种收场（撤退失败只是中途，最终必归三者之一） */
export type 战斗结局 = '胜利' | '失败' | '撤退成功';

/** 🔴 出口契约：战斗结束交回主流程的东西（全部是数据，不直接扣任何全局状态） */
export interface 战斗结果 {
  结局: 战斗结局;
  回合数: number;
  我方: 角色战果[];
  /** 负数 = 下降。✅ 撤退 = −1（4A:534）；🔴 胜/败的士气变化 ⚠️ 全库未见出处 → 待裁定㉕ */
  士气变化: number;
  /** ✅ 4A §8.2：普通约 −5 · 精英约 −10 · Boss −50 以上（🟡「每车」与 3A 总耐久口径施工图时对齐） */
  耐久损耗: number;
  用掉药包: number;
  用掉零件: number;
  /** 🟡 拾取先只给数据清单；入包/入账由主流程 */
  拾取: Array<{ 名字: string; 数量: number }>;
  /** 撤退尝试次数（0 = 没试过撤退；✅ 4A:517 第 3 回合起才判定） */
  撤退尝试次数: number;
}

