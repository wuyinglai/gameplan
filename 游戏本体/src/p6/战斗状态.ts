import type { 角色快照, 敌方单位, 战斗入参, 战斗难度 } from './战斗接口';
import type { 卡牌 } from './卡牌'; // 仅类型（卡牌.ts 也仅类型引用本文件 —— 无运行时循环）

// ---------------------------------------------------------------------------
// 数据结构
