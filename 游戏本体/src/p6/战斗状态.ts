/** ✅ 4A:641 敌方全部退出=胜利 · 我方全部退出=失败；否则战斗继续 */
export function 判定结局(状态: 战斗状态): '胜利' | '失败' | null {
  const 敌方全灭 = 状态.敌方.length > 0 && 状态.敌方.every((u) => u.已退出);
  if (敌方全灭) return '胜利';
  const 我方全灭 = 状态.我方.length > 0 && 状态.我方.every((u) => u.已退出);
  if (我方全灭) return '失败';
  return null;
}

/**
 * 回合切换：回合 +1 · 体力池回复（封顶上限）· 双方护盾清零。
 * ✅ 4A:170/281 护盾回合末清空（对等原则：敌方护盾同样清）。
 * 🔴 状态 tick（灼烧/灰蚀）6.3 接入 —— 本批不动 状态[]。
 */
export function 进入下一回合(状态: 战斗状态): void {
  状态.回合 += 1;
  状态.体力池.当前 = Math.min(状态.体力池.上限, 状态.体力池.当前 + 状态.体力池.每回合回复);
  for (const u of [...状态.我方, ...状态.敌方]) {
    u.护盾 = 0;
  }
  状态.手牌 = []; // ✅ 4A:113 手牌每回合清空（防「再抽牌」变囤牌引擎）
}

/**
 * ✅ 4A:641/643 生命归零 → 退出本场并计入重伤次数。
 * 🔴 敌方死亡触发的逃跑意愿累计（4A:561-563 队友死+10/精英死+30/Boss死+50）—— 6.4 敌方AI.ts 接钩子。
 */
export function 单位归零(状态: 战斗状态, 单位: 单位): void {
  void 状态; // 钩子位：6.4 在此通知敌方AI
  单位.已退出 = true;
  单位.本场重伤次数 += 1;
}
