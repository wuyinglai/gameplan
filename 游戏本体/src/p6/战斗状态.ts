export type 阵营 = '我方' | '敌方';

/** 状态实例 —— 6.3 起具体化（标记/流血/灼烧/迟滞/反击/蓄力/狂化/灰蚀） */
export interface 状态实例 {
  名字: string;
  层数: number;
}

/** 单位（敌我同构 —— ✅ 4A:287 对等原则：一套结构、一套结算，不为敌人另写） */
export interface 单位 {
  名字: string;
  阵营: 阵营;
  当前生命: number;
  生命上限: number;
  /** ✅ 4A:273 开战赋值 · 战内只减不增 · 归零=防具报废转「无甲」档（档判定在 6.2 伤害.ts） */
  护甲: number;
  /** ✅ 4A:170 开战为 0 · 回合末清空 · 可给任意队友叠（叠盾动作 6.1 起） */
  护盾: number;
  /** ✅ 4A:641 生命归零 → 退出当前战斗（重伤状态） */
  已退出: boolean;
  /** ✅ 4A:643-646 本场内归零一次 +1；跨场累计与四级定级在 战后.ts（6.5）*/
  本场重伤次数: number;
  状态: 状态实例[];
}

/** ✅ 4A:78-92 全队共享体力池（仅我方使用；敌方行动不吃这个池） */
export interface 体力池 {
  当前: number;
  上限: number;
  每回合回复: number;
}

export interface 战斗状态 {
  /** 从 1 开始 */
  回合: number;
  难度: 战斗难度;
  我方: 单位[];
  敌方: 单位[];
  体力池: 体力池;
  药包剩余: number;
  零件剩余: number;
  商队耐久: number;
  撤退尝试次数: number;
  /** ✅ 4A:113 手牌回合末清空（由 进入下一回合 强制执行）；回合内打完可再抽 */
  手牌: 卡牌[];
  /** 6.0 只判 胜/败；撤退成功 6.5 起 */
  结局: null | '胜利' | '失败' | '撤退成功';
  /** 🟡 判定类逻辑（撤退/迟滞/敌方AI）的可注入随机种子 —— 保证测试可复现 */
  随机种子: number;
}

// ---------------------------------------------------------------------------
// 构造
// ---------------------------------------------------------------------------

/** 个人体力的缺省值 —— ✅ 4A:82 每人基准 50（有个体差异，快照可覆盖） */
export const 体力基准 = 50;

function 我方单位(快照: 角色快照): 单位 {
  return {
    名字: 快照.名字,
    阵营: '我方',
    当前生命: 快照.当前生命,
    生命上限: 快照.生命上限,
    护甲: 快照.护甲,
    护盾: 0, // ✅ 4A:170 开战为 0
    已退出: false,
    本场重伤次数: 0,
    状态: [],
  };
}

function 敌方单位转(敌方: 敌方单位): 单位 {
  return {
    名字: 敌方.名字,
    阵营: '敌方',
    当前生命: 敌方.当前生命,
    生命上限: 敌方.生命上限,
    护甲: 敌方.护甲,
    护盾: 0,
    已退出: false,
    本场重伤次数: 0,
    状态: 敌方.初始状态.map((名字) => ({ 名字, 层数: 1 })),
  };
}

/**
 * 🔴 快照进（接口契约）：深拷贝入参 → 内部状态。之后内部怎么改都不许碰入参原件。
 * 体力池 ✅ 4A:78-92：回复 = Σ个人体力（缺省 50，个体差异照加）· 上限 = 2×回复 · 起手 = 上限。
 */
export function 开始战斗(入参: 战斗入参): 战斗状态 {
  const 每回合回复 = 入参.我方.reduce((和, 角色) => 和 + (角色.个人体力 || 体力基准), 0);
  const 上限 = 每回合回复 * 2; // ✅ 4A:85 上限 = 2 倍回复（3 人 150/300 · 4 人 200/400）
  return {
    回合: 1,
    难度: 入参.难度,
    我方: 入参.我方.map(我方单位),
    敌方: 入参.敌方.map(敌方单位转),
    体力池: { 当前: 上限, 上限, 每回合回复 }, // ✅ 4A:86 起手 = 上限（满）
    药包剩余: 入参.可用药包,
    零件剩余: 入参.可用零件,
    商队耐久: 入参.商队当前耐久,
    撤退尝试次数: 0,
    手牌: [],
    结局: null,
    随机种子: 1,
  };
}

