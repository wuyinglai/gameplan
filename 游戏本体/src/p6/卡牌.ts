// ---------------------------------------------------------------------------
// 零耗硬约束（✅ 4A:130-137）—— 定义期校验，违规牌不许进池
// ---------------------------------------------------------------------------

/** 零体力卡禁止的「强负面」（✅ 4A:135 灼烧 / 强迟滞） */
const 零耗禁施状态 = new Set(['灼烧', '迟滞', '灰蚀']);

/** 校验一张牌是否满足零耗硬约束。返回 null=合法，否则返回违规原因。 */
export function 校验零耗约束(卡: 卡牌): string | null {
  if (卡.体力 !== 0) return null;
  if ((卡.效果.伤害 ?? 0) > 0) return '零体力卡禁止伤害（4A:132）';
  if ((卡.效果.抽牌数 ?? 0) > 0) return '零体力卡禁止抽牌/加手牌（4A:134）';
  for (const s of 卡.效果.施加状态 ?? []) {
    if (零耗禁施状态.has(s.名字)) return `零体力卡禁止强负面「${s.名字}」（4A:135）`;
  }
  return null;
}

// ---------------------------------------------------------------------------
// 抽牌（✅ 4A:111-112：每人 2 动作 + 1 记忆 · 从自己牌池自由选 · 选完即定）
// 回合内可以「打完再抽」（重复多少遍都合法）—— 唯一闸门是体力池
// ---------------------------------------------------------------------------

export interface 抽牌结果 {
  成功: boolean;
  原因: string | null;
  手牌: 卡牌[];
}

export function 抽一手(牌池: 卡牌[], 选择: string[]): 抽牌结果 {
  const 失败 = (原因: string): 抽牌结果 => ({ 成功: false, 原因, 手牌: [] });
  if (选择.length !== 3) return 失败('起手必须是 3 张（2 动作 + 1 记忆 · 4A:111）');
  const 抽出的: 卡牌[] = [];
  for (const 名字 of 选择) {
    const 找到 = 牌池.find((c) => c.名字 === 名字);
    if (!找到) return 失败(`「${名字}」不在该角色牌池里`);
    抽出的.push(找到);
  }
  const 动作数 = 抽出的.filter((c) => c.层 === '动作卡').length;
  if (动作数 !== 2) return 失败('必须是 2 张动作卡 + 1 张记忆卡（4A:111）');
  return { 成功: true, 原因: null, 手牌: 抽出的 };
}

// ---------------------------------------------------------------------------
// 出牌闸门（✅ 4A:112-114：出牌无上限 · 体力当闸门 · 手牌里的牌才能出）
// ---------------------------------------------------------------------------

export interface 出牌结果 {
  成功: boolean;
  原因: string | null;
  剩余体力: number;
}

/**
 * 出一张牌：检查（在手牌 · 体力够 · 消耗品够）→ 扣体力与消耗品 → 移出手牌。
 * 🔴 效果的「应用」（伤害/护盾/状态）从 6.2 起 —— 本函数只管闸门与代价。
 */
export function 出牌(状态: 战斗状态, 名字: string): 出牌结果 {
  const 失败 = (原因: string): 出牌结果 => ({ 成功: false, 原因, 剩余体力: 状态.体力池.当前 });
  const 位置 = 状态.手牌.findIndex((c) => c.名字 === 名字);
  if (位置 < 0) return 失败('这张牌不在手牌里');
  const 卡 = 状态.手牌[位置];
  if (状态.体力池.当前 < 卡.体力) return 失败('体力不够（4A:114 体力当闸门）');
  const 耗 = 卡.效果.使用消耗品 ?? {};
  if ((耗.药包 ?? 0) > 状态.药包剩余) return 失败('药包不够');
  if ((耗.零件 ?? 0) > 状态.零件剩余) return 失败('零件不够');
  // —— 全过，扣代价 ——
  状态.体力池.当前 -= 卡.体力;
  状态.药包剩余 -= 耗.药包 ?? 0;
  状态.零件剩余 -= 耗.零件 ?? 0;
  状态.手牌.splice(位置, 1);
  return { 成功: true, 原因: null, 剩余体力: 状态.体力池.当前 };
}

// ---------------------------------------------------------------------------
// 直接使用消耗品（✅ 4A:139-147：与出牌共用同一个体力池）
// ---------------------------------------------------------------------------

export function 用消耗品(状态: 战斗状态, 种类: '药包' | '零件'): 出牌结果 {
  const 失败 = (原因: string): 出牌结果 => ({ 成功: false, 原因, 剩余体力: 状态.体力池.当前 });
  if (状态.体力池.当前 < 25) return 失败('体力不够（消耗品 25 点 · 4A:143）');
  if (种类 === '药包' && 状态.药包剩余 < 1) return 失败('药包不够');
  if (种类 === '零件' && 状态.零件剩余 < 1) return 失败('零件不够');
  状态.体力池.当前 -= 25; // ✅ 4A:143-144 药包 25 · 零件 25
  if (种类 === '药包') 状态.药包剩余 -= 1;
  else 状态.零件剩余 -= 1;
  return { 成功: true, 原因: null, 剩余体力: 状态.体力池.当前 };
}
