export type 牌层 = '动作卡' | '记忆卡'; // ✅ 4A:117-122 卡牌双层

/** 体力五档 ✅ 4A:66-72：微0 / 轻25 / 标准50 / 重100 / 极限150 */
export type 体力档 = 0 | 25 | 50 | 100 | 150;

/** 效果数据 —— 6.2（伤害/护甲）与 6.3（状态）起消费；6.1 只做闸门 */
export interface 卡牌效果 {
  /** >0 即「攻击牌」（零耗硬约束用）· 类型：普通=走倍率表与防御层，穿甲=无视护甲（✅ 4A:253） */
  伤害?: number;
  伤害类型?: '普通' | '穿甲';
  护盾?: { 自己?: number; 全队每人?: number; 货车?: number };
  施加状态?: Array<{ 名字: string; 层数: number; 给目标?: boolean }>;
  移除状态层数?: Array<{ 名字: string; 最多层数: number }>;
  恢复生命倍率?: number;      // 如 简易治疗 ×1.5
  修耐久?: number;            // 车体修理 12
  补甲?: number;              // 紧急加固 12
  抽牌数?: number;            // 灰烬治疗 +1 —— 🔴 体力=0 的牌有此字段即违规
  使用消耗品?: { 药包?: number; 零件?: number };
  备注?: string;              // 未结构化效果（承担50% / 翻倍 / 返体力等）→ 6.2/6.3 落地
}

export interface 卡牌 {
  名字: string;
  归属: string;               // 角色名
  层: 牌层;
  体力: 体力档;
  效果: 卡牌效果;
  /** A类出处行号（如 6A:50） */
  出处: string;
}

