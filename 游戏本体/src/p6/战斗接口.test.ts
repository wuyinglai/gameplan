import { describe, expect, it } from 'vitest';
import type { 敌方单位, 角色快照, 战斗入参, 战斗结果 } from './战斗接口';
import { 进行战斗 } from './战斗接口';

/** 三角色按 4A §7 的官方数值造快照（护路人 120 / 荒野射手 70 / 修补师 85） */
function 官方三人(): 角色快照[] {
  return [
    { 名字: '护路人', 当前生命: 120, 生命上限: 120, 个人体力: 50, 护甲: 0, 技能: ['迎击', '掩护', '重击'] },
    { 名字: '荒野射手', 当前生命: 70, 生命上限: 70, 个人体力: 50, 护甲: 0, 技能: ['标记', '精确射击', '放血箭'] },
    { 名字: '修补师', 当前生命: 85, 生命上限: 85, 个人体力: 50, 护甲: 0, 技能: ['简易治疗', '车体修理', '过载'] },
  ];
}

function 一个敌人(): 敌方单位 {
  return { 名字: '灰狼', 生命上限: 60, 当前生命: 60, 护甲: 0, 护盾: 0, 初始状态: [], 迟滞层数: 0 };
}

function 标准入参(): 战斗入参 {
  return {
    我方: 官方三人(),
    敌方: [一个敌人()],
    难度: '普通',
    商队当前耐久: 100,
    可用药包: 5,
    可用零件: 5,
  };
}

describe('6B 接口先行批 · 契约判据', () => {
  it('1 进行战斗() 返回「未实现」标记（内核 6.0 起实现，不许抛错）', () => {
    const 返回 = 进行战斗(标准入参());
    expect(返回).toEqual({ 未实现: true, 说明: expect.stringContaining('6.0') });
  });

  it('2 🔴 入参零改动 —— 快照原则：接口不许偷改主流程传进来的任何对象', () => {
    const 入参 = 标准入参();
    const 原样 = JSON.parse(JSON.stringify(入参)) as 战斗入参; // 深拷贝留底
    进行战斗(入参);
    expect(入参).toEqual(原样);
    // 顺带钉住引用没被换：还是原来那几个对象
    expect(入参.我方[0].名字).toBe('护路人');
  });

  it('3 类型能表达 4A §7 三角色官方数值（120 / 70 / 85）', () => {
    const 三人 = 官方三人();
    expect(三人.map((r) => r.生命上限)).toEqual([120, 70, 85]);
  });

  it('4 类型能表达完整战果（胜负/撤退三收场 · 士气/耐久/药包零件/拾取全字段）', () => {
    // 只做类型自查 + 字段齐全断言，不预设数值 —— 数值判据归 6.x 各批
    const 样例: 战斗结果 = {
      结局: '撤退成功', 回合数: 3,
      我方: [{ 名字: '护路人', 结束生命: 90, 重伤: '无', 失去战斗力: false }],
      士气变化: -1, 耐久损耗: 5, 用掉药包: 0, 用掉零件: 0, 拾取: [], 撤退尝试次数: 1,
    };
    expect(样例.结局).toBe('撤退成功');
    expect(Object.keys(样例).sort()).toEqual(
      ['士气变化', '回合数', '结局', '拾取', '撤退尝试次数', '我方', '用掉零件', '用掉药包', '耐久损耗'].sort(),
    );
  });
});
