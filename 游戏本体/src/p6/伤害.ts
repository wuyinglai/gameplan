// ---------------------------------------------------------------------------
// 类型与倍率表
// ---------------------------------------------------------------------------

export type 防护类型 = '无甲' | '软甲' | '硬甲';
export type 攻击类型 = '打击' | '斩击' | '刺击';

/** 🔴 防护构成：五部位按权重加权后的整体构成，三项合计 = 1（占比由装备数据决定 → ㉛①） */
export interface 防护构成 {
  无甲: number;
  软甲: number;
  硬甲: number;
}

/** ✅ 4A §3.2 倍率表（2026-10-10 修订值）· 表值 = 对单一纯构成的基础倍率，混合构成按构成加权 */
export const 攻击倍率表: Record<攻击类型, Record<防护类型, number>> = {
  打击: { 无甲: 0.9, 软甲: 1.0, 硬甲: 1.3 },
  斩击: { 无甲: 1.1, 软甲: 1.2, 硬甲: 0.9 },
  刺击: { 无甲: 1.1, 软甲: 0.9, 硬甲: 0.9 },
};

// ---------------------------------------------------------------------------
// 防护构成加权（✅ 4A §3.3）
// ---------------------------------------------------------------------------

/** 整体防护倍率 = 硬甲占比×硬甲倍率 + 软甲占比×软甲倍率 + 无甲占比×无甲倍率 */
export function 整体防护倍率(攻击: 攻击类型, 构成: 防护构成): number {
  const 表 = 攻击倍率表[攻击];
  return 构成.硬甲 * 表.硬甲 + 构成.软甲 * 表.软甲 + 构成.无甲 * 表.无甲;
}

// ---------------------------------------------------------------------------
// 外伤结算（✅ 4A §3.4：扣血之前全部算完 → 护盾 → 屏障 → 护甲 → 承伤）
// ---------------------------------------------------------------------------

export interface 外伤输入 {
  /** 攻击基础值（武器面板 × 招式倍数；记忆卡直接给定值如迎击 12） */
  面板: number;
  /** 招式倍数（武器招式 ×1.0/×1.5…；记忆卡独立招式 = 1） */
  招式倍数: number;
  /** 角色加成小数（0.15 = +15%；🔴 力量×技巧加权构成 → 待裁定㉝，本版传 0） */
  角色加成: number;
  攻击类型: 攻击类型;
  构成: 防护构成;
  护盾: number;
  屏障: number;
  护甲: number;
}

export interface 结算结果 {
  /** 扣减前的整次伤害（🔴 倍率作用于整次伤害，一直算到承伤，不分段） */
  总伤害: number;
  剩余护盾: number;
  剩余屏障: number;
  剩余护甲: number;
  /** 实际扣掉的承伤（累计伤害上限的扣减量） */
  承伤扣减: number;
  /** ✅ 4A §4.5 条目4：被甲完全吸收（无溢出到承伤）→ 不施加流血/迟滞 */
  完全吸挡: boolean;
}

/** 外伤结算：三层防御依次抵扣，溢出进承伤。🟡 取整 = 向下（第4A类.12 示例口径 13.2→13，未在 4A 写死） */
export function 结算外伤(i: 外伤输入): 结算结果 {
  const 倍率 = 整体防护倍率(i.攻击类型, i.构成);
  const 总伤害 = Math.floor(i.面板 * i.招式倍数 * (1 + i.角色加成) * 倍率);
  let 余 = 总伤害;
  let 盾 = i.护盾;
  let 屏 = i.屏障;
  let 甲 = i.护甲;
  const 扣盾 = Math.min(盾, 余); 盾 -= 扣盾; 余 -= 扣盾;
  const 扣屏 = Math.min(屏, 余); 屏 -= 扣屏; 余 -= 扣屏;
  const 扣甲 = Math.min(甲, 余); 甲 -= 扣甲; 余 -= 扣甲;
  return {
    总伤害,
    剩余护盾: 盾,
    剩余屏障: 屏,
    剩余护甲: 甲,
    承伤扣减: 余,
    完全吸挡: 余 === 0 && 总伤害 > 0,
  };
}

// ---------------------------------------------------------------------------
// 穿甲（✅ 4A §3.4：护盾 → 屏障 → 承伤，无视护甲，不吃倍率表）
// ---------------------------------------------------------------------------

export interface 穿甲输入 {
  面板: number;
  招式倍数: number;
  角色加成: number;
  护盾: number;
  屏障: number;
  /** 目标当前护甲（穿甲不碰它，原样回显） */
  护甲: number;
}

/** 穿甲结算：不吃攻击类型倍率表，无视护甲层 */
export function 结算穿甲(i: 穿甲输入): 结算结果 {
  const 总伤害 = Math.floor(i.面板 * i.招式倍数 * (1 + i.角色加成));
  let 余 = 总伤害;
  let 盾 = i.护盾;
  let 屏 = i.屏障;
  const 扣盾 = Math.min(盾, 余); 盾 -= 扣盾; 余 -= 扣盾;
  const 扣屏 = Math.min(屏, 余); 屏 -= 扣屏; 余 -= 扣屏;
  return {
    总伤害,
    剩余护盾: 盾,
    剩余屏障: 屏,
    剩余护甲: i.护甲, // 🔴 穿甲不动护甲
    承伤扣减: 余,
    完全吸挡: 余 === 0 && 总伤害 > 0,
  };
}

// ---------------------------------------------------------------------------
// 内伤（✅ 4A §3：不可被防御阻挡，无视护盾/护甲/屏障，直接扣承伤）
// ---------------------------------------------------------------------------

/** 内伤直接扣承伤（流血结算、过载反噬等走这里）；返回实际扣减（不低于 0） */
export function 结算内伤(当前承伤余量: number, 点数: number): number {
  return Math.min(当前承伤余量, Math.max(0, 点数));
}
