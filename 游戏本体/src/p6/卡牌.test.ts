import { describe, expect, it } from 'vitest';
import type { 卡牌, 卡牌效果 } from './卡牌';
import { 官方记忆卡池, 出牌, 抽一手, 用消耗品, 校验零耗约束 } from './卡牌';
import type { 战斗入参 } from './战斗接口';
import { 开始战斗, 进入下一回合 } from './战斗状态';

function 三人入参(): 战斗入参 {
  return {
    我方: [
      { 名字: '护路人', 当前生命: 120, 生命上限: 120, 个人体力: 50, 护甲: 0, 技能: [] },
      { 名字: '荒野射手', 当前生命: 70, 生命上限: 70, 个人体力: 50, 护甲: 0, 技能: [] },
      { 名字: '修补师', 当前生命: 85, 生命上限: 85, 个人体力: 50, 护甲: 0, 技能: [] },
    ],
    敌方: [{ 名字: '灰狼', 生命上限: 60, 当前生命: 60, 护甲: 0, 护盾: 0, 初始状态: [], 迟滞层数: 0 }],
    难度: '普通', 商队当前耐久: 100, 可用药包: 5, 可用零件: 5,
  };
}

/** 构造一张动作卡（⚠️ 官方动作卡数值待裁定㉖ —— 测试用构造牌验证机制） */
function 动作卡(名字: string, 归属: string, 体力: 0 | 25 | 50 | 100 | 150, 效果: 卡牌效果): 卡牌 {
  return { 名字, 归属, 层: '动作卡', 体力, 效果, 出处: '测试构造' };
}

describe('6B · 6.1 卡牌与出牌（判据 1~10）', () => {
  it('1 官方记忆卡池 19 张 · 体力档照抄 6A（标记0 / 重击100 / 简易治疗25 / 过载100）', () => {
    const 总数 = Object.values(官方记忆卡池).reduce((n, 池) => n + 池.length, 0);
    expect(总数).toBe(19); // 护路人6 + 荒野射手6 + 修补师7（✅ 6A §2.1/§3.1/§4.1）
    expect(官方记忆卡池.荒野射手.find((c) => c.名字 === '标记')?.体力).toBe(0);
    expect(官方记忆卡池.护路人.find((c) => c.名字 === '重击')?.体力).toBe(100);
    expect(官方记忆卡池.修补师.find((c) => c.名字 === '简易治疗')?.体力).toBe(25);
    expect(官方记忆卡池.修补师.find((c) => c.名字 === '过载')?.体力).toBe(100);
  });

  it('2 🔴 零耗硬约束（✅ 4A:130-137）：标记合法；0费伤害/0费抽牌/0费强负面全部违规', () => {
    expect(校验零耗约束(官方记忆卡池.荒野射手[0])).toBeNull(); // 标记（0费·1层标记·轻度负面）
    const 零费伤害 = 动作卡('坏牌', '测试', 0, { 伤害: 1 });
    expect(校验零耗约束(零费伤害)).toContain('禁止伤害');
    const 零费抽牌 = 动作卡('坏牌2', '测试', 0, { 抽牌数: 2 });
    expect(校验零耗约束(零费抽牌)).toContain('禁止抽牌');
    const 零费灼烧 = 动作卡('坏牌3', '测试', 0, { 施加状态: [{ 名字: '灼烧', 层数: 1, 给目标: true }] });
    expect(校验零耗约束(零费灼烧)).toContain('强负面');
  });

  it('3 抽一手：2 动作 + 1 记忆（✅ 4A:111）· 3 记忆 → 拒绝', () => {
    const 射手池 = [
      ...官方记忆卡池.荒野射手,
      动作卡('射击', '荒野射手', 50, { 伤害: 6, 伤害类型: '普通' }),
      动作卡('轻格挡', '荒野射手', 25, { 护盾: { 自己: 3 } }),
    ];
    const 好 = 抽一手(射手池, ['射击', '轻格挡', '标记']);
    expect(好.成功).toBe(true);
    expect(好.手牌.map((c) => c.名字)).toEqual(['射击', '轻格挡', '标记']);
    const 坏 = 抽一手(射手池, ['标记', '精确射击', '放血箭']);
    expect(坏.成功).toBe(false);
    expect(坏.原因).toContain('2 张动作卡');
  });

  it('4 抽的牌必须在该角色牌池里（护路人的牌不能给射手抽）', () => {
    const 射手池 = [
      ...官方记忆卡池.荒野射手,
      动作卡('射击', '荒野射手', 50, { 伤害: 6 }),
      动作卡('轻格挡', '荒野射手', 25, { 护盾: { 自己: 3 } }),
    ];
    const 坏 = 抽一手(射手池, ['射击', '轻格挡', '迎击']); // 迎击是护路人的记忆卡
    expect(坏.成功).toBe(false);
    expect(坏.原因).toContain('不在该角色牌池');
  });

  it('5 出牌扣体力：迎击 50（300 → 250）· 卡移出手牌', () => {
    const 状态 = 开始战斗(三人入参());
    状态.手牌 = [官方记忆卡池.护路人[0]]; // 迎击
    const r = 出牌(状态, '迎击');
    expect(r).toEqual({ 成功: true, 原因: null, 剩余体力: 250 });
    expect(状态.手牌).toHaveLength(0);
  });

  it('6 体力不够 → 拒绝且状态一点没变（✅ 4A:114 体力当闸门）', () => {
    const 状态 = 开始战斗(三人入参());
    状态.体力池.当前 = 40;
    状态.手牌 = [官方记忆卡池.护路人[4]]; // 重击 100
    const r = 出牌(状态, '重击');
    expect(r.成功).toBe(false);
    expect(r.原因).toContain('体力不够');
    expect(状态.体力池.当前).toBe(40);
    expect(状态.手牌).toHaveLength(1);
  });

  it('7 🔴 出牌无上限（✅ 4A:112）：连打到体力耗尽为止 —— 3 张标准+2张轻后第6张被拒', () => {
    const 状态 = 开始战斗(三人入参()); // 300 体力
    状态.手牌 = [
      官方记忆卡池.护路人[0], // 迎击 50
      官方记忆卡池.荒野射手[1], // 精确射击 50
      官方记忆卡池.荒野射手[2], // 放血箭 50
      官方记忆卡池.修补师[0], // 简易治疗 25
      官方记忆卡池.修补师[2], // 车体修理 25
      官方记忆卡池.护路人[4], // 重击 100
    ];
    expect(出牌(状态, '迎击').剩余体力).toBe(250);
    expect(出牌(状态, '精确射击').剩余体力).toBe(200);
    expect(出牌(状态, '放血箭').剩余体力).toBe(150);
    expect(出牌(状态, '简易治疗').剩余体力).toBe(125);
    expect(出牌(状态, '车体修理').剩余体力).toBe(100);
    expect(出牌(状态, '重击').成功).toBe(true); // 正好花光
    expect(状态.体力池.当前).toBe(0);
    const 再来 = 官方记忆卡池.荒野射手[3]; // 断筋箭 50
    状态.手牌.push(再来);
    expect(出牌(状态, '断筋箭').原因).toContain('体力不够');
  });

  it('8 消耗品：药包/零件各 25 体力（✅ 4A:143-144）· 数量不足拒绝', () => {
    const 状态 = 开始战斗(三人入参());
    expect(用消耗品(状态, '药包')).toMatchObject({ 成功: true, 剩余体力: 275 });
    expect(状态.药包剩余).toBe(4);
    expect(用消耗品(状态, '零件').剩余体力).toBe(250);
    expect(状态.零件剩余).toBe(4);
    状态.药包剩余 = 0;
    expect(用消耗品(状态, '药包').原因).toContain('药包不够');
  });

  it('9 消耗品记忆卡：简易治疗要药包（6A:80）· 药包不够 → 出牌被拒', () => {
    const 状态 = 开始战斗(三人入参());
    状态.药包剩余 = 0;
    状态.手牌 = [官方记忆卡池.修补师[0]];
    const r = 出牌(状态, '简易治疗');
    expect(r.成功).toBe(false);
    expect(r.原因).toContain('药包不够');
    expect(状态.体力池.当前).toBe(300); // 体力没扣
  });

  it('10 🔴 手牌回合末清空（✅ 4A:113）—— 进入下一回合后手牌归零', () => {
    const 状态 = 开始战斗(三人入参());
    状态.手牌 = [官方记忆卡池.护路人[0], 官方记忆卡池.护路人[1]];
    进入下一回合(状态);
    expect(状态.手牌).toEqual([]);
  });
});
