// 🔴 展示 6.0+6.1 的机制：快照进场 → 抽牌规则 → 出牌（体力闸门）→ 回合切换
//    （体力回复/护盾清空/手牌清空）→ 敌方归零 → 胜利判定。
//    伤害结算在 6.2（下一批）—— 本演示用状态机直接归零收场。
// ============================================================================

import type { 战斗入参 } from './战斗接口';
import { 开始战斗, 进入下一回合, 判定结局, 单位归零 } from './战斗状态';
import { 官方记忆卡池, 出牌, 抽一手 } from './卡牌';

const 线 = (s = '') => console.log(s);

const 入参: 战斗入参 = {
  我方: [
    { 名字: '护路人', 当前生命: 120, 生命上限: 120, 个人体力: 50, 护甲: 0, 技能: [] },
    { 名字: '荒野射手', 当前生命: 70, 生命上限: 70, 个人体力: 50, 护甲: 0, 技能: [] },
    { 名字: '修补师', 当前生命: 85, 生命上限: 85, 个人体力: 50, 护甲: 0, 技能: [] },
  ],
  敌方: [
    { 名字: '灰狼', 生命上限: 60, 当前生命: 60, 护甲: 0, 护盾: 0, 初始状态: [], 迟滞层数: 0 },
  ],
  难度: '普通', 商队当前耐久: 100, 可用药包: 5, 可用零件: 5,
};

const 状态 = 开始战斗(入参);

线('════════ 第一场战斗（6B 第1批 · 无伤害结算，纯机制演示）════════');
线(`第 ${状态.回合} 回合 · 体力池 ${状态.体力池.当前}/${状态.体力池.上限}（每回合回复 ${状态.体力池.每回合回复}）`);

// —— 规则拒绝演示：3 张记忆卡不合法（必须 2 动作 + 1 记忆 · 4A:111）——
const 坏抽 = 抽一手([...官方记忆卡池.荒野射手], ['标记', '标记', '标记']);
线(`  [规则拒绝] 射手抽 3 张记忆卡 → ❌ ${坏抽.原因}`);

// —— 第 1 回合：出两张牌（体力闸门）——
状态.手牌 = [官方记忆卡池.护路人[0], 官方记忆卡池.荒野射手[1]]; // 迎击 / 精确射击
for (const 名字 of ['迎击', '精确射击']) {
  const r = 出牌(状态, 名字);
  线(`  出「${名字}」 → ${r.成功 ? `✅ 剩余体力 ${r.剩余体力}` : `❌ ${r.原因}`}`);
}

// —— 回合切换：体力回复封顶 · 手牌清空 ——
进入下一回合(状态);
线('');
线(`第 ${状态.回合} 回合 · 体力池 ${状态.体力池.当前}/${状态.体力池.上限}（回复 +150 封顶）· 手牌 ${状态.手牌.length} 张（回合末清空 ✅）`);

// —— 第 2 回合：出一张重牌 ——
状态.手牌 = [官方记忆卡池.护路人[4]]; // 重击 100
const 重击结果 = 出牌(状态, '重击');
线(`  出「重击」 → ${重击结果.成功 ? `✅ 剩余体力 ${重击结果.剩余体力}` : `❌ ${重击结果.原因}`}`);

// —— 收场：灰狼归零（伤害在 6.2 —— 这里直接用状态机）——
单位归零(状态, 状态.敌方[0]);
const 结局 = 判定结局(状态);

线('');
线('════════ 汇总 ════════');
线(`  走过回合    ${状态.回合}`);
线(`  我方存活    ${状态.我方.filter((u) => !u.已退出).map((u) => u.名字).join('、')}`);
线(`  灰狼        已退出（本场重伤 ${状态.敌方[0].本场重伤次数} 次）`);
线(`  战斗结局    ${结局 ?? '继续'}`);
线('');
