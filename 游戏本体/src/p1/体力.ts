import type { 游戏状态 } from './类型';

/** 🔴 野外体力上限，恒为 100，不许加档（1A §2） */
export const 体力上限值 = 100;
/** 🔴 每天回复 +50（1A §2） */
export const 每日回复 = 50;
/** 🔴 每格消耗基准 15（1A §5） */
export const 每格基准消耗 = 15;

/** 🔴 够不够走这一格。够不够的判断必须在这里，不许散在主循环里 */
export function 够吗(状态: 游戏状态, 要扣: number): boolean {
  return 要扣 >= 0 && 状态.野外体力 >= 要扣;
}

/** 🔴 扣。调用方负责先问 够吗() —— 这里再兜一道，保证永远不会扣成负数 */
export function 扣(状态: 游戏状态, 多少: number): void {
  if (!够吗(状态, 多少)) {
    throw new Error(`不该发生：没问「够吗」就扣（要扣 ${多少}，剩 ${状态.野外体力}）`);
  }
  状态.野外体力 -= 多少;
}

/** 🔴 每日回复 +50，封顶 100。🔴 只允许 结算.跨日() 调用（禁止事项 57） */
export function 回(状态: 游戏状态): void {
  状态.野外体力 = Math.min(状态.体力上限, 状态.野外体力 + 每日回复);
}
