/// 游戏状态 —— 玩家跑一趟商路期间会变的那些东西
///
/// 🔴 1.0.0 阶段只放最少的字段，用来验证「状态结构 + 更新流程」是通的。
/// 🔴 完整字段清单在 1.1（时间与体力）之后逐个中阶段补。
export interface 游戏状态 {
  // —— 位置 ——
  /// 当前所在坐标（x 向右，y 向上）
  当前坐标: { x: number; y: number };

  // —— 时间 ——
  /// 从 1 开始
  第几天: number;
  /// 一天之内的时刻（07:00 ~ 19:00）
  当前小时: number;

  // —— 体力 ——
  /// 野外体力池，上限 100
  野外体力: number;
  /// 体力上限，恒为 100
  体力上限: number;
}

/// 新建一局状态
///
/// 🔴 初始值说明：🔴 体力 100 / 上限 100 / 第 1 天 / 07:00 —— 🔴 **与 A 类一致**。
/// 🔴 坐标由调用方给（🔴 不写死 —— 地图是内容不是逻辑）。
export function 新建游戏状态(起点: { x: number; y: number }): 游戏状态 {
  return {
    当前坐标: { x: 起点.x, y: 起点.y },
    第几天: 1,
    当前小时: 7,
    野外体力: 100,
    体力上限: 100,
  };
}
