// P1 · 移动 —— 🔴 玩家操作的唯一入口（施工图 §3.5 + §4 九步）
//
// 🔴 九步顺序一步不许调换；①~⑤ 任何一步不过 → 状态一行都不许动（判据 3~7）
// 🔴 ⑥ 里只有三个改动：扣体力 / 换坐标 / 推进时间 —— 不许顺手改别的
// 🔴 ⑧ 只调一次 跨日()，主循环自己绝不回体力
// ============================================================================

import { 查格, 是否相邻, 在图内 } from './地图';
import { 时间够吗, 推进 } from './时间';
import { 够吗, 扣 } from './体力';
import { 每格消耗 } from './消耗';
import { 地点类, type 操作结果, type 游戏状态 } from './类型';

/**
 * 🔴 走一格（目标坐标）
 * ① 在图内 → ② 相邻 → ③ 可通行 → ④ 体力 → ⑤ 时间 → ⑥ 提交 → ⑦ 到点？ → ⑧ 跨日 → ⑨ 标记抵达
 */
export function 走一格(状态: 游戏状态, 目标x: number, 目标y: number): 操作结果 {
  const 地图 = 状态.地图;
  const 失败 = (原因: '出地图了' | '不是相邻格' | '过不去' | '体力不够' | '时间不够'): 操作结果 =>
    ({ 成功: false, 原因 });

  // ① 目标坐标在地图内吗
  if (!在图内(地图, 目标x, 目标y)) return 失败('出地图了');

  // ② 与当前格四方向相邻吗（斜向 / 隔两格 / 原地都走不了）
  if (!是否相邻(状态.当前坐标, { x: 目标x, y: 目标y })) return 失败('不是相邻格');

  // ③⭐ 目标格可通行吗 —— 走到这里，目标格（含路况）已经在手里了
  const 目标格 = 查格(地图, 目标x, 目标y);
  if (!目标格.可通行) return 失败('过不去');

  // ④⭐ 体力够吗（消耗只从 消耗.每格消耗() 拿 —— 禁止事项 58）
  const 要扣 = 每格消耗(状态, 目标格.路况);
  if (!够吗(状态, 要扣)) return 失败('体力不够');

  // ⑤ 时间够走完这一整格吗（🔴 不许走一半，判据 19 允许 17:00 收官那一格）
  if (!时间够吗(状态)) return 失败('时间不够');

  // ⑥⭐ 五项检查全过 —— 现在才允许改状态，且只有这三个改动
  扣(状态, 要扣);
  状态.当前坐标 = { x: 目标x, y: 目标y };
  推进(状态, 2);

  // ⑦⑧ ✍️ 2026-10-23 项目主裁定：🔴 到 19:00 **不再自动跨日**。
  //    A 类原文只说「19:00 天黑了，收工。不管今天走到哪儿，天黑就得停」（0A 游戏介绍）
  //    +「入夜睡觉不耗时间」（1A §2.2）—— 过夜是玩家自己的决定，不是走路自动送的。
  //    施工图判据 16 / 20 的「自动跨日」作废（留痕见 AI交流\项目主裁定_到19点不自动跨日_20261023.md）。
  //    时间用完后再走 → 第 ⑤ 步拒「时间不够」· 状态不动，必须点「结束当天」才回 07:00。

  // ⑨ 走进没到访过的地点 → 标记已到访（⑦ 的「没到点」分支与 ⑧ 之后都要标，
  //    所以放在两条分支汇合之后，语义与 §4 一致）
  标记抵达(状态);

  // 走到终点了吗（§4 最后一行 / 判据 12）
  const 抵达 = 目标x === 地图.终点.x && 目标y === 地图.终点.y;
  return 抵达 ? { 成功: true, 原因: null, 已抵达: true } : { 成功: true, 原因: null };
}

/// 走进地点类格子 = 「抵达」。权威字段是 格子.已到访（json 没有地点名字段 → P1 只有标记）
function 标记抵达(状态: 游戏状态): void {
  const { x, y } = 状态.当前坐标;
  const 格 = 查格(状态.地图, x, y);
  if (!地点类.has(格.类型) || 格.已到访) return;
  格.已到访 = true;
}
