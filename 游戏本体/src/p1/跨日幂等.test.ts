// ============================================================================
// 判据 23~28 · 跨日幂等（施工图 §5.3）—— 🔴 旧代码在这里踩过「一天回两份体力」
// ============================================================================

import { describe, it, expect } from 'vitest';
import { 走一格 } from './移动';
import { 结束当天 } from './结束当天';
import { 跨日 } from './结算';
import { 走廊局, 快照 } from './测试辅助';

const 向东 = (状态: ReturnType<typeof 走廊局>) => 走一格(状态, 状态.当前坐标.x + 1, 状态.当前坐标.y);
const 冲到跨日 = (状态: ReturnType<typeof 走廊局>) => { for (let i = 0; i < 6; i += 1) 向东(状态); };

describe('判据 23~25 · 一次日界只做一次', () => {
  it('23 一次到达 19:00 → 天数只 +1、时钟只重置一次、体力只回一次、天气段只 −1', () => {
    const 状态 = 走廊局();
    const 起始天气段 = 状态.天气剩余天数;
    冲到跨日(状态);
    expect(状态.第几天).toBe(2);                                   // 只 +1
    expect(状态.当前小时).toBe(7);                                  // 只重置这一次
    expect(状态.野外体力).toBe(60);                                 // 10+50，不是 110
    expect(状态.天气剩余天数).toBe(起始天气段 - 1);                   // 只推进一格天气
  });

  it('24 刚跨过日（第 2 天 07:00）立刻点「结束当天」→ 拒绝「今天已结算过了」，不再跨第二次', () => {
    const 状态 = 走廊局();
    冲到跨日(状态);
    const 前 = 快照(状态);
    expect(结束当天(状态)).toEqual({ 成功: false, 原因: '今天已结算过了' });
    expect(快照(状态)).toBe(前);
    expect(状态.第几天).toBe(2);
  });

  it('25 同一天内点两次「结束当天」→ 第二次被拒', () => {
    const 状态 = 走廊局();
    expect(结束当天(状态).成功).toBe(true);
    const 前 = 快照(状态);
    expect(结束当天(状态)).toEqual({ 成功: false, 原因: '今天已结算过了' });
    expect(快照(状态)).toBe(前);
    expect(状态.第几天).toBe(2);
  });
});

describe('判据 26~28 · 任何时候都能收工 + 长跑不漂', () => {
  it('26 开局 07:00 立刻点「结束当天」→ 允许跨日（旧代码在这条挂过）', () => {
    const 状态 = 走廊局();
    expect(状态.当前小时).toBe(7);
    expect(结束当天(状态).成功).toBe(true);                          // 🔴 不许因为「小时 > 7」被拒
    expect(状态.第几天).toBe(2);
    expect(状态.当前小时).toBe(7);
  });

  it('27 体力 0 点时点「结束当天」→ 允许（不许卡死玩家）', () => {
    const 状态 = 走廊局();
    状态.野外体力 = 0;
    expect(结束当天(状态).成功).toBe(true);
    expect(状态.野外体力).toBe(50);
    expect(状态.第几天).toBe(2);
  });

  it('28 连跑 10 个游戏日 → 跨日正好 10 次 · 天数不错 · 体力不越界', () => {
    const 状态 = 走廊局(40);
    let 跨日次数 = 0;
    for (let 天 = 1; 天 <= 10; 天 += 1) {
      expect(向东(状态).成功).toBe(true);              // 白天走一格（顺带把幂等标记清回 false）
      const 之前 = 状态.第几天;
      expect(结束当天(状态).成功).toBe(true);
      if (状态.第几天 === 之前 + 1) 跨日次数 += 1;
      expect(状态.第几天).toBe(天 + 1);
      expect(状态.当前小时).toBe(7);
      expect(状态.野外体力).toBeGreaterThanOrEqual(0);
      expect(状态.野外体力).toBeLessThanOrEqual(100);
      expect(Number.isInteger(状态.野外体力)).toBe(true);
    }
    expect(跨日次数).toBe(10);
  });

  it('跨日() 自己也有保险丝：已结算过再调，四件事一件都不做', () => {
    const 状态 = 走廊局();
    结束当天(状态);
    const 前 = 快照(状态);
    跨日(状态);                                          // 直接调底层也必须无效
    expect(快照(状态)).toBe(前);
  });
});
