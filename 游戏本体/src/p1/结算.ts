import { 回 } from './体力';
import { 推进天气段 } from './天气';
import { 开工小时 } from './时间';
import type { 游戏状态 } from './类型';

/**
 * 🔴 跨日 —— 一次做四件事，顺序固定，不许增删：
 *   1. 第几天 += 1
 *   2. 当前小时 = 07:00
 *   3. 体力 += 50（封顶 100）
 *   4. 天气段 −1（到期则重掷）
 * 🔴 幂等：今天已结算 为 true 就直接返回（判据 23 / 24 / 25 靠这一条）
 *    🔴 标记的置位只发生在这里；清回 false 在 时间.推进()，理由见那里的注释。
 */
export function 跨日(状态: 游戏状态): void {
  if (状态.今天已结算) return;          // 🔴 保险丝：同一次日界不许触发第二次

  状态.今天已结算 = true;
  状态.第几天 += 1;                     // ①
  状态.当前小时 = 开工小时;              // ②
  回(状态);                            // ③ 唯一回体力的地方，封顶在 体力.回() 里
  推进天气段(状态);                     // ④
}
