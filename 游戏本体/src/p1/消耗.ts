import { 每格基准消耗 } from './体力';
import { 每格加成 as 天气加成 } from './天气';
import type { 路况档, 游戏状态 } from './类型';

/**
 * 🔴 路况加成表 —— 🔴🔴 施工图 §6.2：全库只有 1A §5.1 一句「坏路况 → 上升」，
 * 🔴 没有任何文件写出上升多少 → **四档先全资源篮 0**，待项目主裁定。
 * 裁定之后只改这张表，判据 46（r=0 vs r=2 扣的点必须不同）立刻就有区分度。
 */
export const 路况加成: Record<路况档, number> = { 0: 0, 1: 0, 2: 0, 3: 0 };

/** 🔴 公式就这么长 —— 不许加第五项，不许改顺序 */
export function 每格消耗(状态: 游戏状态, 目标格路况: 路况档): number {
  return 每格基准消耗 + 天气加成(状态.当前天气) + 路况加成[目标格路况];
}
