// 判据 50~53 + 5.6+1/5.6+2 · 叠加（施工图 §5.6）—— 🔴 专抓「加成被加两次」
// ============================================================================

import { describe, it, expect } from 'vitest';
import { 每格消耗, 路况加成 } from './消耗';
import { 每格加成 } from './天气';
import { 每格基准消耗 } from './体力';
import { 侦察, 采集, 搜索, 补给, 修车, 治疗, 交易 } from './接口位';
import { 走一格 } from './移动';
import { 走廊局, 快照 } from './测试辅助';
import type { 天气名, 路况档 } from './类型';

const 期望 = (天气: 天气名, 路况: 路况档) =>
  每格基准消耗 + 每格加成(天气) + 路况加成[路况];   // 🔴 只准加一次，谁都不许乘 2

describe('判据 50~53 · 天气 × 路况 叠加只算一次', () => {
  const 组合: [number, 天气名, 路况档][] = [
    [50, '晴朗', 0],
    [51, '暴雨', 2],          // 🔴 这一行抓重复计算
    [52, '灰烬风暴', 2],      // 🔴 这两行是本组核心
    [53, '阴天', 1],
  ];
  for (const [编号, 天气, 路况] of 组合) {
    it(`${编号} ${天气} + r=${路况}：消耗恰好等于两张表各加一次`, () => {
      const 状态 = 走廊局();
      状态.当前天气 = 天气;
      const 实际 = 每格消耗(状态, 路况);
      expect(实际).toBe(期望(天气, 路况));
      // 反双算：加成合计为 0 时（§6.1 / §6.2 数值待裁定），这条会退化成「15 ≠ 15」——
      // 那是我自己造的假红，判据里没这一条。所以只在数值填上之后才要求它有牙齿。
      const 加成合计 = 每格加成(天气) + 路况加成[路况];
      if (加成合计 > 0) {
        expect(实际, `${天气}+r=${路况}：加成被加了两遍`).not.toBe(每格基准消耗 + 2 * 加成合计);
      }
    });
  }
});

describe('判据 5.6+1 / 5.6+2 · 七个接口位', () => {
  const 七个 = [['侦察', 侦察], ['采集', 采集], ['搜索', 搜索], ['补给', 补给],
    ['修车', 修车], ['治疗', 治疗], ['交易', 交易]] as const;

  it('5.6+1 七个接口位都返回「本阶段未实现」· 状态一点没变', () => {
    for (const [名, 函数] of 七个) {
      const 状态 = 走廊局();
      const 前 = 快照(状态);
      expect(函数(状态), 名).toEqual({ 成功: false, 原因: '本阶段未实现' });
      expect(快照(状态), 名).toBe(前);
    }
    // 走一格仍然只有「移动」会改状态 —— 接口位没顺手改东西
    const 状态 = 走廊局();
    expect(走一格(状态, 状态.当前坐标.x + 1, 状态.当前坐标.y).成功).toBe(true);
  });

  it('5.6+2 接口位不许被误实现：每个函数体只有一行 return', () => {
    for (const [名, 函数] of 七个) {
      const 源码 = 函数.toString();
      const 分句 = 源码.split(';').map((句) => 句.trim()).filter((句) => 句 !== '' && 句 !== '}');
      expect(分句.length, `${名} 的函数体超过一行，说明被偷偷实现了：${源码}`).toBe(1);
      expect(源码, 名).toContain('本阶段未实现');
      for (const 关键词 of ['跨日', '扣(', '推进', '每格消耗']) {
        expect(源码.includes(关键词), `${名} 里出现了「${关键词}」—— 接口位不许有行为`).toBe(false);
      }
    }
  });
});
