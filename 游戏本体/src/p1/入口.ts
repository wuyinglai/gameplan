import { 新建游戏状态, type 游戏状态 } from './状态';

/// 演示用的一步操作：🔴 假装往右走一格，扣 15 点体力，推进 2 小时。
///
/// 🔴 【为什么写成这样】
/// 🔴 1.0.0 不做地图读取、不做通行判断（那是 1.3 的活）。
/// 🔴 这里只需要证明「调用一个动作 → 状态变了 → 变化是对的」。
export function 走一格(状态: 游戏状态): void {
  状态.当前坐标 = { x: 状态.当前坐标.x + 1, y: 状态.当前坐标.y };
  状态.当前小时 += 2;
  状态.野外体力 -= 15;
}

/// 把状态打成一行中文，🔴 让不读代码的人也能看懂
export function 描述(标签: string, 状态: 游戏状态): string {
  const { x, y } = 状态.当前坐标;
  return (
    `  ${标签}：第 ${状态.第几天} 天 ${String(状态.当前小时).padStart(2, '0')}:00` +
    `  位置 (${x}, ${y})  体力 ${状态.野外体力} / ${状态.体力上限}`
  );
}

/// 跑一遍完整演示并打印 —— 🔴 项目主看的就是这个
export function 演示(): void {
  const 状态 = 新建游戏状态({ x: 10, y: 199 });

  console.log('\n╔══════════════════════════════════════════════════════════════╗');
  console.log('║  《余烬商队》P1 演示 —— 第 1 阶段 · 旅行基础                    ║');
  console.log('╚══════════════════════════════════════════════════════════════╝\n');

  console.log('【开始】');
  console.log(描述('状态', 状态));

  走一格(状态);

  console.log('\n【走了一格之后】');
  console.log(描述('状态', 状态));

  console.log('\n【变化了什么】');
  console.log('  位置：x 加 1（写死的假移动，🔴 真的移动在 1.3 做）');
  console.log('  时间：+2 小时（一格 = 2 小时）');
  console.log('  体力：-15 点（每格基础消耗 15）');
  console.log('\n');
}
