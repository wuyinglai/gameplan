// ============================================================================
// P1 / 1.0.0 · 入口测试
//
// 🔴 五条断言分四类：
//   ① 入口能跑完不报错
//   ② 初始状态字段是预期值
//   ③ "走一格"之后该变的变了
//   ④ "走一格"之后不该变的没变   ← 🔴 最容易漏，但最重要（抓"改 A 把 B 也改了"）
//   ⑤ 描述函数能读（项目主看的就是这个）
// ============================================================================

import { describe, it, expect } from 'vitest';
import { 新建游戏状态 } from './状态';
import { 走一格, 描述, 演示 } from './入口';

describe('P1 / 1.0.0 · 演示入口', () => {
  it('🔴 入口能跑完不报错（跑这条就能看到那段中文输出）', () => {
    演示();
    expect(true).toBe(true);
  });

  it('🔴 初始状态是对的', () => {
    const 状态 = 新建游戏状态({ x: 10, y: 199 });

    // 🔴 这些数字来自 A 类规则，不是随手写的
    expect(状态.第几天).toBe(1);
    expect(状态.当前小时).toBe(7);          // 07:00 开工
    expect(状态.野外体力).toBe(100);
    expect(状态.体力上限).toBe(100);
    expect(状态.当前坐标).toEqual({ x: 10, y: 199 });
  });

  it('🔴 走一格之后，该变的变了', () => {
    const 状态 = 新建游戏状态({ x: 10, y: 199 });
    走一格(状态);

    expect(状态.当前坐标.x).toBe(11);
    expect(状态.当前小时).toBe(9);          // 07:00 + 2
    expect(状态.野外体力).toBe(85);        // 100 - 15
  });

  it('🔴 走一格之后，不该变的没变', () => {
    const 状态 = 新建游戏状态({ x: 10, y: 199 });
    走一格(状态);

    // 🔴 这一条抓的是「改 A 把 B 也改了」这类 bug —— 最容易漏，但最重要
    expect(状态.第几天).toBe(1);            // 没跨日，天数不许变
    expect(状态.体力上限).toBe(100);        // 上限是常量，不许变
    expect(状态.当前坐标.y).toBe(199);      // 只动了 x
  });

  it('🔴 描述函数能读（项目主看的就是这个）', () => {
    const 状态 = 新建游戏状态({ x: 10, y: 199 });
    const 行 = 描述('状态', 状态);

    expect(行).toContain('第 1 天');
    expect(行).toContain('07:00');
    expect(行).toContain('体力 100 / 100');
  });
});
