import type { 游戏状态 } from './类型';

/** 🔴 走一格固定 2 小时（1A §2.2） */
export const 每格耗时 = 2;

/** 🔴 收工时刻（1A §2.2） */
export const 收工小时 = 19;
/** 🔴 开工时刻（1A §2.2） */
export const 开工小时 = 7;

/**
 * 🔴 推进 n 小时。返回 true = 到点收工了，调用方（移动.ts）去调 结算.跨日()。
 *
 * ✍️ 为什么这里动了 `今天已结算`：施工图 §3.2 只禁止本文件改 `第几天` / `当前小时`，
 *    而幂等标记不清就会出判据 27 要求不能出现的**卡死**：
 *      跨日 → 标记 true → 新的一天什么都不清 → 那一天永远点不了「结束当天」。
 *    放进 推进() 是唯一同时满足三件事的位置：
 *      ① 「推进了时间」= 这一天还在继续 = 没有可结束的今天（清标记）
 *      ② 不碰 第几天 / 当前小时（禁止事项 57 仍然成立）
 *      ③ 不违反 §4 步骤 ⑥「只有三个改动」（改动在 推进 内部，不在主循环里）
 *    顺序也安全：移动.ts 是「先 推进（清）→ 后 跨日（置）」，跨日之后标记稳定为 true。
 */
export function 推进(状态: 游戏状态, n: number): boolean {
  if (!Number.isInteger(n) || n <= 0) {
    throw new Error(`推进耗时必须是正整数小时，收到 ${String(n)}`);
  }
  状态.当前小时 += n;
  状态.今天已结算 = false;              // ← 见上面 ✍️ 的说明
  return 状态.当前小时 >= 收工小时;
}

/** 🔴 当前小时还能不能再走一格。🔴 17:00 还能走（走完正好 19:00）—— 判据 19 */
export function 时间够吗(状态: 游戏状态): boolean {
  return 状态.当前小时 + 每格耗时 <= 收工小时;
}
