type 判定 = '✅' | '❌' | '⏳';
interface 行 { 项目: string; 预期: string; 实际: string; 对不对: 判定 }
const 表: 行[] = [];
const 记 = (项目: string, 预期: string, 实际: string, 对不对: 判定): void => {
  表.push({ 项目, 预期, 实际, 对不对 });
};
const 对 = (项目: string, 预期: string, 实际: string, 成立: boolean): void =>
  记(项目, 预期, 实际, 成立 ? '✅' : '❌');

/// 每行一份全新状态，天气由参数指定（规范硬规矩：强制指定，不许靠骰子撞）
const 新状态 = (天气: 天气名): 游戏状态 => {
  const 状态 = 真局();
  状态.当前天气 = 天气;
  return 状态;
};
const 账 = (状态: 游戏状态): string =>
  `第${状态.第几天}天 ${状态.当前小时}:00 · 体力 ${状态.野外体力}`;
const 描述结果 = (果: 操作结果): string =>
  果.成功 ? (果.已抵达 === true ? '成功 · 已抵达' : '成功') : `拒绝 · ${果.原因}`;

/// 连续向东走 n 格（走廊图专用）
const 向东 = (状态: 游戏状态, 次: number): 操作结果 => {
  let 最后: 操作结果 = { 成功: true, 原因: null };
  for (let i = 0; i < 次; i += 1) {
    最后 = 走一格(状态, 状态.当前坐标.x + 1, 状态.当前坐标.y);
    if (!最后.成功) return 最后;
  }
  return 最后;
};

/// 真图上探一步：脚下摆到满足条件的一格，再朝目标格走
const 探 = (
  项目: string,
  预期: string,
  应成功: boolean,
  找: () => { 脚下: { x: number; y: number }; 目标: { x: number; y: number } },
): void => {
  const 状态 = 真局();
  const { 脚下, 目标 } = 找();
  状态.当前坐标 = { ...脚下 };
  const 之前 = 快照(状态);
  const 果 = 走一格(状态, 目标.x, 目标.y);
  const 没乱动 = 果.成功 || 快照(状态) === 之前;
  记(
    项目, 应成功 ? 预期 : `${预期} · 状态不变`,
    `${描述结果(果)}${应成功 ? '' : (没乱动 ? ' · 状态未变' : ' · 🔴状态被改了')}`,
    应成功 === 果.成功 && 没乱动 ? '✅' : '❌',
  );
};

