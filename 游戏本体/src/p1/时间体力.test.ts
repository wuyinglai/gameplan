// ============================================================================
// 判据 13~22 · 时间与体力（施工图 §5.2）
// 🔴 开局固定：第 1 天 07:00 · 体力 100/100 · 天气与路况加成为 0（§6.1 / §6.2）
// 🔴 用构造的走廊小图：每一步一定可通行，数字才不会被地形污染
// ============================================================================

import { describe, it, expect } from 'vitest';
import { 走一格 } from './移动';
import { 每格消耗 } from './消耗';
import { 每格基准消耗 } from './体力';
import { 每格耗时, 收工小时 } from './时间';
import { 走廊局, 快照 } from './测试辅助';

const 向东 = (状态: ReturnType<typeof 走廊局>) => 走一格(状态, 状态.当前坐标.x + 1, 状态.当前坐标.y);
const 不许变 = (状态: ReturnType<typeof 走廊局>) => 快照(状态);

describe('判据 13~16 · 一天走六格的完整账', () => {
  it('13 从 07:00 连走 3 格 → 第 1 天 13:00 · 体力 55 · 没跨日', () => {
    const 状态 = 走廊局();
    expect(每格消耗(状态, 0)).toBe(15);                 // 本阶段：加成全 0 → 恒 15
    for (let i = 0; i < 3; i += 1) expect(向东(状态).成功).toBe(true);
    expect(状态.第几天).toBe(1);
    expect(状态.当前小时).toBe(13);
    expect(状态.野外体力).toBe(55);
  });

  it('14 接着走第 4 格 → 15:00 · 体力 40', () => {
    const 状态 = 走廊局();
    for (let i = 0; i < 4; i += 1) 向东(状态);
    expect(状态.当前小时).toBe(15);
    expect(状态.野外体力).toBe(40);
  });

  it('15 接着走第 5 格 → 17:00 · 体力 25 · 还没跨日', () => {
    const 状态 = 走廊局();
    for (let i = 0; i < 5; i += 1) 向东(状态);
    expect(状态.当前小时).toBe(17);
    expect(状态.野外体力).toBe(25);
    expect(状态.第几天).toBe(1);
  });

  it('16 接着走第 6 格 → 19:00 到点自动跨日 → 第 2 天 07:00 · 体力 60', () => {
    const 状态 = 走廊局();
    for (let i = 0; i < 5; i += 1) 向东(状态);
    expect(向东(状态).成功).toBe(true);
    expect(状态.第几天).toBe(2);
    expect(状态.当前小时).toBe(7);
    expect(状态.野外体力).toBe(60);                     // 10 + 50
  });

  it('17 第 2 天连走 4 格 → 15:00 · 体力 0（攒池机制的来源）', () => {
    const 状态 = 走廊局();
    for (let i = 0; i < 6; i += 1) 向东(状态);          // 冲完第一天 → 第2天 60 点
    for (let i = 0; i < 4; i += 1) expect(向东(状态).成功).toBe(true);
    expect(状态.当前小时).toBe(15);
    expect(状态.野外体力).toBe(0);
  });
});

describe('判据 18~22 · 不够就什么都不动', () => {
  it('18 体力剩 0 时再走 → 拒绝「体力不够」· 状态一点没变', () => {
    const 状态 = 走廊局();
    for (let i = 0; i < 6; i += 1) 向东(状态);
    for (let i = 0; i < 4; i += 1) 向东(状态);          // 第 2 天走到 0
    const 前 = 不许变(状态);
    expect(向东(状态)).toEqual({ 成功: false, 原因: '体力不够' });
    expect(快照(状态)).toBe(前);
  });

  it('19 当前 17:00 再走一格 → ✅ 允许（17+2=19 正好收工）', () => {
    const 状态 = 走廊局();
    状态.当前小时 = 17;
    const 结果 = 向东(状态);
    expect(结果.成功).toBe(true);
    expect(状态.当前小时).toBe(7);                      // 立刻跨日，停在第二天 07:00
    expect(状态.第几天).toBe(2);
  });

  it('20 时钟永远不会停在 19:00', () => {
    const 状态 = 走廊局();
    const 时刻: number[] = [];
    for (let i = 0; i < 8; i += 1) { 向东(状态); 时刻.push(状态.当前小时); }
    expect(时刻).toEqual([9, 11, 13, 15, 17, 7, 9, 11]);
    expect(时刻).not.toContain(收工小时);
    expect(时刻.every((h) => [7, 9, 11, 13, 15, 17].includes(h))).toBe(true);
  });

  it('21 六格冲刺要 90 点 · 开局 100 够', () => {
    expect(每格基准消耗 * 6).toBe(90);
    expect(每格耗时 * 6).toBe(12);                      // 时间上也正好一天
    const 状态 = 走廊局();
    expect(状态.野外体力).toBe(100);
    for (let i = 0; i < 6; i += 1) expect(向东(状态).成功).toBe(true);
    expect(状态.第几天).toBe(2);
  });

  it('22 体力剩 10 点时走一格 → 拒绝「体力不够」· 状态一点没变', () => {
    const 状态 = 走廊局();
    状态.野外体力 = 10;
    const 前 = 不许变(状态);
    expect(向东(状态)).toEqual({ 成功: false, 原因: '体力不够' });
    expect(快照(状态)).toBe(前);
  });
});
