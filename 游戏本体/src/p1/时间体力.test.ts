// ============================================================================
// 判据 13~22 · 时间与体力（施工图 §5.2）
// 🔴 开局固定：第 1 天 07:00 · 体力 100/100 · 天气与路况加成为 0（§6.1 / §6.2）
// 🔴 用构造的走廊小图：每一步一定可通行，数字才不会被地形污染
//
// ✍️ 2026-10-23 项目主裁定 —— 推翻施工图判据 16 / 20 的「自动跨日」：
//    走到 19:00 就**停在 19:00**（A 类：19:00 天黑收工，天黑就得停；入夜睡觉不耗时间），
//    🔴 走路不会自动送第二天；再走一律拒「时间不够」· 状态一行不动，
//    必须玩家点「结束当天」才 第几天 +1 · 时钟回 07:00 · 体力 +50（封顶 100）。
// ============================================================================

import { describe, it, expect } from 'vitest';
import { 走一格 } from './移动';
import { 结束当天 } from './结束当天';
import { 每格消耗 } from './消耗';
import { 每格基准消耗 } from './体力';
import { 每格耗时, 收工小时, 开工小时 } from './时间';
import { 走廊局, 快照 } from './测试辅助';

const 向东 = (状态: ReturnType<typeof 走廊局>) => 走一格(状态, 状态.当前坐标.x + 1, 状态.当前坐标.y);
const 不许变 = (状态: ReturnType<typeof 走廊局>) => 快照(状态);
const 走满一天 = (状态: ReturnType<typeof 走廊局>) => { for (let i = 0; i < 6; i += 1) 向东(状态); };

describe('判据 13~16 · 一天走六格的完整账', () => {
  it('13 从 07:00 连走 3 格 → 第 1 天 13:00 · 体力 55 · 没跨日', () => {
    const 状态 = 走廊局();
    expect(每格消耗(状态, 0)).toBe(15);                 // 本阶段：加成全 0 → 恒 15
    for (let i = 0; i < 3; i += 1) expect(向东(状态).成功).toBe(true);
    expect(状态.第几天).toBe(1);
    expect(状态.当前小时).toBe(13);
    expect(状态.野外体力).toBe(55);
  });

  it('14 接着走第 4 格 → 15:00 · 体力 40', () => {
    const 状态 = 走廊局();
    for (let i = 0; i < 4; i += 1) 向东(状态);
    expect(状态.当前小时).toBe(15);
    expect(状态.野外体力).toBe(40);
  });

  it('15 接着走第 5 格 → 17:00 · 体力 25 · 还没跨日', () => {
    const 状态 = 走廊局();
    for (let i = 0; i < 5; i += 1) 向东(状态);
    expect(状态.当前小时).toBe(17);
    expect(状态.野外体力).toBe(25);
    expect(状态.第几天).toBe(1);
  });

  it('16 ✍️ 走满第 6 格 → 停在 19:00 不自动跨日 · 点「结束当天」才回 07:00', () => {
    const 状态 = 走廊局();
    for (let i = 0; i < 5; i += 1) 向东(状态);
    expect(向东(状态).成功).toBe(true);
    expect(状态.第几天).toBe(1);                         // 🔴 走路不送跨日
    expect(状态.当前小时).toBe(收工小时);                 // 天黑收工，就停在这一刻
    expect(状态.野外体力).toBe(10);

    expect(结束当天(状态).成功).toBe(true);
    expect(状态.第几天).toBe(2);
    expect(状态.当前小时).toBe(开工小时);
    expect(状态.野外体力).toBe(60);                      // 10 + 50
  });

  it('17 第 2 天连走 4 格 → 15:00 · 体力 0（攒池机制的来源）', () => {
    const 状态 = 走廊局();
    走满一天(状态);                                      // 第一天走满 → 19:00 · 体力 10
    结束当天(状态);                                       // → 第 2 天 07:00 · 体力 60
    for (let i = 0; i < 4; i += 1) expect(向东(状态).成功).toBe(true);
    expect(状态.当前小时).toBe(15);
    expect(状态.野外体力).toBe(0);
  });
});

describe('判据 18~22 · 不够就什么都不动', () => {
  it('18 体力剩 0 时再走 → 拒绝「体力不够」· 状态一点没变', () => {
    const 状态 = 走廊局();
    走满一天(状态);
    结束当天(状态);
    for (let i = 0; i < 4; i += 1) 向东(状态);          // 第 2 天走到 0
    const 前 = 不许变(状态);
    expect(向东(状态)).toEqual({ 成功: false, 原因: '体力不够' });
    expect(快照(状态)).toBe(前);
  });

  it('19 当前 17:00 再走一格 → ✅ 允许（17+2=19 正好收工）· 停在 19:00', () => {
    const 状态 = 走廊局();
    状态.当前小时 = 17;
    const 结果 = 向东(状态);
    expect(结果.成功).toBe(true);
    expect(状态.当前小时).toBe(收工小时);                // ✍️ 停在收工时刻
    expect(状态.第几天).toBe(1);                         // 🔴 没有自动进入第二天
  });

  it('19+ 停在 19:00 后继续走 → 拒「时间不够」· 状态一点没变（要玩家自己开下一天）', () => {
    const 状态 = 走廊局();
    走满一天(状态);                                     // → 19:00
    状态.野外体力 = 100;          // 🔴 体力不够在第 ④ 步、时间不够在第 ⑤ 步：
                                   //    不清满就会先被体力挡掉，测不到时间这一条（判据顺序不许改）
    const 前 = 不许变(状态);
    for (let 次 = 1; 次 <= 5; 次 += 1) {
      expect(向东(状态), `第 ${次} 次本该被拒`).toEqual({ 成功: false, 原因: '时间不够' });
    }
    expect(快照(状态)).toBe(前);
    expect(状态.第几天).toBe(1);
  });

  it('20 ✍️ 改版：时钟只落在 7/9/…/17/19，19:00 是「今天到头」的终态', () => {
    const 状态 = 走廊局();
    const 时刻: number[] = [];
    for (let i = 0; i < 8; i += 1) { 向东(状态); 时刻.push(状态.当前小时); }
    expect(时刻).toEqual([9, 11, 13, 15, 17, 19, 19, 19]);   // 到 19 就不动了
    expect(时刻).toContain(收工小时);                          // 🔴 旧期望「永不为 19」已作废
    expect(时刻.every((h) => [7, 9, 11, 13, 15, 17, 19].includes(h))).toBe(true);

    结束当天(状态);
    expect(状态.当前小时).toBe(开工小时);
    for (let i = 0; i < 2; i += 1) 向东(状态);
    expect(状态.当前小时).toBe(11);
  });

  it('21 六格冲刺要 90 点 · 开局 100 够 · 走完正好停在 19:00（当天到头）', () => {
    expect(每格基准消耗 * 6).toBe(90);
    expect(每格耗时 * 6).toBe(12);                      // 时间上也正好一天
    const 状态 = 走廊局();
    expect(状态.野外体力).toBe(100);
    for (let i = 0; i < 6; i += 1) expect(向东(状态).成功).toBe(true);
    expect(状态.第几天).toBe(1);                        // ✍️ 不自动跨日
    expect(状态.当前小时).toBe(收工小时);
    expect(状态.野外体力).toBe(10);
  });

  it('22 体力剩 10 点时走一格 → 拒绝「体力不够」· 状态一点没变', () => {
    const 状态 = 走廊局();
    状态.野外体力 = 10;
    const 前 = 不许变(状态);
    expect(向东(状态)).toEqual({ 成功: false, 原因: '体力不够' });
    expect(快照(状态)).toBe(前);
  });
});
