import { 跨日 } from './结算';
import type { 操作结果, 游戏状态 } from './类型';

export function 结束当天(状态: 游戏状态): 操作结果 {
  if (状态.今天已结算) {
    // 🔴 幂等（判据 24/25）：刚跨过日就再点，不许跨第二次 ——
    //    旧代码判据写成「当前小时 > 7」，结果开局 07:00 就点不了（判据 26 挂过）。
    return { 成功: false, 原因: '今天已结算过了' };
  }
  跨日(状态);
  return { 成功: true, 原因: null };
}
