import { describe, it, expect } from 'vitest';
import { 新建商队 } from './资源';
import { 新建跨日链记账, 跨日结算, 修车并封顶, 耐久上限全队, 封顶耐久 } from './跨日链';
import { 日结算02 } from './日结算02';
import { 价格, 买补给 } from './地点服务';
import { 每车每天地形损耗, 战斗损耗, 弃车代价, 部位有后果 } from './车损';
import { 自然恢复 } from './士气';
import type { 串联状态 } from './跨日链';

/// 造一份能跑 跨日() 的最小 1B 状态
function 新串联(体力 = 50, 天气剩余 = 5): 串联状态 {
  const 空地图 = {
    宽: 3, 高: 3, 起点: { x: 1, y: 1 }, 终点: { x: 2, y: 2 },
    格子表: new Map(),
  };
  return {
    旅行: {
      当前坐标: { x: 1, y: 1 }, 第几天: 1, 当前小时: 18,
      野外体力: 体力, 体力上限: 100,
      当前天气: '晴朗', 天气剩余天数: 天气剩余,
      地图: 空地图 as never, 今天已结算: false,
    } as 串联状态['旅行'],
    商队: 新建商队(),
  };
}

describe('判据 1~4 · 三段链顺序与幂等', () => {
  it('判据 1　跨日一次：日期 +1 · 时钟回 07:00 · 体力 +50 封顶 · 天气段 −1', () => {
    const 状 = 新串联();
    状.旅行.野外体力 = 60;
    const 果 = 跨日结算(状, 新建跨日链记账(), 3);
    expect(果.第几天).toBe(2);
    expect(果.当前小时).toBe(7);
    expect(果.体力).toBe(100);            // 60 + 50 → 封顶 100
    expect(果.天气.剩余天数).toBe(4);      // 天气段 −1
  });

  it('判据 2　同日补给按出战人数扣（14 人 = 14 + 14）', () => {
    const 状 = 新串联();
    状.商队.资源.食物 = 30;
    状.商队.资源.清水 = 30;
    跨日结算(状, 新建跨日链记账(), 3);
    expect(状.商队.资源.食物).toBe(16);   // 30 − 14
    expect(状.商队.资源.清水).toBe(16);
  });

  it('判据 3　地形损耗按车辆数累加（3 车 1 天 = 4.5）', () => {
    const 状 = 新串联();
    状.商队.资源.耐久 = 100;
    const 果 = 跨日结算(状, 新建跨日链记账(), 3);
    expect(果.地形损耗量).toBe(4.5);       // 1.5 × 3 车 × 1 天
    expect(果.耐久).toBe(95.5);
  });

  it('判据 4　🔴 全链一次跨日，三条链各只执行一次（无重复扣）', () => {
    const 状 = 新串联();
    状.商队.资源.食物 = 100;
    状.商队.资源.耐久 = 100;
    const 果 = 跨日结算(状, 新建跨日链记账(), 3);
    expect(果.各链执行次数).toEqual({ 跨日: 1, 日结算: 1, 地形损耗: 1 });
    expect(状.商队.资源.食物).toBe(86);    // 只扣了一份 14
    expect(果.耐久).toBe(95.5);            // 只扣了一份 4.5
  });
});

describe('判据 5~8 · 自然恢复 / 买 / 修 / 断粮叠加', () => {
  it('判据 5　抵达城镇自然恢复 +1（≤4 时）· 同地点 20 天内不重复（冷却表在记账里）', () => {
    const 状 = 新串联();
    状.商队.资源.士气 = 2;   // 🔴 留 2 点余量：补一次到 3 仍 < 城镇上限 4，才能测到冷却分支
    const 账 = 新建跨日链记账(1);
    const 第一次 = 自然恢复(状.商队, '城镇', 账.今天, 账.士气冷却表);
    if (第一次.恢复了 > 0) 账.士气冷却表.set('城镇', 账.今天);
    expect(第一次.恢复了).toBe(1);
    expect(状.商队.资源.士气).toBe(3);   // 2 → 3，仍低于城镇上限 4
    // 第 10 天再来 → 冷却中
    const 第10天 = 自然恢复(状.商队, '城镇', 10, 账.士气冷却表);
    expect(第10天.恢复了).toBe(0);
    expect(第10天.原因).toContain('冷却中');
  });

  it('判据 6　买补给：钱/库存校验后货物入账（2.2 行为不变）', () => {
    const 状 = 新串联();
    状.商队.资源.金钱 = 100;
    const 果 = 买补给(状.商队, '大城', '食物', 1);
    expect(果.成功).toBe(true);
    expect(状.商队.资源.食物).toBe(5);
    expect(状.商队.资源.金钱).toBe(50);
  });

  it('判据 7　🔴 修车钱修 +20，但首次封顶到耐久上限 180', () => {
    expect(耐久上限全队).toBe(180);
    const 状 = 新串联();
    状.商队.资源.金钱 = 100;
    状.商队.资源.耐久 = 170;
    const 果 = 修车并封顶(状.商队, '大城', '花钱');
    expect(果.成功).toBe(true);
    expect(状.商队.资源.耐久).toBe(180);        // 170 + 20 → 封顶 180
    expect(果.恢复了多少耐久).toBe(10);          // 🔴 真正补进来的只有 10
    expect(状.商队.资源.金钱).toBe(90);          // 钱照扣 10
  });

  it('判据 8　断粮日士气 −1 且与其他惩罚叠加（2026-10-24 裁定）', () => {
    const 状 = 新串联();
    状.商队.资源.食物 = 0;
    状.商队.资源.清水 = 0;
    状.商队.资源.士气 = 10;
    const 果 = 跨日结算(状, 新建跨日链记账(), 3);
    expect(果.补给结算.施加了惩罚).toBe(true);
    expect(果.补给结算.士气变化).toBe(2);        // 断粮 + 断水 叠加 −2
    expect(状.商队.资源.士气).toBe(8);
  });
});

describe('判据 9~12 · 可重复跑 / 抽样 / 零改动 / 稳定性', () => {
  it('判据 9　验收脚本可重复跑（本条 = 串联纯函数，多次结果确定）', () => {
    const a = 跨日结算(新串联(), 新建跨日链记账(), 3);
    const b = 跨日结算(新串联(), 新建跨日链记账(), 3);
    expect(a.第几天).toBe(b.第几天);
    expect(a.地形损耗量).toBe(b.地形损耗量);
  });

  it('判据 10　抽样复核 2.0~2.3 各≥3 条（士气上限10/出发14人3车 · 扣14+14 · 价表 · 地形1.5）', () => {
    // —— 2.0 资源字段（抽 3 条）——
    expect(新建商队().资源.士气).toBe(6);          // 2026-10-24 裁定士气初值 6
    expect(新建商队().出战人数).toBe(14);
    expect(新建商队().车辆数).toBe(3);
    // —— 2.1 商队消耗（抽 3 条）——
    const 扣 = 新建商队(); 扣.资源.食物 = 10; 扣.资源.清水 = 50; 扣.资源.士气 = 0;
    const 扣果 = 日结算02(扣);
    expect(扣.资源.食物).toBe(0);                  // 10 份不够 14 人 → 扣到 0 为止
    expect(扣果.扣了多少食物).toBe(10);            // 只扣到有的一份
    expect(扣.资源.士气).toBe(0);                  // 士气 0 时断粮也不会变负
    // —— 2.2 地点服务（抽 3 条）——
    expect(价格.大城.食物).toBe(10);
    expect(买补给(新建商队(), '村庄', '零件', 1).原因).toBe('村庄不卖零件');
    expect(买补给(新建商队(), '城镇', '清水', 1).原因).toBe('城镇不卖清水');
    // —— 2.3 车损与士气（抽 3 条）——
    expect(每车每天地形损耗).toBe(1.5);
    expect(战斗损耗(3, '普通')).toBe(15);
    expect(部位有后果('损坏')).toBe(true);
    expect(弃车代价('大型').货舱减少).toBe(900);
  });

  it('判据 11　封顶耐久夹在 [0, 180]（串联兜住上下界）', () => {
    const 状 = 新串联();
    状.商队.资源.耐久 = 999; 封顶耐久(状.商队); expect(状.商队.资源.耐久).toBe(180);
    状.商队.资源.耐久 = -50; 封顶耐久(状.商队); expect(状.商队.资源.耐久).toBe(0);
  });

  it('判据 12　🔴 跨日链 30 天连跑：不崩、无负数、每天稳定扣（无重复扣）', () => {
    const 状 = 新串联();
    状.商队.资源.食物 = 1000;
    状.商队.资源.清水 = 1000;
    状.商队.资源.耐久 = 180;
    状.商队.资源.士气 = 10;
    const 账 = 新建跨日链记账(1);
    for (let 天 = 1; 天 <= 30; 天++) {
      // 模拟每天开工把保险丝清回 false（正常游戏由 时间.推进() 做；这里直接跨日链）
      状.旅行.今天已结算 = false;
      跨日结算(状, 账, 3);
      expect(状.商队.资源.食物).toBeGreaterThanOrEqual(0);
      expect(状.商队.资源.耐久).toBeGreaterThanOrEqual(0);
      expect(状.商队.资源.士气).toBeGreaterThanOrEqual(0);
    }
    expect(状.旅行.第几天).toBe(31);          // 1 + 30
    // 耐久 180，每天 −4.5，到 0 封底：40 天才磨完，30 天应还剩
    expect(状.商队.资源.耐久).toBe(180 - 4.5 * 30);
  });
});
