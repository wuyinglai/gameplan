export type 资源名 =
  | '食物'      // 🔴 1 份 = 1 人 1 天口粮；1 格装 5 份（后期可升 10 份/格）—— 3A:35
  | '清水'      // 🔴 1 份 = 1 人 1 天饮水（与食物同量）；1 格 = 1 水箱 = 3 份 —— 3A:36
  | '药包'      // 🔴 战斗后消耗，用于治疗队员；🔴 无「药品」概念 —— 3A:38
  | '零件'      // 🔴 1 零件 = 10 耐久 —— 3A:322（§2.4）
  | '脏水';     // 🔴 野外常见水源，🔴 未净化直饮挂负面 —— 3A:37

/** 🔴 商队资源（八个字段，🔴 一个不少、一个不加） */
export interface 商队资源 {
  食物: number;   // 份
  清水: number;   // 份
  药包: number;   // 个
  零件: number;   // 个
  脏水: number;   // 份

  // 🔴 不设初始金币锚：钱只从跑商与委托来（3A:40、3A:822 · 用户 2026-10-14 定）
  金钱: number;

  // 🔴 耐久按车算：各车相对耐久上限之和 = 车队总上限（3A:39）
  //    🔴 第 4 步才拆成车，这里先一个总数
  耐久: number;

  // 🔴 士气：断粮 −1/天（3A §4）· 抵达城/镇/驿 +1（有阈值与 20 天冷却，3A:515-528）
  士气: number;
}

/** 🔴 商队状态（本阶段只放资源 + 开局人数/车辆） */
export interface 商队状态 {
  资源: 商队资源;
  /** 🔴 开局 14 人（核心成员，含 3 护卫 + 车夫 + 后勤，3A:83）· 后期可招募，🔴 不设硬上限 */
  出战人数: number;
  /** 🔴 开局 3 辆小型货车（300 格/辆 = 900 格，3A:351、3A:669、6A:520） */
  车辆数: number;
}

