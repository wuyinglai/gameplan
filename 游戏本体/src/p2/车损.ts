/** 🔴 3A:198-211 四个部位 */
export type 部位 = '车轮' | '车身' | '车架' | '车篷';

/** 🔴 3A:213-222 四档（前三档纯显示，只有「损坏」有后果） */
export type 部位档位 = '完好' | '磨损' | '破损' | '损坏';

/** 🔴 3A:281 每车每天 −1.5（每车独立，不是全队） */
export const 每车每天地形损耗 = 1.5;

/** 🔴 3A:285-289 战斗损耗 —— 🔴 每车口径（3A:291），全队合计 = 本表值 × 车辆数 */
export const 战斗每车损耗: Record<'普通' | '精英' | 'Boss', number> = {
  普通: 5,
  精英: 10,
  Boss: 50,          // 🔴 A 类原文「−50 以上」，代码取不到「以上」→ 取下界 50（指令 §7.1 的判断）
};

/**
 * 地形损耗：每车每天 −1.5 × 车辆数 × 天数（3A:281）。
 * @returns 这段时间**全队**要扣的耐久总量
 */
export function 地形损耗(车辆数: number, 天数: number): number {
  return 每车每天地形损耗 * 车辆数 * 天数;
}

/**
 * 战斗损耗（3A:285-291）—— 🔴 传进来的是「每车损耗」，本函数按每车口径 × 车辆数得全队合计。
 * 判据 3 的口径就是 A 类那句「每车 5 = 全队 15」。
 */
export function 战斗损耗(车辆数: number, 类型: '普通' | '精英' | 'Boss'): number {
  return 战斗每车损耗[类型] * 车辆数;
}

/**
 * 🔴 弃车代价（3A:262-263，永久）：货舱按车型 −300/−600/−900 · 耐久上限每辆车 −60。
 * 🔴 车夫不减人（3A:265）—— 所以返回值里🔴 没有「减人」这一项。
 * 🔴 只算数据，不做弃车流程（流程归 5B 交互层）。
 */
export function 弃车代价(车型: '小型' | '中型' | '大型'): { 货舱减少: number; 耐久上限减少: number } {
  const 货舱 = { 小型: 300, 中型: 600, 大型: 900 }[车型];   // 3A:262
  return { 货舱减少: 货舱, 耐久上限减少: 60 };                // 3A:263
}

/**
 * 档位有没有后果（3A:213-222）：🔴 只有「损坏」有后果，前三档只是标签。
 * 具体后果（车走不动 / 货物受损）归后续阶段 —— 本步只给判定。
 */
export function 部位有后果(档位: 部位档位): boolean {
  return 档位 === '损坏';
}
