import { 士气上限 } from './资源';
import type { 商队状态, 地点类型 } from './资源';

/**
 * 🔴 士气上限 —— 数值源只有一个：`资源.ts` 的 `士气上限`（3A:512）。
 * ✍️ 指令 §3.2 写的是在这里再写一遍 `= 10`，但它自己那条注释说「不重复定义数值源」——
 *    所以这里🔴 引用已有常量而不是重写数字（回执问题①）。口径与判据数字不变。
 */
export const 士气上限常量 = 士气上限;

/**
 * 🔴 3A:505-507 消费三档（⚠️ A 类自标参考值）——
 * 🔴 判据把这三个价格与效果锁死；将来调平只改这张表。
 * 「生效条件」= A 类的「士气 N 以下有效」，按**严格小于**实现（与 §4.6 表头「低于此值才恢复」同口径；
 *    A 类对消费档没写明含不含 6 —— 回执问题③，待裁定）。
 */
export const 士气消费表 = [
  { 名字: '酒馆小聚', 价格: 150, 恢复: 1, 生效条件: 6 },        // 3A:505
  { 名字: '商队宴席', 价格: 400, 恢复: 1, 生效条件: 10 },       // 3A:506
  { 名字: '豪华休整', 价格: 800, 恢复: 2, 生效条件: null },     // 3A:507 不限士气
] as const;

export interface 士气消费结果 {
  成功: boolean;
  原因: string | null;
  花了多少金: number;
  恢复了: number;
}

/**
 * 🔴 花钱恢复士气（3A:499-513）。可多次（3A:511）· 封顶 10（3A:512）·
 * 🔴🔴 绕开自然恢复的上限与冷却（3A:513）—— 所以本函数🔴 不看冷却表、不看 §4.6 的地点档上限。
 *
 * 拒绝顺序：已到总上限 → 该档生效条件不满足 → 钱不够。任一拒绝状态一字不变。
 */
export function 士气消费(
  状态: 商队状态, 档名: '酒馆小聚' | '商队宴席' | '豪华休整',
): 士气消费结果 {
  const 空: 士气消费结果 = { 成功: false, 原因: '', 花了多少金: 0, 恢复了: 0 };
  const 档 = 士气消费表.find((x) => x.名字 === 档名)!;

  if (状态.资源.士气 >= 士气上限常量) return { ...空, 原因: '士气已到上限' };               // 3A:512
  if (档.生效条件 !== null && 状态.资源.士气 >= 档.生效条件) {
    return { ...空, 原因: `${档名}只在士气 ${档.生效条件} 以下有效` };                        // 3A:505-506
  }
  if (状态.资源.金钱 < 档.价格) return { ...空, 原因: '钱不够' };

  状态.资源.金钱 -= 档.价格;
  const 前 = 状态.资源.士气;
  状态.资源.士气 = Math.min(士气上限常量, 前 + 档.恢复);                                      // 3A:507/512 封顶
  return { 成功: true, 原因: null, 花了多少金: 档.价格, 恢复了: 状态.资源.士气 - 前 };
}

/** 🔴 3A:521-525 自然恢复的地点档上限（🔴 低于此值才恢复；村庄 / 野外 = 0 不恢复） */
export function 自然恢复上限(地点: 地点类型): number {
  return { 大城: 6, 小城: 6, 城镇: 4, 驿站: 4, 村庄: 0 }[地点];   // 3A:521-524
}

/** 🔴 3A:517 / 3A:530 同一地点每 20 天最多触发一次自然恢复 */
export const 自然恢复冷却天数 = 20;

export interface 自然恢复结果 {
  恢复了: number;
  原因: string;
}

/**
 * 抵达地点时的自然恢复（3A:515-532）：所有能恢复的地点一律 +1。
 *
 * 🔴 冷却表由调用方传入（`地点 → 上次触发自然恢复的那一天`），🔴 本函数不写冷却表本身 ——
 *    记账归 2.4 串联的跨日链（指令 §7.3）。
 * 🔴 花过钱不影响这里（3A:513：那两根闸只管自然恢复）。
 */
export function 自然恢复(
  状态: 商队状态, 地点: 地点类型, 今日: number, 冷却表: Map<string, number>,
): 自然恢复结果 {
  const 上限 = 自然恢复上限(地点);
  if (上限 === 0) return { 恢复了: 0, 原因: `${地点}不恢复士气` };                    // 3A:524-525
  if (状态.资源.士气 >= 上限) return { 恢复了: 0, 原因: `士气 ${上限} 以上不自然恢复` };   // 3A:521-523
  const 上次 = 冷却表.get(地点);
  if (上次 !== undefined && 今日 - 上次 < 自然恢复冷却天数) {
    return { 恢复了: 0, 原因: `${地点} ${自然恢复冷却天数} 天冷却中` };                 // 3A:530
  }
  const 前 = 状态.资源.士气;
  状态.资源.士气 = Math.min(士气上限常量, 前 + 1);
  return { 恢复了: 状态.资源.士气 - 前, 原因: 'ok' };
}

/**
 * 🔴 3A:495-496 扣士气双闸：同一场战斗 ≤ 3 · 同一天 ≤ 3。
 *
 * ✍️ 指令 §3.2 的签名多带一个从不使用的 `状态` 参数，而 §4 判据 16 是按
 *    `当日士气扣减上限(拟扣, 当日已扣)` 两参调用的 —— 🔴 以判据为准（回执问题②）。
 * 🔴 崩溃撤退不扣士气（3A:496），所以它🔴 不该调本函数、也不占额度 —— 记账归调用方。
 * 🔴 2.1 的断粮扣士气不走这里（那是「叠加」惩罚，2026-10-24 裁定，不许改）。
 *
 * @param 拟扣 打算扣多少（可为严重重伤加权后的数）
 * @param 当日已扣 今天已经扣掉的点数
 */
export function 当日士气扣减上限(拟扣: number, 当日已扣: number): number {
  const 单场封顶 = Math.min(拟扣, 3);                          // 3A:495
  return Math.min(单场封顶, Math.max(0, 3 - 当日已扣));          // 3A:496
}
