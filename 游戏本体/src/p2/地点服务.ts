export interface 买的结果 {
  成功: boolean;
  原因: string | null;
  /** 🔴 实际买到的份数 / 个数（🔴 四种分开记，3A:93） */
  买到食物: number;
  买到清水: number;
  买到零件: number;
  买到药包: number;
  花了多少金: number;
}

/**
 * 🔴 在某个地点买补给 —— 🔴 一次只买一种（指令 §8.1），要买几种就调几次。
 *
 * 🔴 拒绝的顺序：格数 → 这地方卖不卖 → 钱够不够 → 库存够不够，
 *    🔴🔴 任一拒绝都**不改动状态一个字段**（判据 9 / 10 / 11 / 12 / 17）。
 *
 * @param 格数 买几格（🔴 按格买不拆份，3A:60）
 */
export function 买补给(
  状态: 商队状态, 地点: 地点类型, 种类: '食物' | '清水' | '零件' | '药包', 格数: number,
): 买的结果 {
  const 空: 买的结果 = {
    成功: false, 原因: '', 买到食物: 0, 买到清水: 0, 买到零件: 0, 买到药包: 0, 花了多少金: 0,
  };

  if (格数 <= 0) return { ...空, 原因: '格数不对' };

  const 单价 = 价格[地点][种类];
  if (单价 === 0) return { ...空, 原因: `${地点}不卖${种类}` };

  const 每格 = 每格份数[种类];
  const 总份数 = 格数 * 每格;
  // 🔴 单价是「每份 / 每个」价（2A:199 锚）→ 总价 = 单价 × 份数（🔴 不是 × 格数）
  const 总价 = 单价 * 总份数;

  if (状态.资源.金钱 < 总价) return { ...空, 原因: '钱不够' };

  // 🔴 null = 近似不限（大小城市）· 数值 = 单次上限，超了不卖
  const 上限 = 库存上限[地点][种类];
  if (上限 !== null && 总份数 > 上限) return { ...空, 原因: '库存不够' };

  // 🔴 扣钱 + 进货物（🔴 四种分开记，不许合并，3A:93）
  状态.资源.金钱 -= 总价;
  const 结果: 买的结果 = {
    成功: true, 原因: null,
    买到食物: 0, 买到清水: 0, 买到零件: 0, 买到药包: 0,
    花了多少金: 总价,
  };
  if (种类 === '食物') { 状态.资源.食物 += 总份数; 结果.买到食物 = 总份数; }
  else if (种类 === '清水') { 状态.资源.清水 += 总份数; 结果.买到清水 = 总份数; }
  else if (种类 === '零件') { 状态.资源.零件 += 总份数; 结果.买到零件 = 总份数; }
  else { 状态.资源.药包 += 总份数; 结果.买到药包 = 总份数; }
  return 结果;
}

