/** 🔴 花钱修一次要多少金（3A:319-321）· 🔴 0 = 这地方不能花钱修（村庄：2A:183） */
export const 修理价格: Record<地点类型, number> = {
  大城: 10, 小城: 10, 城镇: 30, 驿站: 25, 村庄: 0,
};

/** 🔴 花钱修一次恢复多少耐久（3A:319-321）—— 🔴 三档价钱恢复量都是 20 */
export const 修理恢复 = 20;

/** 🔴 用零件修一次恢复多少耐久（3A:322「使用零件·普通」）—— 🔴 有修补师那一档归 6B */
export const 零件修复耐久 = 10;

export interface 修车结果 {
  成功: boolean;
  原因: string | null;
  花了多少金: number;
  用了几个零件: number;
  恢复了多少耐久: number;
}

/**
 * 🔴 修车两种方式：花钱（按地点价，3A:319-321）· 用零件（1 个 = 10 耐久，3A:322）。
 *
 * 🔴🔴 这里🔴 不做耐久上限检查 —— A 类 `车队耐久上限` 仍是 0（未定，见 资源.ts:92），
 *    🔴 指令 §8.4 明令不许自己定一个上限数字，🔴 上限由调用方保证（2B 后面的中阶段）。
 */
export function 修车(
  状态: 商队状态, 地点: 地点类型, 方式: '花钱' | '用零件',
): 修车结果 {
  const 空: 修车结果 = { 成功: false, 原因: '', 花了多少金: 0, 用了几个零件: 0, 恢复了多少耐久: 0 };

  if (方式 === '花钱') {
    const 单价 = 修理价格[地点];
    if (单价 === 0) return { ...空, 原因: `${地点}不能花钱修车` };
    if (状态.资源.金钱 < 单价) return { ...空, 原因: '钱不够' };
    状态.资源.金钱 -= 单价;
    状态.资源.耐久 += 修理恢复;
    return { 成功: true, 原因: null, 花了多少金: 单价, 用了几个零件: 0, 恢复了多少耐久: 修理恢复 };
  }

  // 🔴 用零件（不看地点 —— 零件是随身物资，在任何地点都能用）
  if (状态.资源.零件 < 1) return { ...空, 原因: '零件不够' };
  状态.资源.零件 -= 1;
  状态.资源.耐久 += 零件修复耐久;
  return { 成功: true, 原因: null, 花了多少金: 0, 用了几个零件: 1, 恢复了多少耐久: 零件修复耐久 };
}
