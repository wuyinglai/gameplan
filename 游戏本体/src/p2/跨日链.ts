/** 🔴 3A:281「已超单辆 60 上限」→ 单车 60 */
export const 耐久上限每车 = 60;
/** 🔴 3 辆货车 → 全队 180（3A:293 按 180 算过 Boss 战占比） */
export const 耐久上限全队 = 耐久上限每车 * 3;

/** 把车队耐久夹在 [0, 上限] 之间 —— 🔴 2.2/2.3 都不封顶，封顶统一放这里 */
export function 封顶耐久(状态: 商队状态): void {
  状态.资源.耐久 = Math.max(0, Math.min(耐久上限全队, 状态.资源.耐久));
}

