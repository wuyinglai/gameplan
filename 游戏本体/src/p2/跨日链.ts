/**
 * 🔴 跨日链持有的两笔账：
 *   · 士气冷却表 —— `地点 → 上次触发自然恢复的那一天`（3A:530 同地点 20 天一次）
 *   · 当日已扣士气 —— 3A:496「同一天最多 −3」的记账主体
 * 🔴 跨日时 `当日已扣` 清零；冷却表按地点写「今天」。
 */
export interface 跨日链记账 {
  士气冷却表: Map<地点类型, number>;
  当日已扣士气: number;
  今天: number;
}

export function 新建跨日链记账(今天 = 1): 跨日链记账 {
  return { 士气冷却表: new Map<地点类型, number>(), 当日已扣士气: 0, 今天 };
}

// ============================================================================
// 🔴 串联状态（1B 的旅行状态 + 2B 的商队状态装一起，两个对象本身都不改形状）
// ============================================================================

export interface 串联状态 {
  旅行: 游戏状态;
  商队: 商队状态;
}

export interface 跨日链结果 {
  /** ① 1B 段原样透传（跨日是 void，这里回显关键四件套） */
  第几天: number;
  当前小时: number;
  体力: number;
  天气: { 名字: string; 剩余天数: number };
  /** ② 2B 补给/士气段原样透传 */
  补给结算: 跨日结算结果;
  /** ③ 车损段 */
  地形损耗量: number;
  耐久: number;
  /** 🔴 全链只各调一次的证据 */
  各链执行次数: { 跨日: 1; 日结算: 1; 地形损耗: 1 };
  /** 记账快照 */
  记账: { 今天: number; 当日已扣士气: number };
}

/**
 * 🔴 一次跨日 = 三段链按固定顺序各跑一次。
 *
 * @param 状态    串联状态（旅行 + 商队）
 * @param 记账    跨日链持有的两笔账（原地更新：冷却表写今天、当日已扣清零）
 * @param 车辆数  算地形损耗用（一般传 商队.车辆数；显式传是为了让判据能钉死）
 * @param 天数    默认 1；🔴 只放大「折旧」，跨日/日结算🔴 仍只各一次（幂等是 1B/2.1 自己的保险丝）
 */
export function 跨日结算(
  状态: 串联状态, 记账: 跨日链记账, 车辆数: number, 天数 = 1,
): 跨日链结果 {
  // —— ① 1B：日期 / 时钟 / 体力回复 / 天气段（顺序在 1B 内部，本文件不碰）——
  跨日(状态.旅行);

  // —— ② 2B：扣补给 + 断粮惩罚（士气）——
  const 补给结算: 跨日结算结果 = 日结算02(状态.商队);

  // —— ③ 车损：地形折旧（每车每天 −1.5 × 车辆数 × 天数），随后统一封顶 ——
  const 地形损耗量 = 地形损耗(车辆数, 天数);
  状态.商队.资源.耐久 -= 地形损耗量;
  封顶耐久(状态.商队);

  // —— ④ 记账推进：新的一天，当日已扣清零 ——
  记账.今天 = 状态.旅行.第几天;
  记账.当日已扣士气 = 0;

  return {
    第几天: 状态.旅行.第几天,
    当前小时: 状态.旅行.当前小时,
    体力: 状态.旅行.野外体力,
    天气: { 名字: 状态.旅行.当前天气, 剩余天数: 状态.旅行.天气剩余天数 },
    补给结算,
    地形损耗量,
    耐久: 状态.商队.资源.耐久,
    各链执行次数: { 跨日: 1, 日结算: 1, 地形损耗: 1 },
    记账: { 今天: 记账.今天, 当日已扣士气: 记账.当日已扣士气 },
  };
}

/**
 * 🔴 花钱修车 + 封顶（判据 7：+20 但不许超过 180）。
 * 2.2 的 `修车()` 本身不封顶（当时耐久上限未定），🔴 封顶在这一层补，2.2 一个字不改。
 */
export function 修车并封顶(状态: 商队状态, 地点: 地点类型, 方式: '花钱' | '用零件'): 修车结果 {
  const 前 = 状态.资源.耐久;                    // 🔴 必须在 修车() 之前取，否则回显会算成负数
  const 果 = 修车(状态, 地点, 方式);
  if (果.成功) {
    封顶耐久(状态);
    果.恢复了多少耐久 = 状态.资源.耐久 - 前;      // 🔴 回显「真正补进来的」而不是账面 20
  }
  return 果;
}

/** 🔴 调试/验收用一句话（四种资源分开写，3A:93） */
export function 描述串联(状态: 串联状态): string {
  const r = 状态.商队.资源;
  return `第 ${状态.旅行.第几天} 天 ${状态.旅行.当前小时}:00 · 体力 ${状态.旅行.野外体力}`
    + ` · 食物 ${r.食物} · 清水 ${r.清水} · 零件 ${r.零件} · 药包 ${r.药包}`
    + ` · 金钱 ${r.金钱} · 耐久 ${r.耐久}/${耐久上限全队} · 士气 ${r.士气}/${士气上限}`;
}
