describe('判据 9~12 · 士气消费（3A:499-513）', () => {
  it('判据 9　钱 1000 · 士气 5 · 酒馆小聚 → 士气 6 · 钱 850', () => {
    const 状态 = 商队({ 金钱: 1000, 士气: 5 });
    const 果 = 士气消费(状态, '酒馆小聚');
    expect(果.成功).toBe(true);
    expect(状态.资源.士气).toBe(6);
    expect(状态.资源.金钱).toBe(850);
    expect(果.花了多少金).toBe(150);
    expect(果.恢复了).toBe(1);
  });

  it('判据 10　🔴 士气 7 时酒馆小聚 → 拒绝「只在士气 6 以下有效」（3A:505）· 状态没变', () => {
    const 状态 = 商队({ 金钱: 1000, 士气: 7 });
    const 前 = JSON.stringify(状态);
    const 果 = 士气消费(状态, '酒馆小聚');
    expect(果.成功).toBe(false);
    expect(果.原因).toBe('酒馆小聚只在士气 6 以下有效');
    没变(状态, 前);
  });

  it('判据 11　🔴 士气 10 时商队宴席 → 拒绝「士气已到上限」（3A:512）· 状态没变', () => {
    const 状态 = 商队({ 金钱: 10000, 士气: 10 });
    const 前 = JSON.stringify(状态);
    const 果 = 士气消费(状态, '商队宴席');
    expect(果.成功).toBe(false);
    expect(果.原因).toBe('士气已到上限');
    没变(状态, 前);
  });

  it('判据 12　🔴 豪华休整 800 金 +2，但士气 9 只到 10（封顶，3A:507+512）', () => {
    const 状态 = 商队({ 金钱: 1000, 士气: 9 });
    const 果 = 士气消费(状态, '豪华休整');
    expect(果.成功).toBe(true);
    expect(士气上限常量).toBe(10);
    expect(状态.资源.士气).toBe(10);              // 🔴 不是 11
    expect(果.恢复了).toBe(1);                    // 只补得进 1 点
    expect(状态.资源.金钱).toBe(200);              // 🔴 钱照扣 800
    expect(士气消费表.length).toBe(3);
  });
});

describe('判据 13~15 · 自然恢复（3A:515-532）', () => {
  it('判据 13　自然恢复(士气 5, 大城, 今日 100, 空冷却表) → +1 → 6', () => {
    const 状态 = 商队({ 士气: 5 });
    const 果 = 自然恢复(状态, '大城', 100, new Map());
    expect(果.恢复了).toBe(1);
    expect(状态.资源.士气).toBe(6);
    expect(自然恢复上限('大城')).toBe(6);           // 3A:521
    expect(自然恢复上限('小城')).toBe(6);
  });

  it('判据 14　🔴 士气 7 进大城不恢复（城市上限 6）· 士气 5 进城镇也不恢复（城镇上限 4）', () => {
    const 城 = 商队({ 士气: 7 });
    const 城前 = JSON.stringify(城);
    expect(自然恢复(城, '大城', 100, new Map()).恢复了).toBe(0);
    没变(城, 城前);

    const 镇 = 商队({ 士气: 5 });
    const 镇前 = JSON.stringify(镇);
    expect(自然恢复上限('城镇')).toBe(4);            // 3A:522
    expect(自然恢复上限('驿站')).toBe(4);            // 3A:523
    expect(自然恢复(镇, '城镇', 100, new Map()).恢复了).toBe(0);
    没变(镇, 镇前);

    const 村 = 商队({ 士气: 1 });                    // 3A:524 村庄 = 0，再低也不恢复
    expect(自然恢复上限('村庄')).toBe(0);
    expect(自然恢复(村, '村庄', 100, new Map()).恢复了).toBe(0);
    expect(村.资源.士气).toBe(1);
  });

  it('判据 15　🔴 同一地点 20 天冷却：第 110 天（距上次 10 天）不恢复；第 121 天恢复', () => {
    const 冷却中 = 商队({ 士气: 3 });
    const 冷却中前 = JSON.stringify(冷却中);
    const 表 = new Map<string, number>([['大城', 100]]);
    expect(自然恢复冷却天数).toBe(20);               // 3A:530
    expect(自然恢复(冷却中, '大城', 110, 表).原因).toContain('冷却中');
    没变(冷却中, 冷却中前);

    const 到期 = 商队({ 士气: 3 });
    expect(自然恢复(到期, '大城', 121, 表).恢复了).toBe(1);   // 121 − 100 = 21 ≥ 20
    expect(到期.资源.士气).toBe(4);

    const 别处 = 商队({ 士气: 3 });                   // 冷却是🔴 按地点分开记的
    expect(自然恢复(别处, '城镇', 110, 表).恢复了).toBe(1);   // 城镇没进冷却表 → 照恢复（士气 3 < 上限 4）
    expect(别处.资源.士气).toBe(4);
  });
});

describe('判据 16 · 扣士气双闸（3A:495-496）', () => {
  it('判据 16　当日士气扣减上限(5, 0) = 3（单场封顶）· (2, 2) = 1（当日只剩 1 点额度）', () => {
    expect(当日士气扣减上限(5, 0)).toBe(3);
    expect(当日士气扣减上限(2, 2)).toBe(1);
    // 🔴 边界：当日已扣满 3 → 再拟扣多少都是 0；拟扣 0 → 0
    expect(当日士气扣减上限(5, 3)).toBe(0);
    expect(当日士气扣减上限(0, 0)).toBe(0);
    // 🔴 拟扣小于封顶时按拟扣走（不许把小惩罚放大成 3）
    expect(当日士气扣减上限(1, 0)).toBe(1);
  });
});
