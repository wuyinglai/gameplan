import { describe, it, expect } from 'vitest';
import { 新建商队 } from './资源';
import {
  价格, 每格份数, 库存上限, 买补给, 修理价格, 修理恢复, 零件修复耐久, 修车,
} from './地点服务';
import type { 商队状态 } from './资源';

/** 造一个商队：只填测试要用的字段，其余留 新建商队() 的原值 */
function 商队(初值: {
  金钱?: number; 食物?: number; 清水?: number; 零件?: number; 药包?: number; 耐久?: number;
}): 商队状态 {
  const 状态 = 新建商队();
  状态.资源.金钱 = 初值.金钱 ?? 0;
  状态.资源.食物 = 初值.食物 ?? 0;
  状态.资源.清水 = 初值.清水 ?? 0;
  状态.资源.零件 = 初值.零件 ?? 0;
  状态.资源.药包 = 初值.药包 ?? 0;
  状态.资源.耐久 = 初值.耐久 ?? 0;
  return 状态;
}

/// 拒绝类判据统一核对：🔴 状态一个字段都不许变
function 没变(状态: 商队状态, 前: string) {
  expect(JSON.stringify(状态)).toBe(前);
}

