describe('判据 7~12 · 买补给（按格买、拒绝时状态不动）', () => {
  it('判据 7　大城买 1 格食物（5 份）· 钱 100 → 食物 +5 · 钱 −50（10 金 × 5 份）', () => {
    const 状态 = 商队({ 金钱: 100 });
    const 果 = 买补给(状态, '大城', '食物', 1);
    expect(果.成功).toBe(true);
    expect(每格份数.食物).toBe(5);                    // 3A:35
    expect(状态.资源.食物).toBe(5);
    expect(状态.资源.金钱).toBe(50);
    expect(果.买到食物).toBe(5);
    expect(果.花了多少金).toBe(50);
  });

  it('判据 8　🔴 买完四种资源分开断言（没买的就是 0，3A:93）', () => {
    const 状态 = 商队({ 金钱: 100 });
    买补给(状态, '大城', '食物', 1);
    expect(状态.资源.食物).toBe(5);
    expect(状态.资源.清水).toBe(0);      // 🔴 没买清水
    expect(状态.资源.零件).toBe(0);      // 🔴 没买零件
    expect(状态.资源.药包).toBe(0);      // 🔴 没买药包
  });

  it('判据 9　🔴 钱不够（钱 5，要 50）→ 拒绝「钱不够」· 状态一点没变', () => {
    const 状态 = 商队({ 金钱: 5 });
    const 前 = JSON.stringify(状态);
    const 果 = 买补给(状态, '大城', '食物', 1);
    expect(果.成功).toBe(false);
    expect(果.原因).toBe('钱不够');
    没变(状态, 前);
  });

  it('判据 10　🔴 村庄买零件 → 拒绝「村庄不卖零件」（2A §6）· 状态没变', () => {
    const 状态 = 商队({ 金钱: 500 });
    const 前 = JSON.stringify(状态);
    const 果 = 买补给(状态, '村庄', '零件', 1);
    expect(果.成功).toBe(false);
    expect(果.原因).toBe('村庄不卖零件');
    没变(状态, 前);
  });

  it('判据 11　🔴 城镇买清水 → 拒绝（A 类清水价未定 → 填 0 → 视作不卖，2A:199）· 状态没变', () => {
    const 状态 = 商队({ 金钱: 500 });
    const 前 = JSON.stringify(状态);
    const 果 = 买补给(状态, '城镇', '清水', 1);
    expect(果.成功).toBe(false);
    expect(果.原因).toBe('城镇不卖清水');
    没变(状态, 前);
  });

  it('判据 12　🔴 买 0 格 / 负数格 → 拒绝「格数不对」· 状态没变', () => {
    const 状态 = 商队({ 金钱: 500 });
    const 前 = JSON.stringify(状态);
    expect(买补给(状态, '大城', '食物', 0).原因).toBe('格数不对');
    expect(买补给(状态, '大城', '食物', -3).原因).toBe('格数不对');
    没变(状态, 前);
  });
});

describe('判据 13~16 · 修车（3A:319-322）', () => {
  it('判据 13　大城花钱修（钱 100）→ 耐久 +20 · 钱 −10', () => {
    const 状态 = 商队({ 金钱: 100 });
    const 果 = 修车(状态, '大城', '花钱');
    expect(修理价格.大城).toBe(10);
    expect(修理恢复).toBe(20);
    expect(果.成功).toBe(true);
    expect(状态.资源.耐久).toBe(20);
    expect(状态.资源.金钱).toBe(90);
  });

  it('判据 14　🔴 驿站花钱修 → 钱 −25 · 耐久 +20', () => {
    const 状态 = 商队({ 金钱: 100 });
    const 果 = 修车(状态, '驿站', '花钱');
    expect(果.花了多少金).toBe(25);
    expect(状态.资源.金钱).toBe(75);
    expect(状态.资源.耐久).toBe(20);
  });

  it('判据 15　🔴 用零件修（零件 1 个）→ 零件 −1 · 耐久 +10 · 🔴 钱不变', () => {
    const 状态 = 商队({ 金钱: 100, 零件: 1 });
    const 果 = 修车(状态, '城镇', '用零件');
    expect(零件修复耐久).toBe(10);
    expect(果.用了几个零件).toBe(1);
    expect(果.恢复了多少耐久).toBe(10);
    expect(状态.资源.零件).toBe(0);
    expect(状态.资源.耐久).toBe(10);
    expect(状态.资源.金钱).toBe(100);        // 🔴 一分没花
  });

  it('判据 16　🔴 村庄花钱修 → 拒绝「村庄不能花钱修车」（2A:183）· 状态没变', () => {
    const 状态 = 商队({ 金钱: 100 });
    const 前 = JSON.stringify(状态);
    const 果 = 修车(状态, '村庄', '花钱');
    expect(果.成功).toBe(false);
    expect(果.原因).toBe('村庄不能花钱修车');
    没变(状态, 前);
  });
});

describe('判据 17~19 · 库存上限（2A §7.2 区间下限）', () => {
  it('判据 17　🔴 城镇买 5 格食物（25 份 > 上限 20）→ 拒绝「库存不够」· 状态没变', () => {
    const 状态 = 商队({ 金钱: 500 });
    const 前 = JSON.stringify(状态);
    const 果 = 买补给(状态, '城镇', '食物', 5);
    expect(库存上限.城镇.食物).toBe(20);            // 2A:209 区间 20–40 的下限
    expect(果.成功).toBe(false);
    expect(果.原因).toBe('库存不够');
    没变(状态, 前);
  });

  it('判据 18　城镇买 4 格食物（正好 20 份 · 钱 500）→ 食物 +20 · 钱 −300', () => {
    const 状态 = 商队({ 金钱: 500 });
    const 果 = 买补给(状态, '城镇', '食物', 4);
    expect(果.成功).toBe(true);
    expect(状态.资源.食物).toBe(20);
    expect(状态.资源.金钱).toBe(200);              // 15 金 × 20 份 = 300
    expect(果.花了多少金).toBe(300);
  });

  it('判据 19　🔴 村庄 2 格食物（10 份 · 单价 20）成功扣 200；3 格（15 份 > 10）拒绝', () => {
    const 成 = 商队({ 金钱: 500 });
    const 果 = 买补给(成, '村庄', '食物', 2);
    expect(库存上限.村庄.食物).toBe(10);            // 2026-10-24 裁定「约 10 份」
    expect(果.成功).toBe(true);
    expect(成.资源.食物).toBe(10);
    expect(成.资源.金钱).toBe(300);                // 20 金 × 10 份 = 200

    const 拒 = 商队({ 金钱: 500 });
    const 前 = JSON.stringify(拒);
    const 果2 = 买补给(拒, '村庄', '食物', 3);
    expect(果2.成功).toBe(false);
    expect(果2.原因).toBe('库存不够');
    没变(拒, 前);
  });
});

