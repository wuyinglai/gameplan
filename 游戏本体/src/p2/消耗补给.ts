import type { 商队状态 } from './资源';

// ============================================================================
// 🔴 要扣多少
// ============================================================================

/**
 * 每人每天 1 份食物 + 1 份清水（3A:65 / 3A:89）。
 *
 * 🔴 只按出战人数算（3A:85）—— 不出战的人不吃商队口粮（3A:97）。
 * 🔴🔴 返回值必须是两个字段，不许合并成一个总数（表述铁律 3A:93）。
 */
export function 每日消耗(出战人数: number): { 食物: number; 清水: number } {
  return { 食物: 出战人数, 清水: 出战人数 };
}

// ============================================================================
// 🔴 扣掉
// ============================================================================

export interface 扣补给结果 {
  /** 🔴 实际扣掉几份 —— 库存不够时比要扣的少（这个值还兼作「扣之前是不是已经为 0」的判据） */
  扣了多少食物: number;
  扣了多少清水: number;
  /** 🔴 扣完之后是 0 —— 本文件🔴 只报告，惩罚在 断粮扣士气() */
  食物耗尽: boolean;
  清水耗尽: boolean;
}

/**
 * 从状态里扣掉今天要吃的。
 *
 * 🔴🔴 扣到 0 为止，不许扣成负数（判据 6 / 7）。
 * 🔴 🔴 本函数不碰士气、不碰血量 —— 那是下一段的事（判据 8）。
 */
export function 扣补给(状态: 商队状态): 扣补给结果 {
  const 要扣 = 每日消耗(状态.出战人数);
  const 原食物 = 状态.资源.食物;
  const 原清水 = 状态.资源.清水;

  状态.资源.食物 = Math.max(0, 原食物 - 要扣.食物);
  状态.资源.清水 = Math.max(0, 原清水 - 要扣.清水);

  return {
    扣了多少食物: 原食物 - 状态.资源.食物,
    扣了多少清水: 原清水 - 状态.资源.清水,
    食物耗尽: 状态.资源.食物 === 0,
    清水耗尽: 状态.资源.清水 === 0,
  };
}

// ============================================================================
// 🔴 断粮断水惩罚
// ============================================================================

/** 🔴 断粮扣血上限 10%（3A:105）。🔴 本阶段只把 A 类的数字记下来，不作用在任何东西上（指令 §8.3）。 */
export function 断粮扣血百分比(): number {
  return 10;
}

/** 🔴 断水是断粮的两倍 —— 20%（3A:113）。同上，只记数字不作用。 */
export function 断水扣血百分比(): number {
  return 20;
}

/**
 * 🔴 断粮断水 → 扣士气。
 *
 * 🔴 食物 = 0 → 士气 −1（3A:105）；清水 = 0 → 士气 −1（3A:113）；
 *    两者都归零 → 叠加 −2（3A:129「双重惩罚叠加」）。
 *    ⚠️ A 类那句叠加原文举的例子是血量（90/90 → 70/70），士气到底 −2 还是 −1 没写死
 *       —— 指令 §8.2 按「两个 −1 叠加」处理，Hermes 照做并已在回执里报给项目主。
 *
 * 🔴🔴 士气下限 0，不许扣成负数（判据 12）。
 * 🔴 血上限 / 当前血 / 重伤恶化 本阶段不做（角色系统在 P6）。
 *
 * @returns 实际扣掉的士气（下限截断后可能小于 应扣）
 */
export function 断粮扣士气(状态: 商队状态, 食物耗尽: boolean, 清水耗尽: boolean): number {
  let 应扣 = 0;
  if (食物耗尽) 应扣 += 1;
  if (清水耗尽) 应扣 += 1;
  const 前 = 状态.资源.士气;
  状态.资源.士气 = Math.max(0, 前 - 应扣);
  return 前 - 状态.资源.士气;
}

// ============================================================================
// 🔴 描述 —— 人工核对状态用（🔴 两列分开写，不许合并成总数，3A:93）
// ============================================================================

export function 描述补给(标签: string, 状态: 商队状态): string {
  const 要 = 每日消耗(状态.出战人数);
  return [
    `${标签}`,
    `  出战 ${状态.出战人数} 人 · 每天要 ${要.食物} 份食物 + ${要.清水} 份清水`,
    `  现有：食物 ${状态.资源.食物} 份 · 清水 ${状态.资源.清水} 份 · 士气 ${状态.资源.士气}`,
    `  ${状态.资源.食物 === 0 ? '🔴 食物 = 0' : '✅ 有食物'}`,
    `  ${状态.资源.清水 === 0 ? '🔴 清水 = 0' : '✅ 有清水'}`,
  ].join('\n');
}
