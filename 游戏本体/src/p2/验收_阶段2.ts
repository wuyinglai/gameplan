type 判定 = '✅' | '❌' | '⏳';
interface 行 { 项目: string; 预期: string; 实际: string; 对不对: 判定 }
const 表: 行[] = [];
const 对 = (项目: string, 预期: string, 实际: string, 成立: boolean): void => {
  表.push({ 项目, 预期, 实际, 对不对: 成立 ? '✅' : '❌' });
};
const 待 = (项目: string, 缺什么: string, 实际: string): void => {
  表.push({ 项目, 预期: `⏳ ${缺什么}`, 实际, 对不对: '⏳' });
};

