export function 打印2B验收表(): { 通过: number; 待裁定: number; 不合格: number } {
  const 通过 = 表.filter((r) => r.对不对 === '✅').length;
  const 待裁定 = 表.filter((r) => r.对不对 === '⏳').length;
  const 不合格 = 表.filter((r) => r.对不对 === '❌').length;

  console.log('');
  console.log('════════ 2B 阶段验收表（2.0 资源字段 → 2.4 串联）════════');
  console.log('项目'.padEnd(34) + '预期'.padEnd(30) + '实际'.padEnd(34) + '对不对');
  console.log('─'.repeat(108));
  表.forEach((r) => console.log(
    r.项目.padEnd(34) + r.预期.padEnd(30) + r.实际.padEnd(34) + r.对不对,
  ));
  console.log('─'.repeat(108));
  console.log(`汇总：通过 ${通过} · 待裁定 ${待裁定} · 不合格 ${不合格}`);
  console.log('');
  if (不合格 > 0) {
    console.log('未通过项（复现 · 期望 · 实际）：');
    表.filter((r) => r.对不对 === '❌').forEach((r, i) =>
      console.log(`  ${i + 1}. ${r.项目}\n     期望：${r.预期}\n     实际：${r.实际}`));
  } else {
    console.log('未通过项：无');
  }
  console.log('');
  console.log(`参数：出战 ${开局人数} 人 / ${开局车辆} 辆 · 士气上限 ${士气上限} · 耐久上限假设 单车${耐久上限每车}/全队${耐久上限全队}（待裁定㉗）`);
  console.log('🔴 ⏳ 行是**待裁定项**，不代表已实现，也不代表失败 —— 每条都写了缺什么。');
  return { 通过, 待裁定, 不合格 };
}

