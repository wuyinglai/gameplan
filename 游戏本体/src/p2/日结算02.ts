import { 新建商队 } from './资源';
import { 扣补给, 断粮扣士气, 描述补给 } from './消耗补给';
import type { 商队状态 } from './资源';

// ============================================================================
// 🔴 跨日那一刻跑一次
// ============================================================================

export interface 跨日结算结果 {
  扣了多少食物: number;
  扣了多少清水: number;
  /** 🔴 扣完之后是 0 —— 惩罚从**明天**才开始（今天归零那一刻不罚） */
  食物耗尽: boolean;
  清水耗尽: boolean;
  /** 🔴 今天惩罚生效了吗 */
  施加了惩罚: boolean;
  士气变化: number;
}

/**
 * P2 的跨日结算 —— 🔴 一天只调一次（幂等保护归调用方，本中阶段没有调用方）。
 *
 * 🔴🔴 顺序固定「先扣，再罚」，而且「归零那一刻不罚」（指令 §8.1）：
 *   A 类原文是「食物/水 **= 0 后**，每天恶化一次」（3A:105 / 3A:113）。
 *   玩家带的粮正好等于一天消耗时，扣完才变 0 —— 那一刻不该罚，
 *   🔴 从**第二天**起才罚，否则玩家第一天就被罚。
 *   实现方式：「实际扣了多少 = 0」等价于「扣之前就已经是 0」，只有这种情况才罚。
 */
export function 日结算02(状态: 商队状态): 跨日结算结果 {
  // —— 第 1 步：扣 ——
  const 扣 = 扣补给(状态);

  // —— 第 2 步：昨天就已经是 0 的，今天恶化一次 ——
  const 昨天食物就是零 = 状态.资源.食物 === 0 && 扣.扣了多少食物 === 0;
  const 昨天清水就是零 = 状态.资源.清水 === 0 && 扣.扣了多少清水 === 0;

  const 施加了惩罚 = 昨天食物就是零 || 昨天清水就是零;
  const 士气变化 = 施加了惩罚
    ? 断粮扣士气(状态, 昨天食物就是零, 昨天清水就是零)
    : 0;

  return {
    扣了多少食物: 扣.扣了多少食物,
    扣了多少清水: 扣.扣了多少清水,
    食物耗尽: 扣.食物耗尽,
    清水耗尽: 扣.清水耗尽,
    施加了惩罚,
    士气变化,
  };
}

/** 🔴 人工核对用的自跑演示（不进任何调用链，只是 `npx vite-node src/p2/日结算02.ts` 之类手动看） */
export function 跑一次看看(): void {
  const 状态 = 新建商队();
  状态.资源.食物 = 30;
  状态.资源.清水 = 30;
  console.log(描述补给('【跨日之前】', 状态));
  const 果 = 日结算02(状态);
  console.log(描述补给('【跨日之后】', 状态));
  console.log(
    `  扣了 ${果.扣了多少食物} 份食物 + ${果.扣了多少清水} 份清水 · ` +
    `惩罚：${果.施加了惩罚 ? `有（士气 ${果.士气变化}）` : '无'}`,
  );
}
