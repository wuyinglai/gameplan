//
// 跑法：npx vitest run（vitest.config.ts 的 include 是 src/**/*.test.ts，已覆盖本目录）
// 🔴 本目录不许 import src/p1/ 的任何东西（指令 §1 约束 2）—— 本文件只 import ./资源。
// ============================================================================

import { describe, expect, it } from 'vitest';
import * as 资源模块 from './资源';
import {
  车队耐久上限, 士气上限, 开局人数, 开局车辆, 新建商队, 描述资源, 资源上限,
} from './资源';
import type { 商队状态, 资源名 } from './资源';

const 八字段 = ['食物', '清水', '药包', '零件', '脏水', '金钱', '耐久', '士气'];
const 五资源: 资源名[] = ['食物', '清水', '药包', '零件', '脏水'];

describe('P2 第 1 步 · 商队资源字段', () => {
  // ------------------------------------------------------------------ 1
  it('判据 1 · 新建商队() 八个资源字段全部存在（哪怕是 0）', () => {
    const 状态 = 新建商队();
    expect(Object.keys(状态.资源).sort()).toEqual([...八字段].sort());
    for (const 名 of 八字段) {
      expect(typeof 状态.资源[名 as keyof typeof 状态.资源]).toBe('number');
    }
  });

  // ------------------------------------------------------------------ 2
  it('判据 2 · 出战人数 = 14（3A:83）', () => {
    expect(新建商队().出战人数).toBe(14);
    expect(开局人数).toBe(14);
  });

  // ------------------------------------------------------------------ 3
  it('判据 3 · 车辆数 = 3（3A:351 / 3A:669 / 6A:520）', () => {
    expect(新建商队().车辆数).toBe(3);
    expect(开局车辆).toBe(3);
  });

  // ------------------------------------------------------------------ 4
  it('判据 4 · 资源名类型：五种资源都写得出（食物/清水/药包/零件/脏水）', () => {
    // 🔴 这一行本身就是一条编译期断言：少写一种或多写一种，tsc 直接报错。
    const 五种都能写: Record<资源名, number> = { 食物: 1, 清水: 1, 药包: 1, 零件: 1, 脏水: 1 };
    expect(Object.keys(五种都能写).sort()).toEqual([...五资源].sort());
    // 资源上限表的键必须与「五种」严丝合缝（不多不少）
    expect(Object.keys(资源上限).sort()).toEqual([...五资源].sort());
  });

  // ------------------------------------------------------------------ 5
  it('判据 5 · 资源上限表五项全 0（🔴 这是「待裁定」的标记，不是 bug）', () => {
    for (const 名 of 五资源) {
      expect(资源上限[名], `🔴 ${名} 上限应该是 0（待裁定）`).toBe(0);
    }
    expect(车队耐久上限).toBe(0);   // 🔴 第 4 步拆车之后才定（3A:39 各车上限之和）
  });

  // ------------------------------------------------------------------ 6
  it('判据 6（✍️ 已按 A 类修订）· 士气上限 = 10，不是 0', () => {
    // 🔴 指令 §3/§4 原本写「士气上限 A 类没写 → 填 0，判据期望 0」。
    // 🔴 但 A 类写了：3A:510（§4.5 规则条）「士气有上限（最高 10），达到上限后无法再提升」。
    // 🔴 指令引的「城 ≤ 6 / 镇驿 ≤ 4」（3A:517-527 §4.6）是**自然恢复阈值**，不是属性上限。
    // ✍️ 2026-10-21 已就地改指令文件 §3/§4 并留痕；这条测试钉的是 A 类原文，不是指令转述。
    expect(士气上限).toBe(10);
    expect(士气上限).not.toBe(0);
  });

  // ------------------------------------------------------------------ 7
  it('判据 7 · 描述资源() 输出里八个字段名都出现', () => {
    const 状态 = 新建商队();
    const 文本 = 描述资源('出发时', 状态);
    for (const 名 of 八字段) {
      expect(文本, `🔴 输出漏了「${名}」：${文本}`).toContain(名);
    }
    expect(文本).toContain('出战');
    expect(文本).toContain('辆');
    expect(文本).toContain('出发时');
    // 🔴 顺带钉住：数字真的印出来了（开局全 0，所以每个字段后面都该跟 0）
    // 🔴 例外 = 士气：初值 6（3A:452 · 2026-10-24 项目主裁定）
    expect(文本).toContain('食物 0 份');
    expect(文本).toContain('士气 6');
  });

  // ------------------------------------------------------------------ 8
  it('判据 8 · 🔴 本步骤不许有扣/加/消耗函数（加了行为就是提前做第 2 步）', () => {
    const 导出名 = Object.keys(资源模块).sort();
    // 运行时只该有这 7 个值（资源名/商队资源/商队状态 是类型，运行时不存在）
    expect(导出名).toEqual([
      '描述资源', '新建商队', '开局人数', '开局车辆', '士气上限', '资源上限', '车队耐久上限',
    ].sort());

    // 名字里不许出现行为词
    const 行为词 = ['扣', '加', '消耗', '补给', '回复', '恢复', '增加', '减少', '结算', '跨日'];
    for (const 名 of 导出名) {
      for (const 词 of 行为词) {
        expect(名, `🔴 导出了行为函数「${名}」`).not.toContain(词);
      }
    }

    // 函数体里不许出现算术改写（本步骤只读不写）
    for (const [名, 值] of Object.entries(资源模块)) {
      if (typeof 值 !== 'function') continue;
      const 源码 = (值 as unknown as { toString(): string }).toString();
      expect(源码, `🔴 「${名}」里有算术改写`).not.toMatch(/[-+*/]=|\+\+|--/);
    }
  });

  // -------------------------------------------------- 附加：状态是独立新对象
  it('附加 · 每次新建商队() 是独立对象（不共享同一份资源，为第 2 步铺底）', () => {
    const 甲 = 新建商队();
    const 乙 = 新建商队();
    expect(甲.资源).not.toBe(乙.资源);
    expect(甲).not.toBe(乙);
    甲.资源.食物 = 7;                      // 只改甲
    expect(乙.资源.食物).toBe(0);
    const 状态: 商队状态 = 乙;             // 类型自查：乙确实是商队状态
    expect(状态.资源.士气).toBe(6);        // 🔴 初值 6（3A:452 · 2026-10-24 项目主裁定）
  });
});
