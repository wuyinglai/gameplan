// 🔴 只做两件事：推进动作耗时、报告到没到日界。
// 🔴 【不许改 第几天】—— 那是 结算.跨日() 的事，写在这里就会出现两处跨日。
//    （「当前小时」是本模块唯一的写入口；重置回 07:00 由 结算 负责）
// ============================================================================

import type { 游戏状态 } from './状态';

export const 开工时刻 = 7;      // 07:00
export const 收工时刻 = 19;     // 19:00 收工
export const 一天可支配小时 = 收工时刻 - 开工时刻;   // 12 小时
export const 每格耗时 = 2;      // 走 1 格 = 2 小时

/// 还剩几小时收工（0 表示已经到点）
export function 剩余小时(状态: 游戏状态): number {
  return Math.max(0, 收工时刻 - 状态.当前小时);
}

/// 推进一个动作的耗时。🔴 只动 当前小时，不动 第几天，也不自己跨日。
export function 推进(状态: 游戏状态, 小时数: number): void {
  if (!Number.isInteger(小时数) || 小时数 <= 0) {
    throw new Error(`推进耗时必须是正整数小时，收到 ${String(小时数)}`);
  }
  状态.当前小时 += 小时数;
}

/// 到收工了吗（>= 19:00）—— 🔴 只报告，不动任何状态
export function 到收工(状态: 游戏状态): boolean {
  return 状态.当前小时 >= 收工时刻;
}
