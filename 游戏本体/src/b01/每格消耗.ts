// ============================================================================
// 单元 01 · 每格消耗（🔴 全项目只有这一个函数算「走一格扣多少」）
//
// 依据：指令② 二.2 · 施工图 §5 / §5.1（每格消耗只升不降）
//
// 🔴 天气加成、路况加成**都只从这里出**。别的模块（体力 / 主循环）不许自己判断加成，
//    否则同一个数字会散落在三处，改一处漏两处。
//
// 🔴 本刀（指令②）按指令要求：天气与路况**都先按 0** → 恒返回 15。
//    指令③ 把 天气加成已接入 改 true；指令④ 把 路况加成已接入 改 true 并填 夹具值。
//    这样接线一次到位，后面两刀只改这个文件，不用回头动 体力 / 主循环。
// ============================================================================

import type { 游戏状态 } from './状态';
import type { 格子, 路况档 } from './地图';
import { 天气每格加成 } from './状态';

export const 基础每格消耗 = 15;   // 施工图 §2.1：每格恒定 15 点

/// 路况 → 每格加成。🔴 本刀全 0；指令④ 用夹具值（好0 / 普通0 / 差5 / 恶劣10）。
/// 🔴 夹具值不是正式平衡数值，正式档差归 `23`/`24`（施工图 §6.2）。
export const 路况每格加成: Record<路况档, number> = {
  好: 0, 普通: 0, 差: 0, 恶劣: 0,
};

const 天气加成已接入: boolean = false;   // 指令③ 改 true
const 路况加成已接入: boolean = false;   // 指令④ 改 true

/// 走目标格要扣多少点。**只会 ≥ 15**（施工图 §5.1：消耗只升不降）。
export function 每格消耗(状态: 游戏状态, 目标格: 格子): number {
  const 天气加成 = 天气加成已接入 ? 天气每格加成[状态.当前天气] : 0;
  const 路况加成 = 路况加成已接入 ? 路况每格加成[目标格.路况档] : 0;
  return 基础每格消耗 + 天气加成 + 路况加成;
}
