// 🔴 2026-10-19 WorkBuddy 加：锁住「结束当天」的幂等判据
// 🔴 原判据是「当前小时 > 07:00 才可用」—— 🔴 那会让【开局 07:00 用不了】，
//而那恰恰是最需要它的时候（一步都走不动、体力耗尽、刚开局）。
// ============================================================================
describe('🔴 结束当天：永远合法，除非今天已经结算过', () => {

  it('开局 07:00、一步都没走 → 🔴 仍然可以「结束当天」（原判据会拒掉，这里锁住）', () => {
    const 状态 = 新局();
    expect(状态.当前小时).toBe(7);
    expect(状态.今天已结算).toBe(false);

    const 结果 = 结束当天(状态);
    expect(结果.成功).toBe(true);
    expect(状态.第几天).toBe(2);
    expect(状态.当前小时).toBe(7);
    expect(状态.今天已结算).toBe(true);
  });

  it('🔴 幂等：刚自动跨日后再调 → 不能再跨一次（天数不许变 3）', () => {
    const 状态 = 新局();
    // 走到 19:00 自动跨日 → 现在是第 2 天 07:00，今天已结算
    for (let i = 0; i < 6; i += 1) {
      推进时间(状态, 每格耗时);
    }
    expect(状态.第几天).toBe(2);
    expect(状态.今天已结算).toBe(true);

    const 再来一次 = 结束当天(状态);
    expect(再来一次.成功).toBe(false);
    expect(再来一次.原因).toContain('已经结算过');
    // 🔴 关键：天数没有变成 3，体力也没有再回一次
    expect(状态.第几天).toBe(2);
    expect(状态.今天已结算).toBe(true);
  });

  it('🔴 走了一格但没跨日 → 今天没结算过，「结束当天」仍可用', () => {
    const 状态 = 新局();
    走一格(状态, 北边(状态));          // 07:00 → 09:00，没到 19:00
    expect(状态.第几天).toBe(1);
    expect(状态.今天已结算).toBe(false);

    const 结果 = 结束当天(状态);
    expect(结果.成功).toBe(true);
    expect(状态.第几天).toBe(2);
  });
});
