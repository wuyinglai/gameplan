import { describe, it, expect } from 'vitest';
import 地图json from './地图.json';
import { 加载地图, 设格 } from './地图';
import { 新建游戏状态 } from './状态';
import type { 游戏状态 } from './状态';
import { 走一格, 推进时间 } from './主循环';
import { 结束当天 } from './结束当天';
import { 基础每格消耗 } from './每格消耗';
import { 每格耗时 } from './时间';

/// 真夹具 + 起点正北方摆 6 格商路（r=0），保证前 6 格一定走得动。
/// 🔴 坐标全是相对 地图.起点 算出来的，没有一个写死的绝对坐标。
function 新局(): 游戏状态 {
  const 图 = 加载地图(地图json);
  for (let i = 1; i <= 6; i += 1) {
    设格(图, 图.起点.x, 图.起点.y + i, '商路', '好');
  }
  return 新建游戏状态(图);
}

/// 当前格正北那一格
function 北边(状态: 游戏状态) {
  return { x: 状态.当前坐标.x, y: 状态.当前坐标.y + 1 };
}

describe('场景 A：中途手动「结束当天」', () => {
  it('体力 100 → 走 3 格 = 55 → 结束当天 → 第2天 07:00 体力回到 100（封顶）', () => {
    const 状态 = 新局();
    expect(状态.野外体力).toBe(100);
    expect(状态.第几天).toBe(1);
    expect(状态.当前小时).toBe(7);

    for (let i = 0; i < 3; i += 1) {
      const 果 = 走一格(状态, 北边(状态));
      expect(果.成功, `第 ${i + 1} 步应当成功：${果.原因}`).toBe(true);
      expect(果.跨日了).toBe(false);
    }

    expect(基础每格消耗).toBe(15);
    expect(状态.野外体力).toBe(55);          // 100 - 15*3
    expect(状态.当前小时).toBe(13);          // 07:00 + 2*3

    const 果 = 结束当天(状态);
    expect(果.成功).toBe(true);
    expect(状态.第几天).toBe(2);
    expect(状态.当前小时).toBe(7);
    expect(状态.野外体力).toBe(100);          // 55 + 50 = 105 → 封顶 100
  });
});

describe('场景 B：体力见底，19:00 自动跨日', () => {
  it('走到第 6 格剩 10 点 → 自动跨日 → 第2天 07:00 体力 60', () => {
    const 状态 = 新局();
    for (let i = 1; i <= 5; i += 1) {
      const 果 = 走一格(状态, 北边(状态));
      expect(果.成功).toBe(true);
      expect(果.跨日了, `第 ${i} 步不该跨日`).toBe(false);
    }
    expect(状态.当前小时).toBe(17);
    expect(状态.野外体力).toBe(25);

    const 第六步 = 走一格(状态, 北边(状态));
    expect(第六步.成功).toBe(true);
    expect(第六步.跨日了).toBe(true);

    expect(状态.第几天).toBe(2);
    expect(状态.当前小时).toBe(7);
    expect(状态.野外体力).toBe(60);          // 100-90=10 → +50
  });

  it('🔴 跨日只结算一次：体力只回一份（10+50=60，不是 110）、天数只 +1、天气段只 -1', () => {
    const 状态 = 新局();
    const 起始天气段 = 状态.天气剩余天数;
    for (let i = 0; i < 6; i += 1) 走一格(状态, 北边(状态));

    expect(状态.野外体力).toBe(60);
    expect(状态.第几天).toBe(2);
    expect(状态.天气剩余天数).toBe(起始天气段 - 1);   // 只推进一次

    // 再调一次「结束当天」不该重复结算
    const 再结束 = 结束当天(状态);
    expect(再结束.成功).toBe(false);
    expect(状态.第几天).toBe(2);
    expect(状态.当前小时).toBe(7);
    expect(状态.野外体力).toBe(60);
    expect(状态.天气剩余天数).toBe(起始天气段 - 1);
  });
});

describe('边界：拒绝时什么都不发生', () => {
  it('体力只剩 10 点 → 走一格被拒，体力 / 坐标 / 时钟 一个都不动', () => {
    const 状态 = 新局();
    状态.野外体力 = 10;
    const 坐标 = { ...状态.当前坐标 };

    const 果 = 走一格(状态, 北边(状态));
    expect(果.成功).toBe(false);
    expect(果.原因).toMatch(/走不动/);
    expect(状态.野外体力).toBe(10);
    expect(状态.当前坐标).toEqual(坐标);
    expect(状态.当前小时).toBe(7);
  });

  it('只剩 1 小时（18:00）→ 走 2 小时的格被拒，不许「走一半」', () => {
    const 状态 = 新局();
    expect(每格耗时).toBe(2);
    状态.当前小时 = 18;

    const 果 = 走一格(状态, 北边(状态));
    expect(果.成功).toBe(false);
    expect(果.原因).toMatch(/时间不够/);
    expect(状态.当前小时).toBe(18);
    expect(状态.野外体力).toBe(100);
  });

  it('前方是山 → 拒绝；是水 → 拒绝（体力与时钟不动）', () => {
    for (const 类型名 of ['山', '水'] as const) {
      const 状态 = 新局();
      设格(状态.地图, 状态.当前坐标.x, 状态.当前坐标.y + 1, 类型名);
      const 果 = 走一格(状态, 北边(状态));
      expect(果.成功, `${类型名} 应当拦住玩家`).toBe(false);
      expect(果.原因).toContain(`${类型名}无法通行`);
      expect(状态.野外体力).toBe(100);
      expect(状态.当前小时).toBe(7);
    }
  });

  it('斜向一格、隔两格、出地图 → 全部拒绝', () => {
    const 状态 = 新局();
    const 斜 = { x: 状态.当前坐标.x + 1, y: 状态.当前坐标.y + 1 };
    expect(走一格(状态, 斜).原因).toMatch(/相邻/);
    expect(走一格(状态, { x: 状态.当前坐标.x + 2, y: 状态.当前坐标.y }).原因).toMatch(/相邻/);

    状态.当前坐标 = { x: 0, y: 0 };
    expect(走一格(状态, { x: -1, y: 0 }).原因).toMatch(/不在地图范围/);
    expect(走一格(状态, { x: 0, y: 状态.地图.高 }).原因).toMatch(/不在地图范围/);
    expect(状态.当前坐标).toEqual({ x: 0, y: 0 });
  });
});

describe('边界：只推进时间，不许一步跨两天', () => {
  it('从 07:00 只调「推进 2 小时」6 次 → 第2天 07:00，跨日恰好 1 次', () => {
    const 状态 = 新局();
    let 跨日次数 = 0;
    for (let i = 0; i < 6; i += 1) {
      if (推进时间(状态, 每格耗时).跨日了) 跨日次数 += 1;
    }
    expect(状态.第几天).toBe(2);
    expect(状态.当前小时).toBe(7);
    expect(跨日次数).toBe(1);
  });

  it('只调 20 次 → 🔴 第4天 11:00、跨日 3 次（一次不多一次不少）', () => {
    const 状态 = 新局();
    let 跨日次数 = 0;
    for (let i = 0; i < 20; i += 1) {
      if (推进时间(状态, 每格耗时).跨日了) 跨日次数 += 1;
    }
    expect(跨日次数).toBe(3);
    expect(状态.第几天).toBe(4);
    expect(状态.当前小时).toBe(11);
  });
});

describe('边界：「结束当天」防卡死 + 幂等', () => {
  it('15:00 且体力 0（山冲，跑不到任何地点）→ 结束当天 → 日期+1、07:00、坐标不变', () => {
    const 状态 = 新局();
    状态.当前小时 = 15;
    状态.野外体力 = 0;
    const 坐标 = { ...状态.当前坐标 };

    const 果 = 结束当天(状态);
    expect(果.成功, '防卡死的兜底操作必须能用').toBe(true);
    expect(状态.第几天).toBe(2);
    expect(状态.当前小时).toBe(7);
    expect(状态.当前坐标).toEqual(坐标);
    expect(状态.野外体力).toBe(50);          // 0 + 50
  });

  it('19:00 已自动跨日后再调「结束当天」→ 不能再跨一次', () => {
    const 状态 = 新局();
    for (let i = 0; i < 6; i += 1) 走一格(状态, 北边(状态));
    expect(状态.第几天).toBe(2);

    const 果 = 结束当天(状态);
    expect(果.成功).toBe(false);
    expect(状态.第几天).toBe(2);
  });
});

describe('走进地点 = 抵达，格子标记已到访', () => {
  it('走进驿站 → 格子.已到访 = true，状态里的列表跟着投影', () => {
    const 图 = 加载地图(地图json);
    const 驿站坐标 = { x: 图.起点.x, y: 图.起点.y + 1 };
    设格(图, 驿站坐标.x, 驿站坐标.y, '驿站', '普通', '岔口驿站');
    const 状态 = 新建游戏状态(图);

    expect(走一格(状态, 驿站坐标).成功).toBe(true);
    expect(状态.当前坐标).toEqual(驿站坐标);
    expect(状态.已到访地点).toEqual(['岔口驿站']);

    // 走回起点（大城也是地点类 → 也算抵达），再走进驿站，列表不许重复增长
    走一格(状态, { x: 驿站坐标.x, y: 驿站坐标.y - 1 });
    expect(状态.已到访地点.length).toBe(2);   // 驿站 + 起点大城（json 没地点名 → 用坐标当标识）
    const 再进 = 走一格(状态, 驿站坐标);
    expect(再进.成功).toBe(true);
    expect(状态.已到访地点.filter((名) => 名 === '岔口驿站').length).toBe(1);
    expect(状态.已到访地点.length).toBe(2);
  });

  it('走空地 / 商路 不算抵达', () => {
    const 状态 = 新局();
    走一格(状态, 北边(状态));
    expect(状态.已到访地点).toEqual([]);
  });
});

