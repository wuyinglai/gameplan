import type { 地图对象 } from './地图';

export type 天气类型 =
  | '晴朗' | '阴天' | '小雨' | '暴雨'
  | '高温' | '酷热' | '寒潮' | '严寒'
  | '浓雾' | '重雾' | '灰烬风' | '灰烬风暴';

export interface 游戏状态 {
  当前坐标: { x: number; y: number };
  地图: 地图对象;                 // 🔴 2026-10-19 裁定（指令② §一.4）：原来是
                                 //    `Map<string,格子>`，装不下宽/高/起点/终点 —— 主循环
                                 //    没地方读起点终点。现在直接装 地图.ts 的 地图对象。

  第几天: number;                 // 从 1 开始
  当前小时: number;               // 7 ~ 19（19:00 即收工）
  // 🔴 这两个字段只有 结算.ts 的 跨日() 能改，其他模块只读

  野外体力: number;               // 上限 100
  体力上限: number;               // 恒为 100

  当前天气: 天气类型;             // 🔴 存具体天气名，不存布尔
  天气剩余天数: number;

  已到访地点: string[];           // 权威字段是 格子.已到访，这个列表只是它的投影
}

/// 新建一局：起点坐标从 地图对象.起点 读
/// 🔴 硬约束：不许把坐标写死在代码里 —— 这里一个数字坐标都没写。
export function 新建游戏状态(地图: 地图对象): 游戏状态 {
  return {
    当前坐标: { x: 地图.起点.x, y: 地图.起点.y },
    地图,
    第几天: 1,
    当前小时: 7,
    野外体力: 100,
    体力上限: 100,
    当前天气: '晴朗',
    天气剩余天数: 5,              // ★ 普通天气段 5-7 天（施工图 §6.2 夹具值，指令③ 才真掷）
    已到访地点: [],
  };
}

