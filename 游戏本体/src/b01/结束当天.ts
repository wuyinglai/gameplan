// ============================================================================
// 单元 01 · 结束当天（防卡死的兜底操作）
//
// 依据：指令② 二.5
// 🔴 独立操作，不碰移动：不许改坐标、不许扣移动体力、不许额外推进 2 小时。
///   它做的**唯一一件事**就是调 结算.跨日()。
//
// 🔴 幂等口径（指令② 断言：「19:00 已自动跨日后再调 → 不能再跨一次」）：
//    跨完之后时钟就是 07:00，所以这里用「今天还没走过任何时间（小时 == 开工时刻）」
//    当作「这一天还没有可结束的东西」→ 拒绝。
//    ⚠️ 与 `开发流程_单元01.md` 指令⑤ 那句「任何时候都能用」不完全一致：
//       07:00 刚开局时本操作会被拒。指令② §三 已写「先按拒绝实现，改判只需改一处」——
//       要放行就把 结束当天可用() 的判据去掉，别处不用动。已计入偏离清单。
// ============================================================================

import type { 游戏状态 } from './状态';
import { 跨日 } from './结算';
import { 开工时刻 } from './时间';

export interface 操作结果 {
  成功: boolean;
  原因: string | null;
}

/// 现在能不能「结束当天」
export function 结束当天可用(状态: 游戏状态): boolean {
  return 状态.当前小时 > 开工时刻;
}

/// 直接跳到第二天早上。🔴 除了 跨日() 什么都不做。
export function 结束当天(状态: 游戏状态): 操作结果 {
  if (!结束当天可用(状态)) {
    return {
      成功: false,
      原因: '今天刚开始（07:00），没有可结束的一天 —— 若刚自动跨日，说明这一步已经做过了',
    };
  }
  跨日(状态);
  return { 成功: true, 原因: null };
}
