import type { 游戏状态 } from './状态';
import { 每日回复 } from './体力';
import { 开工时刻 } from './时间';

/// ★ 普通天气段 5-7 天，本轮取 5（施工图 §6.2 夹具值）。
/// 🔴 「到期重掷哪种天气」是**指令③**的活（天气模块还没建）——
///    本刀只做「续期」：把剩余天数补回 ★ 值，**不改变当前天气名**。已计入偏离清单。
const 天气段续期天数 = 5;

/// 🔴 跨日那一刻做的四件事，一次不多一次不少：
///   ① 第几天 +1   ② 时钟回 07:00   ③ 体力 +50（封顶 100）   ④ 天气段 -1（到期续期）
export function 跨日(状态: 游戏状态): void {
  状态.第几天 += 1;
  状态.当前小时 = 开工时刻;
  每日回复(状态);                    // 🔴 全项目唯一的体力回复调用点
  推进天气段(状态);
}

function 推进天气段(状态: 游戏状态): void {
  状态.天气剩余天数 -= 1;
  if (状态.天气剩余天数 <= 0) {
    状态.天气剩余天数 = 天气段续期天数;   // 指令③：这里改成按 5A §2.2 概率重掷
  }
}
