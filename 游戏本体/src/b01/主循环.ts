import type { 游戏状态 } from './状态';
import type { 坐标 } from './地图';
import { 查格, 可通行, 可停留, 坐标key } from './地图';
import { 每格耗时, 剩余小时, 推进, 到收工 } from './时间';
import { 够不够, 扣 } from './体力';
import { 每格消耗 } from './每格消耗';
import { 跨日, 开新的一天 } from './结算';

export interface 移动结果 {
  成功: boolean;
  原因: string | null;
  跨日了: boolean;
}

function 是整数(v: number): boolean {
  return Number.isInteger(v);
}

function 在范围内(状态: 游戏状态, x: number, y: number): boolean {
  return 是整数(x) && 是整数(y) && x >= 0 && x < 状态.地图.宽 && y >= 0 && y < 状态.地图.高;
}

/// 🔴 走一格 —— 严格按施工图 §3.8 的九步，拒绝时**什么都不扣**。
export function 走一格(状态: 游戏状态, 目标: 坐标): 移动结果 {
  const 拒绝 = (原因: string): 移动结果 => ({ 成功: false, 原因, 跨日了: false });

  // ① 目标坐标在地图范围内吗
  if (!在范围内(状态, 目标.x, 目标.y)) {
    return 拒绝(`目标 ${目标.x},${目标.y} 不在地图范围内（${状态.地图.宽}×${状态.地图.高}）`);
  }

  // ② 与当前格相邻吗（只看上下左右，本轮不做斜向）
  const 偏移x = 目标.x - 状态.当前坐标.x;
  const 偏移y = 目标.y - 状态.当前坐标.y;
  if (Math.abs(偏移x) + Math.abs(偏移y) !== 1) {
    return 拒绝(`只能走上下左右相邻的一格（偏移 ${偏移x},${偏移y}）`);
  }

  // ③ 目标格可通行吗（山 / 水 不可进）
  const 目标格 = 查格(状态.地图, 目标.x, 目标.y);
  if (!可通行(目标格)) {
    return 拒绝(`${目标格.类型}无法通行`);
  }

  // ④ 体力够吗（消耗只从 每格消耗() 拿，别处不许自己算）
  const 消耗 = 每格消耗(状态, 目标格);
  if (!够不够(状态, 消耗)) {
    return 拒绝(`今天走不动了（体力 ${状态.野外体力} 点，这一格要 ${消耗} 点）`);
  }

  // ⑤ 剩余时间够跑完这一整格吗（🔴 不许做一半）
  const 还剩 = 剩余小时(状态);
  if (还剩 < 每格耗时) {
    return 拒绝(`时间不够（还剩 ${还剩} 小时，这一格要 ${每格耗时} 小时）`);
  }

  // ⑥ 全过 → 扣体力 → 时间 +2h → 换坐标
  if (!扣(状态, 消耗)) {
    return 拒绝('不该发生：够不够 与 扣 结果不一致');
  }
  推进(状态, 每格耗时);
  状态.当前坐标 = { x: 目标.x, y: 目标.y };

  // ⑦⑧ 到 19:00 了吗 → 是就立刻结算（🔴 全项目只有这一处会因为移动而跨日，且只调一次）
  let 跨日了 = false;
  if (到收工(状态)) {
    跨日(状态);
    跨日了 = true;
  } else {
    // 🔴 2026-10-19 加：没跨日但动了时间 → 这一天还在继续，
    //    「结束当天」应该仍然可用，所以显式清回 false。
    开新的一天(状态);
  }

  // ⑨ 走进没到访过的地点 → 标记已到访
  标记抵达(状态);

  return { 成功: true, 原因: null, 跨日了 };
}

/// 🔴 推进一段时间的**唯一入口**：时间模块只负责加小时、只负责报告到没到点，
///    「到点就去结算」这件事由主循环做（施工图 §3.6：主循环是唯一串联的地方，
///    而 时间.ts 明令不许改 第几天）。指令② 那两条「只调推进 6 次 / 20 次」的断言
///    走的就是这个函数。
export function 推进时间(状态: 游戏状态, 小时数: number): { 跨日了: boolean } {
  推进(状态, 小时数);
  if (到收工(状态)) {
    跨日(状态);
    return { 跨日了: true };
  }
  // 🔴 动了时间但没跨日 → 这一天还在继续，「结束当天」仍应可用
  开新的一天(状态);
  return { 跨日了: false };
}

/// 走进地点类格子 = 「抵达」。权威字段是 格子.已到访，状态里那个列表只是投影。
/// 🔴 夹具的 json 没有地点名字段，所以没有名字时用坐标当标识。
function 标记抵达(状态: 游戏状态): void {
  const { x, y } = 状态.当前坐标;
  const 格 = 查格(状态.地图, x, y);
  if (!可停留(格) || 格.已到访) return;
  格.已到访 = true;
  状态.已到访地点.push(格.地点名 ?? 坐标key(x, y));
}
