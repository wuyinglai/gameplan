import { describe, it, expect } from 'vitest';
import { 加载地图, 查格 } from './地图';
import { 走一格 } from './移动';
import { 真局, 真图, 快照, 找一步, 是山, 是水, 是碎石差路, 是商路好路, 终点旁边 } from './测试辅助';
import { 新建游戏状态 } from './状态';

const 不许变 = (状态: ReturnType<typeof 真局>) => 快照(状态);

describe('判据 1~2 · 合法的一步', () => {
  it('1 往右走一格 → 成功 · x +1', () => {
    const 状态 = 真局();
    const 前 = { ...状态.当前坐标 };
    expect(走一格(状态, 前.x + 1, 前.y)).toEqual({ 成功: true, 原因: null });
    expect(状态.当前坐标).toEqual({ x: 前.x + 1, y: 前.y });
  });

  it('2 往上走一格 → 成功 · y +1', () => {
    const 状态 = 真局();
    const 前 = { ...状态.当前坐标 };
    expect(走一格(状态, 前.x, 前.y + 1)).toEqual({ 成功: true, 原因: null });
    expect(状态.当前坐标).toEqual({ x: 前.x, y: 前.y + 1 });
  });
});

describe('判据 3~5 · 位置不合法', () => {
  it('3 斜着走 → 拒绝「不是相邻格」· 状态一点没变', () => {
    const 状态 = 真局();
    const 前 = 不许变(状态);
    const 目标 = { x: 状态.当前坐标.x + 1, y: 状态.当前坐标.y + 1 };
    expect(走一格(状态, 目标.x, 目标.y)).toEqual({ 成功: false, 原因: '不是相邻格' });
    expect(快照(状态)).toBe(前);
  });

  it('4 隔两格走 → 拒绝「不是相邻格」· 状态一点没变', () => {
    const 状态 = 真局();
    const 前 = 不许变(状态);
    expect(走一格(状态, 状态.当前坐标.x + 2, 状态.当前坐标.y)).toEqual({ 成功: false, 原因: '不是相邻格' });
    expect(快照(状态)).toBe(前);
  });

  it('5 往图外走 → 拒绝「出地图了」· 状态一点没变', () => {
    const 状态 = 真局();
    状态.当前坐标 = { x: 0, y: 0 };              // 挪到左下角，才试得出「往图外」
    const 前 = 不许变(状态);
    expect(走一格(状态, -1, 0)).toEqual({ 成功: false, 原因: '出地图了' });
    expect(走一格(状态, 0, 状态.地图.高)).toEqual({ 成功: false, 原因: '出地图了' });
    expect(快照(状态)).toBe(前);
  });
});

describe('判据 6~9 · 目标格能不能踩', () => {
  it('6 走进山（block）→ 拒绝「过不去」· 状态一点没变', () => {
    const 状态 = 真局();
    const { 脚下, 目标 } = 找一步(是山);
    状态.当前坐标 = 脚下;
    const 前 = 不许变(状态);
    expect(走一格(状态, 目标.x, 目标.y)).toEqual({ 成功: false, 原因: '过不去' });
    expect(快照(状态)).toBe(前);
  });

  it('7 走进水（blk_wt）→ 拒绝「过不去」· 状态一点没变', () => {
    const 状态 = 真局();
    const { 脚下, 目标 } = 找一步(是水);
    状态.当前坐标 = 脚下;
    const 前 = 不许变(状态);
    expect(走一格(状态, 目标.x, 目标.y)).toEqual({ 成功: false, 原因: '过不去' });
    expect(快照(状态)).toBe(前);
  });

  it('8 走进碎石地（blk_fr，r=2）→ ✅ 成功（可通行，只是慢）', () => {
    const 状态 = 真局();
    const { 脚下, 目标 } = 找一步(是碎石差路);
    状态.当前坐标 = 脚下;
    expect(走一格(状态, 目标.x, 目标.y).成功).toBe(true);
    expect(查格(状态.地图, 目标.x, 目标.y).路况).toBe(2);   // 确实是差路况，不是踩到普通格
  });

  it('9 走进商路（road，r=0）→ ✅ 成功', () => {
    const 状态 = 真局();
    const { 脚下, 目标 } = 找一步(是商路好路);
    状态.当前坐标 = 脚下;
    expect(走一格(状态, 目标.x, 目标.y).成功).toBe(true);
    expect(查格(状态.地图, 目标.x, 目标.y).类型).toBe('空地');   // 商路不是类型，是路况好的空地
  });
});

describe('判据 10~12 · 未标注格 / 地点 / 终点', () => {
  it('10 走进未标注的格子 → 成功 · 当作空地 · 普通', () => {
    const 小图 = 加载地图({
      map: { width: 10, height: 10 }, start: [1, 1], end: [8, 8],
      locations: [{ t: 'big', x: 1, y: 1 }],
    });
    const 状态 = 新建游戏状态(小图);
    expect(走一格(状态, 2, 1).成功).toBe(true);
    const 格 = 查格(小图, 2, 1);
    expect(格.类型).toBe('空地');
    expect(格.路况).toBe(1);
    expect(格.可通行).toBe(true);
    expect(小图.格子表.has('2,1')).toBe(false);          // 默认格不许写进表里
  });

  it('11 走进大城格 → 成功 · 标记 已到访 = true', () => {
    const 图 = 真图();
    const 状态 = 新建游戏状态(图);
    状态.当前坐标 = { x: 图.起点.x + 1, y: 图.起点.y };   // 起点东边那格（实测可通行）
    expect(走一格(状态, 图.起点.x, 图.起点.y).成功).toBe(true);
    expect(查格(图, 图.起点.x, 图.起点.y).类型).toBe('大城');
    expect(查格(图, 图.起点.x, 图.起点.y).已到访).toBe(true);
  });

  it('12 走进终点 → 成功 · 返回「已抵达」', () => {
    const 图 = 真图();
    const 状态 = 新建游戏状态(图);
    状态.当前坐标 = 终点旁边();
    expect(走一格(状态, 图.终点.x, 图.终点.y)).toEqual({ 成功: true, 原因: null, 已抵达: true });
  });
});
