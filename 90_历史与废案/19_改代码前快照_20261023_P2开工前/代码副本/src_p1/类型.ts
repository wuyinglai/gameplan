// ---------------------------------------------------------------------------
// 坐标键 / 地图对象 —— 照抄 §2.3
// ---------------------------------------------------------------------------

export interface 地图对象 {
  宽: number;      // 400
  高: number;      // 400
  起点: { x: number; y: number };
  终点: { x: number; y: number };
  格子表: Map<string, 格子>;   // 🔴 key = `${x},${y}` —— 查一格 O(1)
}

/** 🔴 坐标取 key —— 全项目只有这一处拼 key，别的地方不许自己拼字符串 */
export function 坐标键(x: number, y: number): string {
  return `${x},${y}`;
}

// ---------------------------------------------------------------------------
// 游戏状态 —— 照抄 §2.2
// ---------------------------------------------------------------------------

export interface 游戏状态 {
  // —— 位置 ——
  当前坐标: { x: number; y: number };

  // —— 时间 ——
  // 🔴 这两个字段只有 结算.跨日() 能改，任何别的地方碰它就是 bug
  第几天: number;        // 从 1 开始
  当前小时: number;       // 7 / 9 / 11 / 13 / 15 / 17

  // —— 体力 ——
  野外体力: number;       // 0 ~ 100
  体力上限: number;       // 🔴 恒为 100

  // —— 天气（1.2 加）——
  当前天气: 天气名;              // 🔴 默认「晴朗」
  天气剩余天数: number;          // 🔴 默认 5（普通天气 5~7 的下限）

  // —— 地图（1.3 加）——
  地图: 地图对象;

  // ✍️ Hermes 补充 ②：施工图 §2.2 的字段清单里**没有**这一项，
  //    但 §3.7 与 §3.8 明确要求「用 状态.今天已结算 做幂等」、判据 24 / 26 也靠它。
  //    🔴 已报给 WorkBuddy：施工图 §2.2 需要补这一行（基础文档我不能自己改）。
  /** 🔴 只有 结算.跨日() 置 true；只有 时间.推进() 清回 false（见那里的注释） */
  今天已结算: boolean;
}

