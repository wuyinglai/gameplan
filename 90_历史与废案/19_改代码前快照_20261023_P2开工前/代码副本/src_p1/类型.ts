/** 🔴 8 种格子类型 —— 照抄 1A §4，不许增删 */
export type 格子类型 =
  | '空地'      // 野外空地（含商路 —— 商路是路况不是类型）
  | '地形'      // 山 / 水 / 桥 / 林 / 废墟，多数不可通行
  | '大城'
  | '小城'
  | '城镇'
  | '驿站'
  | '村庄'
  | '营地';

/** 🔴 路况四档 —— 来自地图 json 的 r 字段 */
export type 路况档 = 0 | 1 | 2 | 3;

export interface 格子 {
  类型: 格子类型;
  路况: 路况档;
  /** 🔴 不可通行 = 山 / 水 / 裂谷。地形里桥和碎石地是可通行的 */
  可通行: boolean;
  /** 🔴 走进地点类格子后置 true —— 用于「已到访」 */
  已到访: boolean;
  /** 🔴 地点名（大城名等）—— 非地点格为 null。P1 不用，P2~P7 用 */
  地点名: string | null;
}

/** 🔴 地图 json 的 t 键 → 格子类型。🔴 唯一翻译处，不许在别处再判一次 */
export const T到类型: Record<string, 格子类型> = {
  big: '大城',
  small: '小城',
  town: '城镇',
  village: '村庄',
  inn1: '驿站',
  // 🔴 已知偏差：json 写 special，规格书写「探索点」，A 类 §4 没有这一类
  //    暂时映射成「营地」（唯一功能相近的临时落脚点）—— 见 施工图 §6.4
  special: '营地',
  road: '空地',        // 🔴 商路不是格子类型，是「路况好」的空地
  blk_fr: '地形',      // 可通行（桥 / 碎石地）
  block: '地形',       // 不可通行（山 / 裂谷）
  blk_wt: '地形',      // 不可通行（水 / 河）
};

/** 🔴 不可通行的 t 键 —— 只有这两个。其余全部可通行 */
export const 不可通行的T: ReadonlySet<string> = new Set(['block', 'blk_wt']);

/** 🔴 地点类格子 —— 踩上去 = 进界面，不是「继续赶路」 */
export const 地点类: ReadonlySet<格子类型> = new Set<格子类型>([
  '大城', '小城', '城镇', '驿站', '村庄', '营地',
]);

/** 🔴 不可通行的格子类型 —— 只有「地形」里的一部分，由 t 键决定 */
export function 该T是否可通行(t: string): boolean {
  return !不可通行的T.has(t);
}

