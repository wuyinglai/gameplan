export * from './类型';

import type { 地图对象, 游戏状态 } from './类型';

/** 🔴 起点坐标从 地图对象 读 —— 代码里一个坐标数字都不许写死 */
export function 新建游戏状态(地图: 地图对象): 游戏状态 {
  return {
    当前坐标: { x: 地图.起点.x, y: 地图.起点.y },
    第几天: 1,
    当前小时: 7,                    // 07:00 开工（1A §2.2）
    野外体力: 100,
    体力上限: 100,                  // 🔴 恒为 100（1A §2）
    当前天气: '晴朗',               // 施工图 §2.2 默认值
    天气剩余天数: 5,                // 普通天气 5~7 的下限（5A §2.1）
    地图,
    今天已结算: false,
  };
}
