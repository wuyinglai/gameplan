/** 时刻：当前小时 → 07:00 这种写法 */
const 时刻 = (h: number) => `${String(h).padStart(2, '0')}:00`;

/** 体力条：25 → ▓▓▓░░░░░░░ */
function 体力条(n: number): string {
  const 格 = Math.round((n / 100) * 10);
  return '▓'.repeat(格) + '░'.repeat(10 - 格);
}

