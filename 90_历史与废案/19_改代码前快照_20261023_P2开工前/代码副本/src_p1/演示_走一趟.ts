/** 🔴 用真实地图 · 走 BFS 四方向最短路 —— 这条路是「程序自己找的」，不是人挑的 */
function 走一趟(打印前几格 = 30) {
  const 地图 = 加载地图(地图json);
  const 状态 = 新建游戏状态(地图);

  // —— BFS 找最短路（跟验收脚本同一条）——
  // 🔴 一次把 json 的形状说清 —— 免得后面每个字段各断言一次（tsc 会抱怨）
  const 原始 = 地图json as unknown as {
    map: { width: number; height: number };
    start: [number, number];
    end: [number, number];
    locations: Array<{ x: number; y: number; t: string }>;
  };
  const 堵 = new Set<string>();
  for (const c of 原始.locations) {
    if (c.t === 'block' || c.t === 'blk_wt') 堵.add(`${c.x},${c.y}`);
  }
  const 宽 = 原始.map.width;
  const 高 = 原始.map.height;
  const 起 = 原始.start;
  const 终 = 原始.end;
  const 键 = (x: number, y: number) => `${x},${y}`;
  const 前驱 = new Map<string, string | null>([[键(起[0], 起[1]), null]]);
  const 队: Array<[number, number]> = [[起[0], 起[1]]];
  let 找到 = false;
  while (队.length > 0) {
    const [x, y] = 队.shift()!;
    if (x === 终[0] && y === 终[1]) { 找到 = true; break; }
    for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]] as const) {
      const nx = x + dx, ny = y + dy;
      if (nx < 0 || nx >= 宽 || ny < 0 || ny >= 高) continue;
      const k = 键(nx, ny);
      if (前驱.has(k) || 堵.has(k)) continue;
      前驱.set(k, 键(x, y));
      队.push([nx, ny]);
    }
  }
  if (!找到) { console.log('🔴 走不到终点'); return null; }
  const 路径: Array<{ x: number; y: number }> = [];
  for (let k = 键(终[0], 终[1]); k !== null; k = 前驱.get(k)!) {
    const [x, y] = k.split(',').map(Number);
    路径.push({ x, y });
  }
  路径.reverse();

  console.log('');
  console.log('╔══════════════════════════════════════════════════════════════════════╗');
  console.log('║  《余烬商队》演示 · 从灰原走到小城（真实地图 400×400）              ║');
  console.log('╚══════════════════════════════════════════════════════════════════════╝');
  console.log('');
  console.log(`  起点 (${起[0]},${起[1]})   终点 (${终[0]},${终[1]})   最短 ${路径.length - 1} 格`);
  console.log('');

  let 步 = 1;
  let 格数 = 0;
  let 休息 = 0;
  let 已打印 = 0;
  const 每天格数: number[] = [];
  const 地点集 = new Set<string>();
  // 🔴 今天这一栏已经走了几格（跨日时结算进「每天格数」）
  let 今天格数 = 0;

  while (步 < 路径.length && 格数 < 1200) {
    const 目标 = 路径[步];
    const 果 = 走一格(状态, 目标.x, 目标.y);

    if (果.成功) {
      格数++;
      今天格数++;
      const 格 = 查格(状态.地图, 目标.x, 目标.y);
      const 是地点 = 地点类.has(格.类型);
      if (是地点) 地点集.add(格.类型);

      // 🔴 前 N 格逐格打印 —— 之后只打印每天的收尾
      if (已打印 < 打印前几格) {
        已打印++;
        console.log(
          `  第${状态.第几天}天 ${时刻(状态.当前小时)}  ` +
          `(${状态.当前坐标.x},${状态.当前坐标.y})  ` +
          `体力 ${体力条(状态.野外体力)} ${String(状态.野外体力).padStart(3)}/100  ` +
          `${格.类型}${是地点 ? ' 📍' : ''}${果.已抵达 ? ' 🎯 抵达' : ''}`
        );
      }
      步++;
    } else {
      // 🔴 走不动 → 玩家会点「结束当天」休息一晚
      const 理由 = 果.原因 ?? '?';
      const 歇 = 结束当天(状态);
      if (!歇.成功) {
        console.log('');
        console.log(`  ⚠ 收工失败：${歇.原因} —— 🔴 这是卡死（不该发生）`);
        break;
      }
      休息++;
      // 🔴 收工那一刻 = 这一天结束了，把今天走了几格记下来
      每天格数.push(今天格数);
      今天格数 = 0;
      if (已打印 < 打印前几格 || 已打印 === 打印前几格) {
        已打印++;
        console.log(
          `  第${状态.第几天}天 ${时刻(状态.当前小时)}  ` +
          `(${状态.当前坐标.x},${状态.当前坐标.y})  ` +
          `体力 ${体力条(状态.野外体力)} ${String(状态.野外体力).padStart(3)}/100  ` +
          `☾ ${理由白话[理由] ?? 理由} → 休息 → 第${状态.第几天}天 ${时刻(状态.当前小时)} 体力 ${状态.野外体力}`
        );
      }
    }
  }

  // —— 汇总 ——
  if (今天格数 > 0) 每天格数.push(今天格数);
  const 每天 = 每天格数.filter(n => n > 0);
  const 平均 = 每天.length > 0 ? (每天.reduce((a, b) => a + b, 0) / 每天.length) : 0;
  console.log('');
  console.log('╔══════════════════════════════════════════════════════════════════════╗');
  console.log('║  汇总                                                                ║');
  console.log('╚══════════════════════════════════════════════════════════════════════╝');
  console.log('');
  const 抵达了 = 步 >= 路径.length;
  console.log(`  ${抵达了 ? '✅' : '⚠️'} 抵达终点      ${抵达了 ? '是' : '否'}`);
  console.log(`     走了          ${格数} 格`);
  console.log(`     用了          ${状态.第几天} 天`);
  console.log(`     休息          ${休息} 晚`);
  console.log(`     经过地点      ${地点集.size > 0 ? [...地点集].join('、') : '（一个都没经过）'}`);
  console.log(`     每天格数      平均 ${平均.toFixed(1)} 格`);
  console.log(`     当前天气      ${状态.当前天气}（还剩 ${状态.天气剩余天数} 天）`);
  console.log('');

  return { 格数, 天数: 状态.第几天, 休息, 抵达: 抵达了, 地点: [...地点集], 平均 };
}

