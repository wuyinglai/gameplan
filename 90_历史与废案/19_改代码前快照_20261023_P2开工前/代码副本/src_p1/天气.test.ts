import { describe, it, expect } from 'vitest';
import { 每格加成, 掷天气段, 天气概率, 天气段长, 推进天气段 } from './天气';
import { 每格消耗 } from './消耗';
import { 每格基准消耗 } from './体力';
import { 跨日 } from './结算';
import { 走廊局 } from './测试辅助';
import type { 天气名 } from './类型';

const 十二种 = Object.keys(天气概率) as 天气名[];

describe('判据 29~40 · Twelve 天气逐个（每种一行）', () => {
  const 清单: [天气名, number][] = [
    ['晴朗', 29], ['阴天', 30], ['小雨', 31], ['暴雨', 32],
    ['高温', 33], ['酷热', 34], ['寒潮', 35], ['严寒', 36],
    ['浓雾', 37], ['重雾', 38], ['灰烬风', 39], ['灰烬风暴', 40],
  ];
  for (const [天气, 编号] of 清单) {
    it(`${编号} ${天气}：每格消耗 = 15 + 天气加成 + 路况0`, () => {
      const 状态 = 走廊局();
      状态.当前天气 = 天气;
      const 消耗 = 每格消耗(状态, 1);
      expect(消耗).toBe(每格基准消耗 + 每格加成(天气) + 0);
      expect(消耗).toBeGreaterThanOrEqual(每格基准消耗);      // §5.1：消耗只升不降
    });
  }
});

describe('天气表本身（§1.3 照抄 5A §2.2）', () => {
  it('12 种天气名一个不多一个不少，概率合计 = 1.00', () => {
    expect(十二种.length).toBe(12);
    expect(十二种).toEqual(['晴朗', '阴天', '小雨', '暴雨', '高温', '酷热',
      '寒潮', '严寒', '浓雾', '重雾', '灰烬风', '灰烬风暴']);
    const 合计 = 十二种.reduce((累, 天) => 累 + 天气概率[天], 0);
    expect(合计).toBeCloseTo(1.0, 10);
  });

  it('天气段长与 5A §2.1 一致：普通 5-7 / 特殊 3-6 / 灰烬风 4-5 / 灰烬风暴 2-3', () => {
    expect(天气段长['晴朗']).toEqual([5, 7]);
    expect(天气段长['阴天']).toEqual([5, 7]);
    for (const 天 of ['小雨', '暴雨', '高温', '酷热', '寒潮', '严寒', '浓雾', '重雾'] as 天气名[]) {
      expect(天气段长[天], 天).toEqual([3, 6]);
    }
    expect(天气段长['灰烬风']).toEqual([4, 5]);
    expect(天气段长['灰烬风暴']).toEqual([2, 3]);
  });

  it('随机源可注入：给定同一个骰子值 → 掷出同一种天气', () => {
    expect(掷天气段(() => 0.0)).toBe(掷天气段(() => 0.0));
    expect(掷天气段(() => 0.0)).toBe('晴朗');
    expect(掷天气段(() => 0.995)).toBe('灰烬风暴');
  });
});

describe('判据 41~42 · 加成区分度 / 到期重掷', () => {
  it.skip('41 同一份代码：指定晴朗 vs 指定暴雨 → 扣的点必须不同', () => {
    // 🔴 必然失败：天气每格加成待项目主裁定（施工图 §6.1），现在两种都是 0。
    // 🔴 不许改成 toBe(0)、不许删 —— 裁定之后去掉 .skip，这条就是验收线。
    const 晴 = 走廊局(); 晴.当前天气 = '晴朗';
    const 暴 = 走廊局(); 暴.当前天气 = '暴雨';
    const 差异 = Math.abs(每格消耗(暴, 1) - 每格消耗(晴, 1));
    expect(差异).toBeGreaterThan(0);
  });

  it('42 天气段剩余 1 天时跨日 → 剩余天数重掷成新一段的值', () => {
    const 状态 = 走廊局();
    状态.当前天气 = '晴朗';
    状态.天气剩余天数 = 1;
    跨日(状态);
    const [小, 大] = 天气段长[状态.当前天气];
    expect(状态.天气剩余天数).toBeGreaterThanOrEqual(小);
    expect(状态.天气剩余天数).toBeLessThanOrEqual(大);
  });

  it('天气段没到期时跨日只是 −1，不重掷（天气名不变）', () => {
    const 状态 = 走廊局();
    状态.天气剩余天数 = 5;
    推进天气段(状态, () => 0.99);
    expect(状态.天气剩余天数).toBe(4);
    expect(状态.当前天气).toBe('晴朗');
  });
});
