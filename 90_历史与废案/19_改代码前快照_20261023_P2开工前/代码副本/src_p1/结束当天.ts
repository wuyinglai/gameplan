import { 跨日 } from './结算';
import type { 操作结果, 游戏状态 } from './类型';

export function 结束当天(状态: 游戏状态): 操作结果 {
  // ✍️ 2026-10-23 项目主裁定：玩家主动点「结束当天」🔴 任何时候都必须生效 ——
  //    原地站着连着点，就该连着过第 2、3、4 天（判据 26/27「不许卡死玩家」的精神，这里推到底）。
  //    施工图判据 24/25「第二次要点被拒」作废，留痕见
  //    AI交流\项目主裁定_到19点不自动跨日_20261023.md。
  //    自动跨日取消后，跨日() 里那个 今天已结算 保险丝只用来防「同一次调用链里触发两次」，
  //    所以这里先清标记再跨日；它不再用来拒绝玩家第二次的主动指令。
  状态.今天已结算 = false;
  跨日(状态);
  return { 成功: true, 原因: null };
}
