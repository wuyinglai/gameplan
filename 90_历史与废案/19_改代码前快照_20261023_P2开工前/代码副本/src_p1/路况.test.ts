import { describe, it, expect } from 'vitest';
import { 加载地图, 查格 } from './地图';
import { 每格消耗, 路况加成 } from './消耗';
import { 每格加成 } from './天气';
import { 每格基准消耗 } from './体力';
import { 走廊局 } from './测试辅助';
import type { 路况档 } from './类型';

const 造图 = (清单: { t: string; x: number; y: number; r?: number }[], 宽 = 20) => 加载地图({
  map: { width: 宽, height: 宽 }, start: [1, 1], end: [宽 - 2, 宽 - 2], locations: 清单,
});

describe('判据 43~45 · 三档逐个（每档一行）', () => {
  const 档: [路况档, number][] = [[0, 43], [1, 44], [2, 45]];
  for (const [路况, 编号] of 档) {
    it(`${编号} r=${路况}：每格消耗 = 15 + 天气加成 + 路况加成[${路况}]`, () => {
      const 状态 = 走廊局();
      expect(每格消耗(状态, 路况)).toBe(每格基准消耗 + 每格加成(状态.当前天气) + 路况加成[路况]);
    });
  }
});

describe('判据 46~48 · 区分度 / 缺省 / 恶劣', () => {
  it.skip('46 同一份代码读 r=0 和 r=2 → 扣的点必须不同', () => {
    // 🔴 必然失败：路况四档加成待项目主裁定（施工图 §6.2 完全查不到），现在四档全 0。
    // 🔴 不许改成 toBe(0)、不许删 —— 裁定之后去掉 .skip。
    const 状态 = 走廊局();
    expect(Math.abs(每格消耗(状态, 2) - 每格消耗(状态, 0))).toBeGreaterThan(0);
  });

  it('47 没标 r 的格子 → 当作 r=1 普通', () => {
    const 图 = 造图([{ t: 'big', x: 1, y: 1 }, { t: 'road', x: 2, y: 1 }]);
    expect(查格(图, 2, 1).路况).toBe(1);
  });

  it('47之二 r 是脏值（7）→ 按普通 + 不停机', () => {
    const 警告 = console.warn;
    let 打了几次 = 0;
    console.warn = (() => { 打了几次 += 1; }) as typeof console.warn;
    try {
      expect(查格(造图([{ t: 'road', x: 3, y: 3, r: 7 }]), 3, 3).路况).toBe(1);
    } finally {
      console.warn = 警告;
    }
    expect(打了几次).toBe(1);
  });

  it('48 r=3 恶劣：本图 0 格 → 用构造数据测', () => {
    const 图 = 造图([{ t: 'road', x: 5, y: 5, r: 3 }]);
    expect(查格(图, 5, 5).路况).toBe(3);
    const 状态 = 走廊局();
    expect(每格消耗(状态, 3)).toBe(每格基准消耗 + 每格加成(状态.当前天气) + 路况加成[3]);
  });
});

describe('判据 49 · 不许断言「路 A 天数少但消耗高」', () => {
  it('49 体力是唯一的账：任何 (天气, 路况) 组合都不会让消耗跌破基准', () => {
    // 🔴 这条取代旧判据「路 A 天数少但消耗高」—— 单一资源池驱动两个轴，
    //    数学上不可能同时成立（施工图 §5.5 第 49 行 / 旧文档已作废）。
    const 状态 = 走廊局();
    for (const 路况 of [0, 1, 2, 3] as 路况档[]) {
      expect(每格消耗(状态, 路况)).toBeGreaterThanOrEqual(每格基准消耗);
    }
  });

  it('49之二 真图上的 r 分布读得出来（3,209 格 r=2、0 格 r=3）', () => {
    const 状态 = 走廊局();
    void 状态;
    const 真 = 加载地图(JSON.parse(JSON.stringify({
      map: { width: 20, height: 20 }, start: [1, 1], end: [2, 2],
      locations: [{ t: 'road', x: 1, y: 1, r: 0 }, { t: 'road', x: 2, y: 2, r: 2 }],
    })));
    expect([查格(真, 1, 1).路况, 查格(真, 2, 2).路况]).toEqual([0, 2]);
  });
});
