/**
 * 🔴 天气段推进：剩余 −1，归零则重掷（写回 当前天气 与 剩余天数）。
 *    判据 42：剩余 1 天时跨日 → 剩余天数变成新一段的值（天气名可同可不同）。
 */
export function 推进天气段(状态: 游戏状态, 随机源: () => number = Math.random): void {
  状态.天气剩余天数 -= 1;
  if (状态.天气剩余天数 > 0) return;
  状态.当前天气 = 掷天气段(随机源);
  状态.天气剩余天数 = 掷区间(天气段长[状态.当前天气], 随机源);
}
