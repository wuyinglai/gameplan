import type { 天气名, 游戏状态 } from './类型';

/** 🔴 基础概率 —— 照抄 5A §2.2。合计 0.68（正常）+ 0.32（特殊）= 1.00 */
export const 天气概率: Record<天气名, number> = {
  晴朗: 0.34, 阴天: 0.34,
  小雨: 0.05, 暴雨: 0.03,
  高温: 0.05, 酷热: 0.02,
  寒潮: 0.05, 严寒: 0.02,
  浓雾: 0.05, 重雾: 0.02,
  灰烬风: 0.02, 灰烬风暴: 0.01,
};

/** 🔴 天气段持续天数 —— 照抄 5A §2.1（第 95–96 行与第 798 行，逐字对上）：
 *    普通天气（晴朗、阴天）5–7 天 · 特殊天气（小雨/暴雨/高温/酷热/寒潮/严寒/浓雾/重雾）3–6 天
 *    灰烬风 4–5 天 · 灰烬风暴 2–3 天 */
export const 天气段长: Record<天气名, [number, number]> = {
  晴朗: [5, 7], 阴天: [5, 7],
  小雨: [3, 6], 暴雨: [3, 6], 高温: [3, 6], 酷热: [3, 6],
  寒潮: [3, 6], 严寒: [3, 6], 浓雾: [3, 6], 重雾: [3, 6],
  灰烬风: [4, 5], 灰烬风暴: [2, 3],
};

const 天气清单 = Object.keys(天气概率) as 天气名[];

/// 掷一个 [最小, 最大] 闭区间内的整数（含端点）
function 掷区间(区间: [number, number], 随机源: () => number): number {
  const [小, 大] = 区间;
  const 幅度 = 大 - 小 + 1;
  const 落点 = Math.floor(随机源() * 幅度);
  return 小 + Math.min(幅度 - 1, Math.max(0, 落点));
}

/** 🔴 掷一个天气段。🔴 随机源可注入 —— 测试不许靠骰子撞想要的结果（验收规范规矩 4） */
export function 掷天气段(随机源: () => number = Math.random): 天气名 {
  const 骰 = 随机源();
  let 累计 = 0;
  for (const 天 of 天气清单) {
    累计 += 天气概率[天];
    if (骰 < 累计) return 天;
  }
  return 天气清单[天气清单.length - 1];   // 浮点误差兜底：落到最后一种
}

