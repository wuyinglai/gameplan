import { 加载地图 } from './地图';
import { 新建游戏状态, type 游戏状态 } from './状态';
import { 走一格 } from './移动';
import { 结束当天 } from './结束当天';
import 地图json from './地图.json';

export function 描述(标签: string, 状态: 游戏状态): string {
  const { x, y } = 状态.当前坐标;
  return (
    `  ${标签}：第 ${状态.第几天} 天 ${String(状态.当前小时).padStart(2, '0')}:00` +
    `  位置 (${x}, ${y})  体力 ${状态.野外体力} / ${状态.体力上限}`
  );
}

/// 往东走一格，把结果打成中文（🔴 走不了也要让项目主看得见原因）
function 试着走(状态: 游戏状态, 标签: string): string {
  const 目标x = 状态.当前坐标.x + 1;
  const 结果 = 走一格(状态, 目标x, 状态.当前坐标.y);
  if (!结果.成功) return `  ${标签}：❌ 走不了 —— ${结果.原因}`;
  return `  ${标签}：✅${描述('现在', 状态)}`;
}

export function 演示(): void {
  const 地图 = 加载地图(地图json);
  const 状态 = 新建游戏状态(地图);

  console.log('\n╔══════════════════════════════════════════════════════════════╗');
  console.log('║  《余烬商队》P1 演示 —— 1.3 地图与移动（真地图 · 真判断）        ║');
  console.log('╚══════════════════════════════════════════════════════════════╝\n');
  console.log(`  地图：${地图.宽} × ${地图.高} 共 ${地图.宽 * 地图.高} 格 · json 标注了 ${地图.格子表.size} 格`);
  console.log(`  起点 (${地图.起点.x}, ${地图.起点.y}) → 终点 (${地图.终点.x}, ${地图.终点.y})\n`);
  console.log('【开始】');
  console.log(描述('状态', 状态));

  console.log('\n【往东走四格】');
  for (let 步 = 1; 步 <= 4; 步 += 1) {
    console.log(试着走(状态, `第 ${步} 步`));
  }

  const 第一次 = 结束当天(状态);
  console.log(`\n【结束当天】${第一次.成功 ? '✅ 跨到第二天' : '❌ ' + 第一次.原因}`);
  console.log(描述('状态', 状态));
  const 第二次 = 结束当天(状态);
  console.log(
    `【立刻再点一次】${第二次.成功 ? '🔴 不该成功（幂等破了）' : `✅ 被拒：${第二次.原因}`} —— 判据 25`,
  );
  console.log('\n');
}
