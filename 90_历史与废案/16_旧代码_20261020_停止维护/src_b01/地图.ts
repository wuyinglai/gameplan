// ---------------------------------------------------------------------------

/// 按坐标查一格。
/// 🔴 地图范围外 → **抛错**（不许当成空地返回）。
/// 🔴 范围内但 json 没列出 → 返回默认格子（空地 · 普通 · 未到访），**不写进表**。
export function 查格(地图: 地图对象, x: number, y: number): 格子 {
  校验坐标(地图, x, y);
  return 地图.格子表.get(坐标key(x, y)) ?? 默认格子(x, y);
}

/// 🔴 把任意一格改成别的类型 —— 项目主要求的能力：
///    「可以先是一张 400×400 全空的图，但要有把空格改成其他格的能力」。
///    会写进格子表（覆盖原值）；路况档与地点名可省。
export function 设格(
  地图: 地图对象,
  x: number,
  y: number,
  类型: 格子类型,
  新路况: 路况档 = '普通',
  地点名: string | null = null,
): 格子 {
  校验坐标(地图, x, y);
  const 新格: 格子 = {
    坐标: { x, y },
    类型,
    路况档: 新路况,
    地点名,
    已到访: false,
    信息等级: 起始信息等级,
  };
  地图.格子表.set(坐标key(x, y), 新格);
  return 新格;
}

export function 校验坐标(地图: 地图对象, x: number, y: number): void {
  if (!是整数(x) || !是整数(y)) {
    throw new Error(`坐标必须是整数，收到 ${String(x)},${String(y)}`);
  }
  if (x < 0 || x >= 地图.宽 || y < 0 || y >= 地图.高) {
    throw new Error(
      `坐标越界：${x},${y}（地图 ${地图.宽}×${地图.高}，有效 0..${地图.宽 - 1} / 0..${地图.高 - 1}）`,
    );
  }
}
