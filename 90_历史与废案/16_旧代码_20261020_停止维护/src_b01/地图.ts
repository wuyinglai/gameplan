// ---------------------------------------------------------------------------
// 一、类型定义（照抄施工图 §3.5.1，字段不许增删）
// ---------------------------------------------------------------------------

// 🔴 山/水/桥/林/废墟 必须是**顶层枚举值**，不许折进一个叫「地形」的笼统值。
//    （折进去以后 `不可通行类型.has(格.类型)` 恒等于 false —— 山和水谁也拦不住）
export type 格子类型 =
  | '空地'
  | '山' | '水'                 // 🔴 不可通行
  | '桥' | '林' | '废墟'        // 🔴 可通行（废墟本轮按可通行处理）
  | '商路'
  | '大城' | '小城' | '城镇' | '驿站' | '村庄' | '营地';

export type 路况档 = '好' | '普通' | '差' | '恶劣';

export interface 格子 {
  坐标: { x: number; y: number };
  类型: 格子类型;
  路况档: 路况档;
  地点名: string | null;        // 只有地点类才有名字
  已到访: boolean;              // 🔴 记的是「玩家实际到没到过」，不是「能不能看见」
  信息等级: number;             // 🔴 本轮没人读它（主动侦察归单元 04），只是随格存着
}

// 🔴 下面两个集合里的值必须**都在上面的枚举里**。
//    写了枚举外的值 = 静默失效（比报错更坏）—— 防退化断言见 地图.test.ts 第 5 条。
export const 不可通行类型: ReadonlySet<格子类型> = new Set<格子类型>(['山', '水']);

// 可停留 = 走进就算「抵达」；进城买东西是单元 02
export const 可停留类型: ReadonlySet<格子类型> = new Set<格子类型>(
  ['大城', '小城', '城镇', '驿站', '村庄', '营地'],
);

/// 🔴 枚举的全部取值 —— 专供防退化断言遍历（防「集合里写了枚举外的值 = 静默失效」）
export const 全部格子类型: readonly 格子类型[] = [
  '空地', '山', '水', '桥', '林', '废墟', '商路',
  '大城', '小城', '城镇', '驿站', '村庄', '营地',
];

const 合法类型名: ReadonlySet<string> = new Set<string>(全部格子类型);

/// 是否可通行 / 是否可停留 —— 🔴 全项目只认这两个函数，别处不许自己比字符串
export function 可通行(格: 格子): boolean {
  return !不可通行类型.has(格.类型);
}

export function 可停留(格: 格子): boolean {
  return 可停留类型.has(格.类型);
}

// ---------------------------------------------------------------------------
// 二、地图 json 的格式契約
// ---------------------------------------------------------------------------

/** json 里每条记录长这样：`t` 必填、`x`/`y` 必填、`r` 可省（省 = 普通） */
interface 地图条目 {
  t: string;
  x: number;
  y: number;
  r?: number;
}

interface 地图文件形状 {
  map: { width: number; height: number };
  note?: string;
  start: [number, number];      // 🔴 起点（本轮 = A 大城）
  end: [number, number];        // 🔴 终点（本轮 = B 小城）
  locations: 地图条目[];
}

/** 类型键 → 中文枚举（指令 §四.3① 那张全表，含旧键自动转）。
 *   🔴 表里没有、且本身也不是合法枚举名的键 → **抛错**，不许静默跳过。 */
const 类型键映射: Readonly<Record<string, 格子类型>> = {
  big: '大城',
  small: '小城',
  town: '城镇',
  village: '村庄',
  inn1: '驿站',
  inn0: '驿站',                 // 旧键
  camp: '营地',
  special: '营地',              // 🔴 见下方「两处特殊说明」
  road: '商路',
  blk_fr: '桥',
  block: '山',
  blk_mt: '山',                 // 旧键
  blk_wt: '水',
  blk_ru: '废墟',               // 🔴 见下方「两处特殊说明」
};

// 🔴 「两处特殊说明」（Hermes 2026-10-19 · 指令 §四.3① 原文自相矛盾，已就地修正）
//    ① `blk_ru`：表格那行写「废墟」、正文那行写「桥」——两个目标值。
//       这里取**表格值「废墟」**：同一节里「废墟本轮按可通行处理」与本表「可通行 ✅」互相
//       印证，而「桥」没有任何印证。改动已在 AI交流 指令文件里署名留痕，等 WorkBuddy 复核。
//    ② `special` → `'营地'` 之后，表格却又标「可停留 ❌」——**结构上做不到**：
//       可停留是按**类型**判的（`可停留类型.has(格.类型)`），营地必然可停留。
//       真要「能走进但不停留」，得给它独立枚举值，而那属于 A 类 `1A §4`，B 类不许自创。
//       本轮按「营地」实现（= 可停留），已在指令文件里署名标注。

/// 解析一个 `t` 值。
/// 🔴 除了上面那张表，还接受**本身就是枚举名的键**：实测夹具直接写 `t: "空地"`（189 条），
///    中文名与施工图 §3.5.1 逐字相同，不算自创。（指令的全表原先漏了这一行，已补）
function 取格子类型(键: string): 格子类型 | undefined {
  const 显式 = 类型键映射[键];
  if (显式 !== undefined) return 显式;
  return 合法类型名.has(键) ? (键 as 格子类型) : undefined;
}

export interface 坐标 {
  x: number;
  y: number;
}

export interface 地图对象 {
  宽: number;
  高: number;
  起点: 坐标;                   // 🔴 来自 json 顶层 start
  终点: 坐标;                   // 🔴 来自 json 顶层 end
  /// key = `${x},${y}`
  格子表: Map<string, 格子>;
}

export function 坐标key(x: number, y: number): string {
  return `${x},${y}`;
}

/// 起始信息等级 = 1（施工图 §6.2 测试参数表；本轮没人读它）
const 起始信息等级 = 1;

/// 一张地图里「没被列出」的格子长这样：空地 · 路况普通 · 没名字 · 没到过。
/// 🔴 依据：指令 §四.3③「坐标超出地图范围 → 抛错」—— 反过来说，**地图范围内**
///    没列出的格子就是空地。夹具只列了一小部分（4254 / 160000）。
function 默认格子(x: number, y: number): 格子 {
  return {
    坐标: { x, y },
    类型: '空地',
    路况档: '普通',
    地点名: null,
    已到访: false,
    信息等级: 起始信息等级,
  };
}

/// 🔴 路况档只认 json 里的 `r`（指令 §四.3②）：不给 → 普通；0好 1普通 2差 3恶劣；
///    **0~3 之外 → 按普通处理 + 打警告（不许抛错）**。
/// 🔴 不许自己定「商路=好、其余=普通」—— 那是自创，只认 `r`。
export function 解析路况(r: unknown, 说明: string): 路况档 {
  if (r === undefined || r === null) return '普通';
  switch (r) {
    case 0: return '好';
    case 1: return '普通';
    case 2: return '差';
    case 3: return '恶劣';
  }
  console.warn(`⚠️ 路况 r 不在 0~3（收到 ${String(r)}，${说明}）—— 按「普通」处理`);
  return '普通';
}

// ---------------------------------------------------------------------------
// 三、加载
// ---------------------------------------------------------------------------

function 是整数(v: unknown): v is number {
  return typeof v === 'number' && Number.isInteger(v);
}

function 是坐标对(v: unknown): v is [number, number] {
  return Array.isArray(v) && v.length === 2 && 是整数(v[0]) && 是整数(v[1]);
}

/// 把地图 json（已解析的对象）转成地图对象。
/// 🔴 必须抛错：形状不对 / 缺尺寸 / 缺 start 或 end / 未知键 / 坐标越界
/// 🔴 只打警告：`r` 越界、同坐标重复
export function 加载地图(原始: unknown): 地图对象 {
  if (typeof 原始 !== 'object' || 原始 === null) {
    throw new Error('地图数据形状不对：顶层不是对象');
  }
  const 文件 = 原始 as Partial<地图文件形状>;
  const 宽 = 文件.map?.width;
  const 高 = 文件.map?.height;
  if (!是整数(宽) || !是整数(高) || (宽 as number) <= 0 || (高 as number) <= 0) {
    throw new Error('地图数据缺尺寸：应有 map.width / map.height 两个正整数');
  }
  if (!Array.isArray(文件.locations)) {
    throw new Error('地图数据缺 locations 数组');
  }
  if (!是坐标对(文件.start)) {
    throw new Error('地图数据缺 start：应是 [x, y] 两个整数 —— 代码要知道从哪出发');
  }
  if (!是坐标对(文件.end)) {
    throw new Error('地图数据缺 end：应是 [x, y] 两个整数 —— 代码要知道走到哪');
  }

  const 宽数 = 宽 as number;
  const 高数 = 高 as number;
  const 格子表 = new Map<string, 格子>();

  const 校验在范围内 = (x: number, y: number, 说明: string): void => {
    if (!是整数(x) || !是整数(y)) {
      throw new Error(`坐标不是整数：${说明} @ ${String(x)},${String(y)}`);
    }
    if (x < 0 || x >= 宽数 || y < 0 || y >= 高数) {
      throw new Error(
        `坐标越界：${说明} @ ${x},${y}（地图 ${宽数}×${高数}，有效 0..${宽数 - 1} / 0..${高数 - 1}）`,
      );
    }
  };

  校验在范围内(文件.start[0], 文件.start[1], 'start');
  校验在范围内(文件.end[0], 文件.end[1], 'end');

  for (const 条 of 文件.locations) {
    const 说明 = `坐标 ${条.x},${条.y}`;
    const 类型 = 取格子类型(条.t);
    if (类型 === undefined) {
      throw new Error(
        `未知类型键 "${条.t}"（${说明}）—— 既不在「类型键映射」里，也不是合法的格子类型名。` +
        `请先补映射表，不许静默跳过。`,
      );
    }
    校验在范围内(条.x, 条.y, 条.t);

    const key = 坐标key(条.x, 条.y);
    const 新格: 格子 = {
      坐标: { x: 条.x, y: 条.y },
      类型,
      路况档: 解析路况(条.r, `${条.t} @ ${条.x},${条.y}`),
      地点名: null,
      已到访: false,
      信息等级: 起始信息等级,
    };

    const 已有 = 格子表.get(key);
    if (已有 !== undefined) {
      // 🔴 Gap 7 裁定（指令② §一.3）：同坐标重复 → **地点类优先 + 丢弃其余 + 警告**（不抛错）。
      //    本轮「商路只标记、不结算」，所以这条裁定对本单元的正确性零影响。
      const 保留新的 = 可停留类型.has(类型) && !可停留类型.has(已有.类型);
      console.warn(
        `⚠️ 同一格被列了两次：${key}（已有 ${已有.类型} ↔ 又来 ${条.t}→${类型}）` +
        `—— 按「地点类优先」保留「${保留新的 ? 类型 : 已有.类型}」`,
      );
      if (!保留新的) continue;
    }
    格子表.set(key, 新格);
  }

  return {
    宽: 宽数,
    高: 高数,
    起点: { x: 文件.start[0], y: 文件.start[1] },
    终点: { x: 文件.end[0], y: 文件.end[1] },
    格子表,
  };
}

