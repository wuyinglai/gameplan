// ============================================================================
// 单元 01 · 结束当天（防卡死的兜底操作）
//
// 依据：指令② 二.5 · 施工图 §3.5.4 规则三
// 🔴 独立操作，不碰移动：不许改坐标、不许扣移动体力、不许额外推进 2 小时。
///   它做的**唯一一件事**就是调 结算.跨日()。
//
// 🔴 幂等口径（2026-10-19 WorkBuddy 修正）：
//    原判据是「当前小时 > 07:00 才可用」—— 🔴 **错在开局 07:00 用不了**，
//    而那恰恰是最需要它的时候（一步都走不动、体力耗尽、刚开局）。
//    现在改成显式的「今天是否已经结算过」标记，🔴 与小时数无关。
// ============================================================================

import type { 游戏状态 } from './状态';
import { 跨日 } from './结算';

export interface 操作结果 {
  成功: boolean;
  原因: string | null;
}

/// 今天是不是已经结算过了（🔴 开局为 false，跨日时置 true）
// 🔴 这个标记只由 结算.跨日() 写 —— 别处写它就等于出现了第二个跨日入口。
function 今天已结算(状态: 游戏状态): boolean {
  return 状态.今天已结算;
}

/// 🔴 「结束当天」是**永远合法**的操作（施工图 §3.5.4 规则三）
///   —— 唯一不可用的情形是：今天已经结算过了（那就没有"今天"可结束）。
///
/// 🔴 幂等保护（施工图 §3.5.4 规则三第 6 条）：
///   19:00 已自动跨日后再调「结束当天」→ **不得再跨一次**。
///   本轮（指令②）唯一会触发跨日的移动是「走一格」，且走完一格必推进 2 小时，
///   因此**今天已经推进过任何时间 = 今天已经结算过**（走到 19:00 那一刻就跨了）。
export function 结束当天可用(状态: 游戏状态): boolean {
  return !今天已结算(状态);
}

/// 直接跳到第二天早上。🔴 除了 跨日() 什么都不做。
export function 结束当天(状态: 游戏状态): 操作结果 {
  if (!结束当天可用(状态)) {
    return {
      成功: false,
      原因: '今天已经结算过了，没有可结束的这一天 —— 若刚自动跨日，说明这一步已经做过了',
    };
  }
  跨日(状态);
  return { 成功: true, 原因: null };
}