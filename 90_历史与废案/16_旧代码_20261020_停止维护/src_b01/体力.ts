//
// 依据：施工图 §2.1 / §3.6（体力.py）
// 🔴 只管「够不够 / 扣 / 每日回复」三件事，不管谁触发、不管扣完发生什么。
// 🔴 【每日回复只许 结算.跨日() 调用】—— 主循环里再回一次就是本单元最容易出的 bug。
// ============================================================================

import type { 游戏状态 } from './状态';

export const 每日回复量 = 50;   // 施工图 §2.1：每天 +50

/// 够不够花这么多点（不许欠体力硬走）
export function 够不够(状态: 游戏状态, 点数: number): boolean {
  return 点数 >= 0 && 状态.野外体力 >= 点数;
}

/// 扣体力。🔴 不够就返回 false 且**什么都不扣**（拒绝时不消耗任何东西）。
export function 扣(状态: 游戏状态, 点数: number): boolean {
  if (!够不够(状态, 点数)) return false;
  状态.野外体力 -= 点数;
  return true;
}

/// 每日回复：+50，🔴 封顶在 体力上限（恒 100），永远不会超过。
/// 🔴 全项目只有 结算.跨日() 调它 —— 别处出现第二次调用就是重复结算。
export function 每日回复(状态: 游戏状态): void {
  状态.野外体力 = Math.min(状态.体力上限, 状态.野外体力 + 每日回复量);
}
